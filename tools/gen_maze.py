"""Собирает `app/public/images/veroyatnost/labirint-glass.svg`.

Весь стиль — в `glass_style.py`. Здесь только данные картинки: стены,
подписи, блёстки и паук.

    python3 tools/gen_maze.py

ВНИМАНИЕ. `RECTS` и координаты проёмов сверены с оригиналом задачи —
от них зависит правильный ответ. Менять их нельзя.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from glass_style import P, kartinka  # noqa: E402

VYHOD = Path(__file__).resolve().parents[1] / 'app/public/images/veroyatnost/labirint-glass.svg'

COLS, ROWS = 54, 44

# Стены в мелких клетках: (c0, c1, r0, r1) включительно, снято с
# пиксельного скана оригинала.
RECTS = [
    (0, 23, 0, 3), (30, 53, 0, 3),        # верхняя стена, проём = Выход D
    (0, 3, 10, 13), (0, 3, 20, 43),       # левая стена: проём 4–9 = Выход B, 14–19 = Вход
    (50, 53, 10, 43),                     # правая стена: проём 4–9 = Выход A
    (0, 43, 40, 43),                      # нижняя стена, проём 44–49 = Выход C
    (20, 23, 4, 13),                      # вертикаль от верха
    (10, 13, 10, 23),                     # вертикаль слева внутри
    (30, 51, 10, 13),                     # длинная горизонталь справа
    (10, 33, 20, 23), (40, 51, 20, 23),   # второй ряд
    (30, 33, 20, 29),                     # короткая вертикаль
    (10, 43, 30, 33),                     # третий ряд
    (40, 43, 30, 41),                     # вертикаль вниз
]

LABELS = [
    ('Вход', P(-1.2, 17), 'end'),
    ('Выход B', P(-1.2, 7), 'end'),
    ('Выход D', P(27, -2.2), 'middle'),
    ('Выход A', P(55.2, 7), 'start'),
    ('Выход C', P(47, 46.6), 'middle'),
]

SPARKS = [
    (0, 0), (53, 0), (24, 0), (30, 0), (20, 13), (0, 43),
    (43, 43), (50, 43), (30, 29), (40, 30), (10, 23), (50, 10),
]

# Паук стоит во входном коридоре.
SPIDER = (2, 17)

if __name__ == '__main__':
    svg = kartinka(RECTS, LABELS, COLS, ROWS, sparks=SPARKS, spider=SPIDER)
    VYHOD.write_text(svg, encoding='utf-8')
    print(f'{VYHOD} — {len(svg)} байт')
