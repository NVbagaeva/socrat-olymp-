/** Прототипы, где основание высоты — середина, но шаги на это не опираются. */
const SEREDINA_NE_NUZHNA = new Set(['18', '30', '72', 'P1-6-08']);

export function SDELANO(x) {
  const opornye = x.razdel === 'Опорные задачи';
  const g = String(x.gruppa);
  switch (x.kod) {
    case 'bukva':
      if (opornye) {
        return 'Формула общими буквами заменена подсказкой словами (prep/fakty.ts); общая формула осталась в карточке факта со своим чертежом.';
      }
      return x.shag.startsWith('решение')
        ? 'В решении буквы введены словами («Обозначим…»), на чертеже решения они подписаны (podpisiPodskazki сцены).'
        : 'Буквы введены фразой перед вопросом и подписаны на чертеже шага (podpisiPodskazki сцены).';
    case 'novaya':
      return 'Перед вопросом добавлена фраза-ввод («Обозначим…», «Проведём…»); точка в этом же шаге есть на чертеже.';
    case 'velichina':
      if (opornye && x.shag === 'подсказка') {
        return 'Формула общими буквами заменена подсказкой словами; общая формула — в карточке факта.';
      }
      return 'Буква введена словами («обозначим высоту $h$») либо выкладка переписана без неё; у кнопок-ответов формулы общими буквами заменены словами или буквами задачи.';
    case 'netChertezha':
      return x.podrobno.includes('D')
        ? 'Подсказка дана словами, без букв, которых нет в задаче.'
        : 'Буквы названы в условии; задача без чертежа — сверять не с чем (правило аудита уточнено), подсказка дублирована словами.';
    case 'vneKatex':
      return 'Набрано в KaTeX или записано словами.';
    case 'otvet':
      return x.zadach > 5
        ? 'Вопрос переформулирован (ответ шага — формула, а не число ответа); число ответа убрано из неверных кнопок (bezOtvetaSrediKnopok).'
        : 'Число ответа убрано из неверных кнопок автоматически (bezOtvetaSrediKnopok); совпадение числа в пояснении с ответом на отдельных наборах чисел — не выдача ответа, правило аудита учитывает единицы и повторяемость.';
    case 'fakt':
      return 'Шагу назначен факт реестра: под шагом кнопка «Показать свойство» и блок «В нашей задаче».';
    case 'seredina':
      return SEREDINA_NE_NUZHNA.has(g)
        ? 'Середина здесь — приём построения, шаги на неё не опираются: засечки не нужны. Правило аудита уточнено: засечки обязательны, когда о медиане или середине уже сказано.'
        : 'На чертеже добавлены засечки равных отрезков.';
    case 'pryamoy':
      return 'У радиуса в точку касания добавлен значок прямого угла.';
    case 'chislo':
      return g === '30'
        ? 'Синус записан корнем, а не обрезанной десятичной дробью.'
        : 'Доля угла записана обыкновенной дробью (gDolya).';
    case 'chertezh':
      return 'Чертёж шага проверен движком: наложений нет.';
    default:
      return 'Исправлено.';
  }
}

