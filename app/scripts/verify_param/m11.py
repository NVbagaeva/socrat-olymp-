def t5(a):  # x² − 2ax + 3 ≤ 0 имеет хотя бы одно решение на [0; 1]
    return hot_raz(kv(1, -2 * a, 3), na_otrezke(0, 1, (a,)), "<=")


def t6(a):  # система x² − 4x + a ≤ 0, x ≤ 1 имеет хотя бы одно решение
    return hot_raz(kv(1, -4, a), na_luche(1, False, (2,)), "<=")


def t7(a):  # x² − 2ax + 2a² − 4a ≤ 0: множество решений — отрезок длины 2√3
    L = otrezok(kuski(kv(1, -2 * a, 2 * a * a - 4 * a), "<=", (a,)))
    return L is not None and abs(L - 2 * np.sqrt(3)) < 1e-7


def t8(a):  # ax² − 2x + 1 > 0 при всех x ∈ [2; 3]
    A, B = a, -2
    return vsegda(kv(A, B, 1), na_otrezke(2, 3, vershina(A, B)), ">")


def t9(a):  # x² − 2ax + 2a + 3 ≤ 0 имеет решения, и все они на [0; 4]
    f = kv(1, -2 * a, 2 * a + 3)
    # Плотная сетка около отрезка (шаг 2·10⁻⁵): корень, вышедший за конец
    # на тысячные, сеткой не теряется; дальше — вся прямая.
    x = np.unique(np.concatenate((na_pryamoy((a, 0, 4)), np.linspace(-2, 6, 400_001))))
    s = x[gde(f, x, "<=")]
    return s.size > 0 and bool(s.min() >= -1e-9) and bool(s.max() <= 4 + 1e-9)


def t10(a):  # (a − 3)x² + 2(a − 2)x + a − 1 ≥ 0: множество решений — отрезок длины не меньше 1
    A, B, C = a - 3, 2 * (a - 2), a - 1
    L = otrezok(kuski(kv(A, B, C), ">=", vershina(A, B)))
    return L is not None and L >= 1 - 1e-9


