"""Метод 8 «Метод оценки»: проверка разборов, опорных и тренировочных задач.

У каждой задачи — условие «как в тексте задачи», без оценок метода:
функция по параметру говорит, выполняется ли требование задачи.
Проверка — перебором по x:

  * «имеет решение» — по теореме о промежуточном значении: разность
    частей g непрерывна на промежутке, и корень есть, когда на густой
    сетке (с особыми точками) у g есть значения обоих знаков или нуль.
    Для уравнений, где части только касаются (сумма неотрицательных),
    это значит: наименьшее значение g на сетке — нуль с точностью 10⁻¹².
    Точки, где обе части могут коснуться (вершина параболы, нуль модуля,
    x = 0, концы области), проверяются точно — как x = 0 в m05.py: на
    сетке они тоже есть, точная подстановка лишь снимает ошибку
    округления в точке касания. Если значение параметра отстоит от
    найденного на 10⁻³, наименьшее значение g не меньше ~10⁻⁶ — его
    сетка не спутает с нулём;
  * «ровно одно решение» — счётом корней общим поиском (obshchee.korni):
    смена знака на сетке и касание (локальный минимум |g| около нуля).
    Около касания 1 − sin(πx/2) записано как 2 sin²(π(x − 1)/4), а
    свободный член — последним, как в m05.py: это тождества, а не шаги
    решения.

Область определения учитывается так: где g не определена (корень из
отрицательного, деление на нуль), сетки нет — промежутки области
проверяются отдельно.

NEVERNYE — заведомо неверные ответы: значения, при которых границы
оценок равны, но достигаются в разных точках; неточная оценка
(sin x + cos x ≤ 2); потерянная область; неравенство Коши без
отрицательных чисел. run.py требует, чтобы перебор каждый из них
опроверг.
"""

import math

import numpy as np

from obshchee import INF, korni

PI = math.pi
TOL = 1e-12


def setka(lo, hi, n=200_001, tochki=()):
    return np.concatenate((np.linspace(lo, hi, n), np.asarray(tochki, dtype=float)))


def znaki(g, x):
    """На сетке x у непрерывной g есть значения обоих знаков (или нуль): корень есть."""
    with np.errstate(all="ignore"):
        y = g(x)
    y = y[np.isfinite(y)]
    return bool(y.size and np.min(y) <= TOL and np.max(y) >= -TOL)


def koren_est(g, *promezhutki):
    """Хотя бы на одном промежутке области (сетке) у g есть корень."""
    return any(znaki(g, x) for x in promezhutki)


X_TRIG = setka(-2 * PI, 2 * PI, tochki=(0, PI / 4, PI / 2, -PI / 2, PI, -PI, 3 * PI / 4, 5 * PI / 4))


# ── Разборы ─────────────────────────────────────────────────────────


def r1(a):  # cos πx = x² − 2ax + 2a² − 4a + 5: хотя бы одно решение
    g = lambda x: x * x - 2 * a * x + 2 * a * a - 4 * a + 5 - np.cos(PI * x)
    return koren_est(g, setka(-10, 10, tochki=(a, 0, 1, 2, 3)))


def r2(a):  # √(x² − 5x + 4) + |x² − (a + 2)x + 2a| = 0: хотя бы одно решение
    g = lambda x: np.sqrt(x * x - 5 * x + 4) + np.abs(x * x - (a + 2) * x + 2 * a)
    return koren_est(g, setka(-10, 1, tochki=(1, a)), setka(4, 15, tochki=(4, a)))


def r3(a):  # 2^|x| + |a − 1| + |a − 3| = 2 + cos x: хотя бы одно решение
    g = lambda x: 2 ** np.abs(x) + abs(a - 1) + abs(a - 3) - 2 - np.cos(x)
    return koren_est(g, setka(-10, 10, tochki=(0,)))


# ── Опорные ─────────────────────────────────────────────────────────


def o1(a):  # sin x = a² − 3a + 3: решение
    return koren_est(lambda x: np.sin(x) - (a * a - 3 * a + 3), X_TRIG)


def o2(a):  # x + 1/x = a: решение (x ≠ 0 — два промежутка)
    g = lambda x: x + 1 / x - a
    return koren_est(g, setka(0.01, 100, tochki=(1,)), setka(-100, -0.01, tochki=(-1,)))


def o3(a):  # √x + √(2 − x) = a: решение
    g = lambda x: np.sqrt(x) + np.sqrt(2 - x) - a
    return koren_est(g, setka(0, 2, tochki=(0, 1, 2)))


def o4(a):  # |x − a| + |x + 1| ≤ 3: хотя бы одно решение
    x = setka(-20, 20, tochki=(a, -1))
    return bool(np.min(np.abs(x - a) + np.abs(x + 1)) <= 3 + TOL)


def o5(a):  # x² + 4x + 5 + |a − 1| = 1 − sin²(πx/2): решение
    g = lambda x: x * x + 4 * x + 5 + abs(a - 1) - (1 - np.sin(PI * x / 2) ** 2)
    return koren_est(g, setka(-10, 10, tochki=(-2, 0)))


# ── Тренировка ──────────────────────────────────────────────────────


def t1(a):  # 2^|x| + a² = cos x: решение
    return koren_est(lambda x: 2 ** np.abs(x) + a * a - np.cos(x), setka(-10, 10, tochki=(0,)))


def t2(a):  # cos x = a² − 3a + 1: решение
    return koren_est(lambda x: np.cos(x) - (a * a - 3 * a + 1), X_TRIG)


def t3(a):  # √(x − 1) + |a² − a − 2| + |x + a − 3| = 0: решение
    g = lambda x: np.sqrt(x - 1) + abs(a * a - a - 2) + np.abs(x + a - 3)
    return koren_est(g, setka(1, 20, tochki=(1, 3 - a)))


def t4(a):  # cos πx = (x − a)² + |a² − 3a| + 1: решение
    g = lambda x: (x - a) ** 2 + abs(a * a - 3 * a) + 1 - np.cos(PI * x)
    return koren_est(g, setka(-10, 10, tochki=(a, 0, 3)))


def t5(a):  # x² + 1/x² + (a − 1)² = 2 cos 2πx: решение (x ≠ 0)
    g = lambda x: x * x + 1 / (x * x) + (a - 1) ** 2 - 2 * np.cos(2 * PI * x)
    return koren_est(g, setka(1e-3, 10, tochki=(1,)), setka(-10, -1e-3, tochki=(-1,)))


def t6(a):  # 3 sin x + 4 cos x = a² + 4a + 9: решение
    x0 = math.atan2(3, 4)
    x = np.concatenate((X_TRIG, [x0, x0 + PI]))
    return koren_est(lambda x: 3 * np.sin(x) + 4 * np.cos(x) - (a * a + 4 * a + 9), x)


def t7(a):  # sin x = (a² + 1)/(2a): решение
    if abs(a) < 1e-12:
        return False
    return koren_est(lambda x: np.sin(x) - (a * a + 1) / (2 * a), X_TRIG)


def t8(a):  # sin(πx/2) = x² − 2x + a² − 4a + 5: ровно одно решение
    # x² − 2x + a² − 4a + 5 − sin(πx/2) = (x − 1)² + 2 sin²(π(x − 1)/4) + (a² − 4a + 4 − 1),
    # свободный член — последним
    c = a * a - 4 * a + 3
    g = lambda x: ((x - 1) ** 2 + 2 * np.sin(PI * (x - 1) / 4) ** 2) + c
    r = korni(g, -8, 10, n=400_001, tochki=(1,))
    return r != INF and len(r) == 1


def t9(a):  # |sin x| + |cos x| = |a|: решение
    return koren_est(lambda x: np.abs(np.sin(x)) + np.abs(np.cos(x)) - abs(a), X_TRIG)


