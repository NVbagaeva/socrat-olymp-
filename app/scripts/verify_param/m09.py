"""Метод 9 «Аналитический способ»: проверка разборов, опорных и тренировочных задач.

У каждой задачи — условие «как в тексте задачи», без случаев и формул
корней из решения: функция по параметру говорит, выполняется ли
требование задачи. Проверка — перебором по x общим поиском корней
(obshchee.korni): смена знака на сетке, касание (локальный минимум |g|
около нуля) и точная подстановка в особых точках — концах области и
изломах модуля.

Почему это проверяет то, что обычно теряют при аналитическом решении:

  * старший коэффициент обращается в нуль — уравнение становится
    линейным, и у квадратного уравнения около этого значения один корень
    уходит далеко (при a = 1 ± 10⁻³ — за тысячу). Поэтому сетка по x —
    плотная около нуля и логарифмическая до ±10⁷: далёкий корень не
    теряется, а при a = 1 перебор видит ровно один корень;
  * совпавшие корни (двойной корень, корни двух случаев в одной точке)
    перебор находит одной точкой: близкие находки склеиваются, только
    если между ними g ≈ 0, — двойной корень считается один раз;
  * выколотые точки и область определения: где знаменатель — нуль или
    подкоренное выражение отрицательно, g = nan, и корня там нет (0/0
    в выколотой точке тоже nan);
  * «при всех x > 0», «множество решений содержит отрезок» — проверка
    знака на сетке, в том числе далеко (логарифмическая сетка).

NEVERNYE — заведомо неверные ответы: потерян случай «старший
коэффициент — нуль» (a = 1), совпавший корень посчитан дважды, корень
вне области определения посчитан, не учтён случай равенства нулю
коэффициента при делении. run.py требует, чтобы перебор каждый из них
опроверг.
"""

import numpy as np

from obshchee import INF, korni

TOL = 1e-12


def setka(lo, hi, n=200_001, tochki=(), daleko=True):
    """Сетка x: плотная на [lo; hi], логарифмическая до ±10⁷ и особые точки."""
    chasti = [np.linspace(lo, hi, n), np.asarray(tochki, dtype=float)]
    if daleko:
        d = np.geomspace(abs(hi) + 1 if hi > 0 else 1, 1e7, 20_000)
        chasti.append(d)
        d = np.geomspace(abs(lo) + 1 if lo < 0 else 1, 1e7, 20_000)
        chasti.append(-d)
    return np.unique(np.concatenate(chasti))


def koren(v):
    """√v там, где v ≥ 0; вне области — nan (без предупреждений numpy)."""
    v = np.asarray(v, dtype=float)
    return np.sqrt(np.where(v >= 0, v, np.nan))


def schet(g, x):
    """Корни g на сетке x: список или INF."""
    return korni(g, float(x[0]), float(x[-1]), setka=x)


def rovno(g, x, n):
    r = schet(g, x)
    return r != INF and len(r) == n


def hotya_by(g, x):
    r = schet(g, x)
    return r == INF or len(r) > 0


# ── Разборы ─────────────────────────────────────────────────────────


def r1(a):  # (a − 1)x² + 2ax + a + 3 = 0: ровно один корень
    g = lambda x: (a - 1) * x * x + 2 * a * x + a + 3
    return rovno(g, setka(-20, 20), 1)


def r2(a):  # (x − a)(x − 2a + 1)/(x − 3) = 0: ровно два корня
    g = lambda x: (x - a) * (x - 2 * a + 1) / (x - 3)
    return rovno(g, setka(-20, 20, tochki=(a, 2 * a - 1, 3), daleko=False), 2)


def r3(a):  # √(x + a) = x: ровно один корень
    g = lambda x: koren(x + a) - x
    return rovno(g, setka(-20, 20, tochki=(-a, 0), daleko=False), 1)


# ── Опорные ─────────────────────────────────────────────────────────


def o1(a):  # (a² − 1)x = a + 1: не имеет решений
    g = lambda x: (a * a - 1) * x - (a + 1)
    return schet(g, setka(-20, 20)) == []


def o2(a):  # (ax − 1)/(x − 1) = 0: не имеет решений
    g = lambda x: (a * x - 1) / (x - 1)
    return schet(g, setka(-20, 20, tochki=(1,))) == []


def o3(a):  # |x| = ax + 1: ровно два корня
    g = lambda x: np.abs(x) - a * x - 1
    return rovno(g, setka(-20, 20, tochki=(0,)), 2)


def o4(a):  # ax + 1 > 2x − a при всех x > 0
    x = setka(1e-9, 20, daleko=False)
    x = np.concatenate((x, np.geomspace(1e-12, 1e9, 20_000)))
    return bool(np.min(a * x + 1 - (2 * x - a)) > 0)


def o5(a):  # x² − (a + 2)x + 2a = 0: ровно один корень на отрезке [0; 3]
    g = lambda x: x * x - (a + 2) * x + 2 * a
    x = setka(0, 3, n=300_001, tochki=(0, 3, a, 2), daleko=False)
    x = x[(x >= 0) & (x <= 3)]
    return rovno(g, x, 1)


def o6(a):  # (x − 1)a = x + 2: имеет корень x > 2
    g = lambda x: (x - 1) * a - x - 2
    x = setka(2, 30, n=400_001)
    x = x[x > 2]
    return hotya_by(g, x)


# ── Тренировка ──────────────────────────────────────────────────────


def t1(a):  # (a − 2)x = a² − 4: ровно одно решение
    g = lambda x: (a - 2) * x - (a * a - 4)
    return rovno(g, setka(-20, 20), 1)


def t2(a):  # ax = a + 3: имеет положительный корень
    g = lambda x: a * x - a - 3
    x = setka(-20, 20)
    return hotya_by(g, x[x > 0])


def t3(a):  # (a + 1)x² − 2x + 1 = 0: хотя бы один корень
    g = lambda x: (a + 1) * x * x - 2 * x + 1
    return hotya_by(g, setka(-20, 20))


def t4(a):  # (x² − (a + 3)x + 3a)·√(x − 1) = 0: ровно два корня
    g = lambda x: (x * x - (a + 3) * x + 3 * a) * koren(x - 1)
    return rovno(g, setka(-20, 20, tochki=(1, 3, a), daleko=False), 2)


def t5(a):  # (x² − (a + 1)x + a)/(x² − 4) = 0: ровно один корень
    g = lambda x: (x * x - (a + 1) * x + a) / (x * x - 4)
    return rovno(g, setka(-20, 20, tochki=(1, a, 2, -2), daleko=False), 1)


def t6(a):  # (x − a)/(x − 2) ≤ 0: множество решений содержит отрезок [3; 4]
    x = np.linspace(3, 4, 100_001)
    return bool(np.max((x - a) / (x - 2)) <= TOL)


def t7(a):  # √(2x + a) = x − 1: ровно два корня
    g = lambda x: koren(2 * x + a) - (x - 1)
    return rovno(g, setka(-20, 20, tochki=(-a / 2, 1, 2), daleko=False), 2)


def t8(a):  # |x + 1| = a(x − 1): ровно один корень
    g = lambda x: np.abs(x + 1) - a * (x - 1)
    return rovno(g, setka(-20, 20, tochki=(-1,)), 1)


def t9(a):  # (a − 1)x² − 2ax + a + 1 = 0: все корни принадлежат [0; 2]
    g = lambda x: (a - 1) * x * x - 2 * a * x + a + 1
    r = schet(g, setka(-20, 20, tochki=(0, 1, 2)))
    if r == INF:
        return False
    return all(-1e-9 <= x <= 2 + 1e-9 for x in r)


