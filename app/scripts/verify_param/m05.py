"""Метод 5 «Чётность функций»: проверка разборов, опорных и тренировочных задач.

У каждой задачи — условие «как в тексте задачи», без выкладок решения:
функция по параметру говорит, выполняется ли требование задачи. Система
сводится подстановкой к одному уравнению по одной переменной: каждому
его корню отвечает ровно одно решение системы.

Корни считаются по отдельности на трёх частях прямой — без опоры на
симметрию уравнения:
  * x = 0 — точной подстановкой (|g(0)| < 10⁻¹²);
  * (δ; X] и [−X; −δ) — общим поиском (obshchee.korni) не самой g, а
    g(x)/|x|^p. У тех же корней это деление снимает «плоский» нуль в
    x = 0: при найденном значении параметра g(x) ведёт себя около нуля
    как x⁴/12 или x⁴/4, и поиск по g принял бы полосу почти-нулей за
    бесконечно много корней. После деления на x⁴ функция около нуля —
    около константы, а двойной корень x = 0 — один корень, посчитанный
    точной подстановкой.
Корни в (0; δ), δ = 10⁻⁵, появляются только при параметре ближе ~10⁻⁹
к особому значению; ближайшие проверяемые значения отстоят на 10⁻³.

Чтобы около x = 0 не терять точность, cos x − 1 записано как
−2 sin²(x/2), а квадраты в системах раскрыты — это тождества, а не шаги
решения.

NEVERNYE — заведомо неверные ответы (среди них отброшенные кандидаты):
run.py требует, чтобы перебор каждый из них опроверг.
"""

import math

import numpy as np

from obshchee import INF, chislo, korni

DELTA = 1e-5


def _v0(g):
    with np.errstate(all="ignore"):
        v = g(np.array([0.0]))[0]
    return bool(np.isfinite(v) and abs(v) < 1e-12)


def schet(g, X=20.0, p=2, tochki=(), n=200_001):
    """Число решений g(x) = 0 на [−X; X] (INF — бесконечно много)."""

    def h(x):
        return g(x) / np.abs(x) ** p

    plus = korni(h, DELTA, X, n=n, tochki=[t for t in tochki if t > DELTA])
    minus = korni(h, -X, -DELTA, n=n, tochki=[t for t in tochki if t < -DELTA])
    if plus == INF or minus == INF:
        return INF
    return int(_v0(g)) + len(plus) + len(minus)


def odno(g, **kw):
    return schet(g, **kw) == 1


# ── Разборы ─────────────────────────────────────────────────────────


def r1(a):  # x² + a|x| + a² − 4 = 0: ровно одно решение
    return odno(lambda x: x**2 + a * np.abs(x) + a**2 - 4)


def r2(a):  # x² + a·cos x = a² − 5a + 8: ровно одно решение
    # свободный член — последним и отдельно: иначе прибавление числа ~1 съело бы
    # разность x² − 2a·sin²(x/2) ~ x⁴/12 около нуля
    return odno(lambda x: (x**2 - 2 * a * np.sin(x / 2) ** 2) + (a - (a**2 - 5 * a + 8)), p=4)


def r3(a):  # y = x² + a, x² + y² = 1: ровно одно решение
    # x² + (x² + a)² − 1, квадрат раскрыт
    return odno(lambda x: x**4 + (2 * a + 1) * x**2 + (a**2 - 1), p=4)


# ── Опорные ─────────────────────────────────────────────────────────


def o1(a):  # x² + 3|x| = a² − 4: ровно одно решение
    return odno(lambda x: x**2 + 3 * np.abs(x) - (a**2 - 4))


def o2(a):  # 2^|x| + x² = a: ровно одно решение
    return odno(lambda x: 2 ** np.abs(x) + x**2 - a)


def o3(a):  # 1/x² + x² = a: ровно одно решение
    return odno(lambda x: 1 / x**2 + x**2 - a)


def o4(a):  # x² + y² = 2, x + y = a: ровно одно решение (y = a − x)
    g = lambda x: x**2 + (a - x) ** 2 - 2
    return chislo(korni(g, -10, 10, n=400_001)) == 1


def o5(a):  # x² − 2|x| = a: ровно два решения
    return schet(lambda x: x**2 - 2 * np.abs(x) - a) == 2


# ── Тренировка ──────────────────────────────────────────────────────


def t1(a):  # x² + 4|x| + a² − 2a = 0: ровно одно решение
    return odno(lambda x: x**2 + 4 * np.abs(x) + a**2 - 2 * a)


def t2(a):  # 2^|x| + a = cos x: ровно одно решение
    return odno(lambda x: 2 ** np.abs(x) + a - np.cos(x))


def t3(a):  # |x| = a x² + a − 1: ровно одно решение (корни до |x| ≈ 1/a)
    return odno(lambda x: np.abs(x) - a * x**2 - a + 1, X=200.0, n=1_000_001)


def t4(a):  # x² = a sin² x + a² − 4: ровно одно решение
    return odno(lambda x: x**2 - a * np.sin(x) ** 2 - (a**2 - 4))


def t5(a):  # 2^|x| − a|x| = a² − 1: ровно одно решение
    return odno(lambda x: 2 ** np.abs(x) - a * np.abs(x) - (a**2 - 1))


def t6(a):  # x² − 4|x| = a² − 4a: ровно три решения
    return schet(lambda x: x**2 - 4 * np.abs(x) - (a**2 - 4 * a)) == 3


def t7(a):  # x² + y² = 4, x = a − y²: ровно одно решение (по y)
    # (a − y²)² + y² − 4, квадрат раскрыт
    return odno(lambda y: y**4 + (1 - 2 * a) * y**2 + (a**2 - 4), p=4)


def t8(a):  # x² + y² = 1, y = a x² + 1: ровно одно решение
    # x² + (a x² + 1)² − 1, квадрат раскрыт
    return odno(lambda x: a**2 * x**4 + (2 * a + 1) * x**2, p=4)


def t9(a):  # x² + (a − 2)² = |x + a − 2| + |x − a + 2|: ровно одно решение
    b = a - 2
    g = lambda x: x**2 + b**2 - np.abs(x + b) - np.abs(x - b)
    return odno(g, tochki=(b, -b))


