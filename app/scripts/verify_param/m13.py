# Открытый конец промежутка: сетка начинается на столько внутри.
OTSTUP = 1e-6


def schet(g, x):
    """Корни g на сетке x: список или INF."""
    return korni(g, float(x[0]), float(x[-1]), setka=x, dopusk=DOPUSK)


def rovno(g, x, n):
    r = schet(g, x)
    return r != INF and len(r) == n


def est(g, x):
    r = schet(g, x)
    return r == INF or len(r) > 0


def otrezok(lo, hi, lo_vkl=True, hi_vkl=True, tochki=(), n=300_001, otstup=OTSTUP):
    """Сетка по промежутку от lo до hi; открытый конец — на otstup внутри."""
    a = lo if lo_vkl else lo + otstup
    b = hi if hi_vkl else hi - otstup
    x = setka(a, b, n=n, tochki=(a, b) + tuple(tochki), daleko=False)
    return x[(x >= a) & (x <= b)]


def pryamaya(lo=-30, hi=30, tochki=()):
    """Вся прямая: плотно на [lo; hi], дальше логарифмически до ±10⁷."""
    return setka(lo, hi, n=400_001, tochki=tochki)


def luch(ot, tochki=()):
    """Луч [ot; +∞): плотно до ot + 40, дальше логарифмически."""
    x = setka(ot, ot + 40, n=400_001, tochki=(ot,) + tuple(tochki))
    return x[x >= ot]


def otn(lev, prav):
    """Разность частей, делённая на 1 + |левая часть|: тот же нуль, без потери точности."""
    return lambda x: (lev(x) - prav(x)) / (1 + np.abs(lev(x)))


def kub(t):  # f(t) = t³ + t
    return t**3 + t


def pyat(t):  # f(t) = t⁵ + t
    return t**5 + t


def arcsin(x):
    with np.errstate(all="ignore"):
        return np.where(np.abs(x) <= 1, np.arcsin(np.clip(x, -1, 1)), np.nan)


# ── Разборы ─────────────────────────────────────────────────────────


def r1(a):  # (x² + a)³ + x² + a = 27x³ + 3x: ровно два корня на [0; 3]
    g = otn(lambda x: kub(x * x + a), lambda x: 27 * x**3 + 3 * x)
    return rovno(g, otrezok(0, 3, tochki=(1.5,)), 2)


def r2(a):  # x³ + a = ∛(x − a): ровно три корня
    g = lambda x: x**3 + a - np.cbrt(x - a)
    t = 1 / SQ3
    return rovno(g, pryamaya(-5, 5, tochki=(-t, t, 0, a)), 3)


def r3(a):  # x³ − 3x = a: ровно два корня на [0; 2]
    return rovno(lambda x: x**3 - 3 * x - a, otrezok(0, 2, tochki=(1,)), 2)


def r4(a):  # sin(π/3 · cos x) = a: ровно два корня на [0; 2π)
    g = lambda x: np.sin(PI / 3 * np.cos(x)) - a
    # У открытого конца 2π при a = √3/2 левая часть ≈ −0,26·(x − 2π)²: сетка
    # отступает на 10⁻⁴, чтобы этот двойной корень вне промежутка не попал
    # в допуск нуля. Ближайший настоящий корень (a не ближе 10⁻³ к √3/2)
    # дальше 0,06 от конца.
    return rovno(g, otrezok(0, 2 * PI, hi_vkl=False, tochki=(PI,), otstup=1e-4), 2)


def r5(a):  # (x² + a)⁵ + (x − 3)⁵ + x² + x + a − 3 = 0: ровно два корня на [−2; 1]
    g = otn(lambda x: pyat(x * x + a), lambda x: -pyat(x - 3))
    return rovno(g, otrezok(-2, 1, tochki=(-0.5,)), 2)


def r6(a):  # arcsin(x² − a) + arcsin x = 0: ровно два корня
    g = lambda x: arcsin(x * x - a) + arcsin(x)
    return rovno(g, otrezok(-1, 1, tochki=(-0.5, 0)), 2)


# ── Опорные ─────────────────────────────────────────────────────────


def o1(a):  # x⁵ + 3x + 2^x = a: есть корень на [0; 1]
    return est(lambda x: x**5 + 3 * x + 2**x - a, otrezok(0, 1))


def o2(a):  # 2^(x² + a) + x² + a = 4^x + 2x: есть решение
    g = otn(lambda x: 2 ** (x * x + a) + x * x + a, lambda x: 4**x + 2 * x)
    x = pryamaya(-10, 10, tochki=(1,))
    return est(g, x[np.abs(x) < 300])


def o3(a):  # √(x + 1) + x³ = a: есть решение
    return est(lambda x: np.sqrt(x + 1) + x**3 - a, luch(-1, tochki=(0,)))


def o4(a):  # (2^x + 3)/(2^x + 1) = a: есть решение
    # Только |x| ≤ 30: дальше разность с пределом (2/(2^x + 1) при a = 1)
    # меньше допуска нуля, и предел сошёл бы за корень. Корень при a из
    # сетки (не ближе 10⁻³ к 1 и 3) — |x| < 12.
    x = otrezok(-30, 30, n=600_001)
    return est(lambda x: (2**x + 3) / (2**x + 1) - a, x)


def o5(a):  # x³ + ax − 1 = 0: есть корень на (0; 1)
    return est(lambda x: x**3 + a * x - 1, otrezok(0, 1, False, False))


def o6(a):  # (x + a)³ + (3x − 2)³ + 4x + a − 2 = 0: есть корень на [0; 1]
    g = otn(lambda x: kub(x + a), lambda x: -kub(3 * x - 2))
    return est(g, otrezok(0, 1))


