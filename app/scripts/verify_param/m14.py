"""Метод 14 «Метод упрощающего значения»: проверка разборов, опорных и тренировочных задач.

У каждой задачи — исходное условие «как в тексте задачи», без
найденного в решении разложения на множители и без кандидатов:
функция по параметру говорит, выполняется ли требование задачи.

  * «x₀ — решение (корень)»: неравенство или уравнение вычисляется в
    самой точке x₀ — как записано в условии, вместе с областью
    определения: нуль знаменателя, отрицательное подкоренное выражение,
    основание логарифма ≤ 0 или = 1 — не решение. Равенство — с допуском
    10⁻¹², нестрогое неравенство — с тем же допуском;
  * «ровно n корней»: корни исходного уравнения ищутся по x общим
    поиском (obshchee.korni, допуск нуля 10⁻¹²) на густой сетке
    (до 3·10⁻⁵ на рабочем отрезке, дальше логарифмически до ±10⁷):
    смена знака — корень; касание и кратный корень (x²(x − 2) при a = 0,
    (x + 1/2)³ при a = 3/4) — минимум |g| около нуля, совпавшие находки
    склеиваются в одну. Выбранное значение (x = 2, x = 3, x = −1) и
    другие особые x лежат в сетке точно. Тождество (a = 1 в
    (a − 1)(a − x²) = 0) — бесконечно много корней;
  * система: точка проверяется подстановкой в оба уравнения, затем y из
    второго уравнения (y = x, y = ax + …) подставляется в первое — как
    в условии — и считаются корни по x: каждому x одно решение;
  * «корень при любом b»: для квадратного по x уравнения корень есть
    ⇔ дискриминант ≥ 0 — он вычисляется из коэффициентов исходного
    уравнения на сетке b ∈ [−60; 60] (шаг 0,01, b = 0 точно);
  * концы ответа и особые значения параметра приходят в сетку a точно
    и в ±ε от них.

NEVERNYE — заведомо неверные ответы с типичными ошибками главы:
кандидаты без проверки (лишний корень после возведения в квадрат,
второе решение системы); значение вне области (нуль знаменателя,
основание 1 включены); достаточное условие «x₀ обнуляет b» принято за
ответ; совпадение корня с выбранным значением не учтено (совпавшие —
дважды); подстановка только в числитель. run.py требует, чтобы перебор
каждый из них опроверг.
"""

import math

import numpy as np

from m09 import setka
from obshchee import INF, korni

DOPUSK = 1e-12
SQ2 = math.sqrt(2)
SQ3 = math.sqrt(3)
SQ5 = math.sqrt(5)


def schet(g, x):
    """Корни g на сетке x: список или INF."""
    return korni(g, float(x[0]), float(x[-1]), setka=x, dopusk=DOPUSK)


def rovno(g, x, n):
    r = schet(g, x)
    return r != INF and len(r) == n


def pryamaya(lo=-6, hi=6, tochki=(), n=400_001):
    """Вся прямая: плотно на [lo; hi], дальше логарифмически до ±10⁷."""
    return setka(lo, hi, n=n, tochki=tochki)


def luch(ot, do=8, tochki=(), n=400_001):
    """Луч [ot; +∞): плотно до do, дальше логарифмически; конец ot — в сетке."""
    x = setka(ot, do, n=n, tochki=(ot,) + tuple(tochki))
    return x[x >= ot]


def drob(chisl, znam):
    """Значение дроби; нуль знаменателя — None (дробь не определена)."""
    if abs(znam) < 1e-15:
        return None
    return chisl / znam


def koren_est_pri_vseh_b(A, B, C, b_osob=(0.0,)):
    """Квадратное по x уравнение A·x² + B(b)·x + C(b) = 0 (A ≠ 0) имеет корень при всех b сетки."""
    b = np.concatenate((np.arange(-60, 60.005, 0.01), np.asarray(b_osob, dtype=float)))
    d = B(b) ** 2 - 4 * A * C(b)
    return bool(np.min(d) >= -DOPUSK)


# ── Разборы ─────────────────────────────────────────────────────────


def r1(a):  # x = 1 — решение (x − a²)/(x + a − 3) ≤ 0
    x = 1.0
    v = drob(x - a * a, x + a - 3)
    return v is not None and v <= DOPUSK


def r2(a):  # x = a — решение (x² + ax − 6)/(x − 1) ≤ 0
    x = a
    v = drob(x * x + a * x - 6, x - 1)
    return v is not None and v <= DOPUSK


def r3(a):  # x³ − 2x² + ax − 2a = 0: ровно два различных корня
    g = lambda x: x**3 - 2 * x * x + a * x - 2 * a
    return rovno(g, pryamaya(-6, 6, tochki=(2, 0, -2)), 2)


def r4(a):  # x² + (b − 2)x + a − b = 0: корень при любом b
    return koren_est_pri_vseh_b(1.0, lambda b: b - 2, lambda b: a - b)


def r5(a):  # x⁴ − 2ax² − x + a² − a = 0: ровно два различных корня
    g = lambda x: x**4 - 2 * a * x * x - x + a * a - a
    return rovno(g, pryamaya(-6, 6, tochki=(-0.5, 0.5, 1.5)), 2)


def r6(a):  # x² + y² = 5, y = ax + a² − a − 1: решение (2; 1) и других нет
    c = a * a - a - 1
    if abs(4 + 1 - 5) > DOPUSK or abs(1 - (2 * a + c)) > 1e-9:
        return False
    g = lambda x: x * x + (a * x + c) ** 2 - 5
    r = schet(g, pryamaya(-6, 6, tochki=(2, -1)))
    return r != INF and len(r) == 1 and abs(r[0] - 2) < 1e-6


# ── Опорные ─────────────────────────────────────────────────────────


def o1(a):  # x = −2 — корень √(x + 3a) = x + 4 − a
    x = -2.0
    pod = x + 3 * a
    if pod < 0:
        return False
    return abs(math.sqrt(pod) - (x + 4 - a)) < 1e-9


def o2(a):  # x = a — решение log_x(3a − x) ≤ 1
    x = a
    arg = 3 * a - x
    if x <= 0 or abs(x - 1) < 1e-15 or arg <= 0:
        return False
    return math.log(arg) / math.log(x) <= 1 + DOPUSK


def o3(a):  # a|x − 3| = x² − 9: ровно один корень
    g = lambda x: a * np.abs(x - 3) - (x * x - 9)
    return rovno(g, pryamaya(-25, 25, tochki=(3, -3), n=600_001), 1)


def o4(a):  # a² − a(x² + 1) + x² = 0: ровно два корня
    g = lambda x: a * a - a * (x * x + 1) + x * x
    return rovno(g, pryamaya(-6, 6, tochki=(0,)), 2)


def o5(a):  # (1; 2) — решение системы x² + y² ≤ a², y − x ≥ a − 2
    x, y = 1.0, 2.0
    return x * x + y * y <= a * a + DOPUSK and y - x >= a - 2 - DOPUSK


# ── Тренировочная работа ────────────────────────────────────────────


def t1(a):  # x = 2 — корень x² − (a + 1)x + a² − 2 = 0
    x = 2.0
    return abs(x * x - (a + 1) * x + a * a - 2) < 1e-9


def t2(a):  # x = 2 — решение (x + a)/(x − a) ≤ 0
    x = 2.0
    v = drob(x + a, x - a)
    return v is not None and v <= DOPUSK


def t3(a):  # x³ + ax² − 4x − 4a = 0: ровно два различных корня
    g = lambda x: x**3 + a * x * x - 4 * x - 4 * a
    return rovno(g, pryamaya(-8, 8, tochki=(2, -2, -a)), 2)


def t4(a):  # x = 3 — решение log_(a+1)(x − a) ≥ 1
    x = 3.0
    osn, arg = a + 1, x - a
    if osn <= 0 or abs(osn - 1) < 1e-15 or arg <= 0:
        return False
    return math.log(arg) / math.log(osn) >= 1 - DOPUSK


def t5(a):  # x² − 5x + 6 = a|x − 3|: ровно два различных корня
    g = lambda x: x * x - 5 * x + 6 - a * np.abs(x - 3)
    return rovno(g, pryamaya(-10, 12, tochki=(3, 2, 1)), 2)


def t6(a):  # x⁴ + 2x³ − 2a(x² + x) + a² = 0: ровно два различных корня
    g = lambda x: x**4 + 2 * x**3 - 2 * a * (x * x + x) + a * a
    return rovno(g, pryamaya(-6, 6, tochki=(0, -1, -2)), 2)


def t7(a):  # (x − a)² + y² = 2, y = x: ровно два решения, одно из них (1; 1)
    if abs((1 - a) ** 2 + 1 - 2) > 1e-9:
        return False
    g = lambda x: (x - a) ** 2 + x * x - 2
    r = schet(g, pryamaya(-6, 6, tochki=(1, -1)))
    return r != INF and len(r) == 2 and any(abs(t - 1) < 1e-6 for t in r)


def t8(a):  # x² + (b − 4)x + a − 2b = 0: корень при любом b
    return koren_est_pri_vseh_b(1.0, lambda b: b - 4, lambda b: a - 2 * b)


def t9(a):  # 1 и 2 — решения (x − a)(x − a²) ≤ 0, 3 — нет
    f = lambda x: (x - a) * (x - a * a)
    return f(1) <= DOPUSK and f(2) <= DOPUSK and f(3) > DOPUSK


def t10(a):  # (a² − (x² + 2x)a + 2x³)·√(x + 1) = 0: ровно три различных корня
    def g(x):
        with np.errstate(all="ignore"):
            s = np.sqrt(np.where(x >= -1, x + 1, np.nan))
        return (a * a - (x * x + 2 * x) * a + 2 * x**3) * s

    t = (2, 1, 0.5, a / 2)
    return rovno(g, luch(-1, 8, tochki=t), 3)


