import type { ReactNode } from 'react';

/**
 * Прямые знаки ≈ и → внутри курсивной математической строки рисунка.
 *
 * Строка `.pr-math` набрана курсивом, как переменные в формуле, а знаки
 * отношений в наборе формул всегда прямые. Дело не только в правиле:
 * в курсивных начертаниях математических шрифтов этих знаков нет,
 * и на печатном листе Chromium брал их из системной антиквы — проверка
 * состава шрифтов сборника это ловит. Прямой tspan берёт знак из
 * прямого начертания того же стека.
 */
export function Znaki({ text }: { text: string }): ReactNode {
  return text.split(/([≈→])/).map((chast, i) =>
    i % 2 === 1 ? (
      <tspan key={i} className="pr-znak">
        {chast}
      </tspan>
    ) : (
      chast
    ),
  );
}
