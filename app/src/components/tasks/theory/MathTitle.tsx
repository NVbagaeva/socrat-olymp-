import type { ReactNode } from 'react';
import { Phrases } from './Phrases';
import { phrases } from './markup';

/**
 * Заголовок с разметкой $…$.
 *
 * Буквы-переменные в заголовке набираются так же, как в тексте:
 * математическим курсивом, а не обычным шрифтом. Заголовок без
 * долларов возвращается строкой как есть — разметка у подтем, где
 * такой записи нет, не меняется ни на узел.
 *
 * Набирает KaTeX на сборке, поэтому компонент серверный: в ленте
 * вкладок он появляется уже готовым узлом, и katex не уезжает
 * в клиентский бандл всех разделов сайта.
 */
export function MathTitle({ text }: { text: string }): ReactNode {
  /* Куски заголовка лежат в одной обёртке: заголовок раздела — колонка
     из кружка с номером и текста, и без обёртки каждый кусок стал бы
     в этой колонке отдельной ячейкой. Тогда строка не переносится и
     на узком экране заголовок вылезает за край. */
  return text.includes('$') ? (
    <span>
      <Phrases parts={phrases(text)} />
    </span>
  ) : (
    text
  );
}
