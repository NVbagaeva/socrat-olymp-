/**
 * Навигация между разделами (подтемами) задания: плашка над вкладками,
 * выезжающее меню «Все разделы задания №…» и блок «Другие разделы №…»
 * внизу вкладок. Типы общие — компонент не знает, какое это задание:
 * данные собирает страница (для №12 — razdely12.ts).
 */

/** Иконка раздела: WebP и запасной PNG трёх ширин (srcset). */
export interface IkonkaRazdela {
  webp: string;
  png: string;
  /** Запасной адрес для браузера без srcset. */
  src: string;
  /** Натуральные пропорции файла: место под картинку резервируется. */
  width: number;
  height: number;
}

export interface RazdelKarta {
  id: string;
  /** Название раздела — название функции: «Иррациональная функция». */
  title: string;
  /** Подпись под названием — название графика: «График — ветвь параболы». */
  graphName: string;
  icon: IkonkaRazdela;
  /**
   * Раздела ещё нет на сайте: в меню — бледная карточка «Скоро», не
   * ссылка; в блоке «Другие разделы» её нет вовсе.
   */
  soon: boolean;
  /**
   * Адреса вкладок раздела: id вкладки → адрес. Вкладка «О задании»
   * (about) есть всегда, остальные — только если они у раздела есть.
   */
  vkladki: Readonly<Record<string, string>>;
  /** Раздел тренажёра в хранилище тренировок: «12:linear». */
  scope: string;
}

export interface RazdelyData {
  /** Номер задания: «12». */
  no: string;
  razdely: readonly RazdelKarta[];
  /** id текущего раздела. */
  current: string;
  /** Подзаголовок блока «Другие разделы №…» внизу вкладок. */
  podzagolovok: string;
}

/** Вкладка, которая есть у любого раздела: на неё уходят по умолчанию. */
export const VKLADKA_PO_UMOLCHANIYU = 'about';

/**
 * Параметр адреса, которым открывается вкладка без своего адреса
 * («Теория», «Методы», «Генератор»): /zadaniya/12/quadratic/?vkladka=theory.
 */
export const VKLADKA_PARAM = 'vkladka';

/**
 * Событие «открыть меню разделов»: его шлёт кнопка «‹ Все разделы №…»
 * в шапке. Шапка собирается на сервере и с плашкой над вкладками не
 * связана, а меню у страницы одно — то, что живёт при плашке.
 * detail — узел, на который вернуть фокус после закрытия.
 */
export const RAZDELY_OPEN_EVENT = 'razdely:otkryt';
