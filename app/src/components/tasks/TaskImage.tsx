import Image from 'next/image';

export interface TaskImageProps {
  /** Номер задания двумя цифрами — он же номер файла картинки. */
  no: string;
  /** Формат файла. Не задан — webp; svg у заданий с векторным чертежом. */
  format?: 'webp' | 'svg';
}

/**
 * Миниатюра задания.
 *
 * Путь собирается из номера задания, поэтому новое задание не требует
 * ни строчки кода — достаточно положить файл с нужным номером. Формат
 * задаётся в списке заданий: векторная миниатюра стоит в том же месте
 * и тех же размеров, что и растровые, отличается только расширение.
 *
 * Подложки под картинкой нет: у самих картинок есть светлые заливки,
 * и круг того же цвета только добавлял второй слой, в котором картинка
 * тонула.
 *
 * alt пустой намеренно: картинка декоративная, название задания стоит
 * рядом текстом, и повторять его для скринридера незачем.
 */
export function TaskImage({ no, format = 'webp' }: TaskImageProps) {
  return (
    <Image
      className="ill-photo"
      src={`/images/task-${no}.${format}`}
      alt=""
      width={96}
      height={96}
    />
  );
}
