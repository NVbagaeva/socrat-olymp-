import { nabratVykladku } from '@/lib/tex';
import { VykladkaKlient } from '../VykladkaKlient';

/**
 * Формула отдельной строкой в карточке теории.
 *
 * Собирается выкладкой — тем же правилом, что шпаргалки №3 и разборы:
 * браузер набирает её в строки по ширине карточки. Раньше формула
 * стояла в одну строку с `overflow-x: auto` и в узкой карточке
 * уезжала во внутреннюю прокрутку, которой на экране не видно.
 *
 * Набор выключной: дроби и индексы в полный рост, как у формулы
 * отдельной строкой.
 *
 * Не всякую запись есть где разорвать: «$0 < P(A) < 1$» — это одно
 * утверждение без знака равенства, сложения и вычитания, и выкладка
 * оставит его одной строкой. Значит, место под него даёт карточка:
 * сетки, в которых формула перестаёт помещаться, переходят на колонку
 * меньше (zadanie4.css). Прокрутки не остаётся ни в том, ни в другом
 * случае.
 */
export function FormulaTeorii({ tex }: { tex: string }) {
  return (
    <VykladkaKlient className="vteor-formula" vykladka={nabratVykladku(zapis(tex), true, true)} />
  );
}

/**
 * Запись формулы без долларов. В конфиге теории формула хранится
 * одной записью целиком в долларах: «$P(A) = 0$». Строка другого
 * вида — ошибка в данных, и сборка о ней скажет, а не покажет
 * ученику доллары.
 */
function zapis(tex: string): string {
  const zapisBezDollarov = /^\$([^$]+)\$$/.exec(tex.trim());
  if (zapisBezDollarov === null) {
    throw new Error(`Формула теории должна быть одной записью в долларах: ${tex}`);
  }
  return zapisBezDollarov[1] ?? '';
}
