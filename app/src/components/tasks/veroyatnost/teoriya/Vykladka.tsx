import { typeset } from '@/lib/tex';

export interface VykladkaProps {
  /** Строки формулы, каждая — TeX без долларов, в порядке чтения. */
  stroki: readonly string[];
}

/**
 * Формула в несколько строк — выкладка, как в тетради.
 *
 * Где формула рвётся, решает автор в конфиге: каждая строка массива
 * — отдельная строка на экране, одна под другой, по левому краю.
 * Знак «=» на разрыве по школьному правилу пишется дважды — в конце
 * оборванной строки и в начале следующей — и стоит в самом тексте
 * строк. Здесь строки только набираются KaTeX: ни знаков, ни
 * переносов по ширине код не добавляет. Строка, которая не влезла в
 * колонку, — повод переставить разрыв, а не прокрутка.
 */
export function Vykladka({ stroki }: VykladkaProps) {
  return (
    <div className="vteor-vykladka">
      {stroki.map((stroka, i) => (
        <span
          // Строки могут повторяться дословно, поэтому ключ — место.
          key={i}
          className="vteor-vykladka__stroka"
          dangerouslySetInnerHTML={{ __html: typeset(`$${stroka}$`, true) }}
        />
      ))}
    </div>
  );
}
