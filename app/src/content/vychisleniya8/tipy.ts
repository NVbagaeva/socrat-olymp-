/** Подсказка до ответа для задачи. */
export function podskazkaTipa(prototype: string, podtip?: string): string | null {
  const svoya = podtip === undefined ? undefined : PODTIPY8[`${prototype}:${podtip}`]?.podskazka;
  return svoya ?? TIPY8[prototype]?.podskazka ?? null;
}

/** Название типа на сайте; нет текста — название из генератора. */
export function nazvanieTipa(prototype: string, fallback: string): string {
  return TIPY8[prototype]?.nazvanie ?? fallback;
}
