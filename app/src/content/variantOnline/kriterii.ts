/** Общие места критериев, если вариант не уточнил: читаются без подстановки. */
const OBSHCHEE: Record<string, string> = {
  u: 'отдельных точек',
  u2: 'один из промежутков множества значений a, возможно, с включением граничных точек',
  u3: 'исследованию, на котором основано решение (аналитически или графически)',
};

/** Критерии задания с уточнениями варианта. */
export function kriteriiZadaniya(
  no: Part2No,
  utochnenie: Readonly<Record<string, string>> = {},
): Kriteriy[] {
  const zamena = (s: string) =>
    s.replace(/\{(u\d?)\}/g, (_m, k: string) => utochnenie[k] ?? OBSHCHEE[k] ?? '');
  return KRITERII[no].map((k) => ({ ball: k.ball, ili: k.ili.map(zamena) }));
}
