/** Тип задач: плашка «О задании» и разбор под ней. */
export interface Tip1 {
  /** Якорь плашки и адрес разбора: …/razbor/{id}/. */
  id: string;
  blok: string;
  title: string;
  hint: string;
  /** Прототип, чей чертёж — миниатюра плашки. */
  mini: number;
  /** Разобранные примеры: [прототип, номер задачи Блока 1 или 0 — образец]. */
  primery: readonly (readonly [number, number])[];
  /** Блок «Опорных задач» для «Потренироваться». */
  prep: string;
  /** Тип только для тренажёра и генератора: на «О задании» плашки нет. */
  tolkoTrenazher?: true;
}

