/* ── Туры ──────────────────────────────────────────────────────── */

export interface TourStep {
  id: string;
  /** Короткое имя шага для панели «Как проходит тур?». */
  short: string;
  /** Страница шага; тур сам переходит на неё. */
  href: string;
  /**
   * Что подсветить: CSS-селекторы, рамка охватывает их все. Пусто —
   * подсказка по центру экрана без подсветки.
   */
  target: readonly string[];
  /**
   * Что подсветить на телефоне, если не то же самое: цель должна
   * помещаться между липкими полосами и нижним листом подсказки.
   */
  narrowTarget?: readonly string[];
  /**
   * Что тур нажимает перед шагом, чтобы цель показалась: раскрыть
   * свёрнутый блок. Нажимается, только если кнопка видна.
   */
  open?: string;
  title: string;
  text: string;
  /** Текст на телефоне, если цель там другая (narrowTarget). */
  narrowText?: string;
}

export interface TourFinal {
  short: string;
  title: string;
  lead: string;
  skillsTitle: string;
  skills: readonly string[];
  again: string;
  go: { label: string; href: string };
}

export interface Tour {
  id: TourId;
  /** Подпись в меню «?». */
  label: string;
  steps: readonly TourStep[];
  final: TourFinal;
}

