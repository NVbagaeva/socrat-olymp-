/** Подпись звёзд: «Сложность ★★: дробно-рациональное → квадратное». */
export function podpisUrovnya(level: 1 | 2 | 3, section?: SectionId): string {
  const zv = '★'.repeat(level);
  const obshchee =
    [
      'линейное уравнение или прямой счёт',
      'дробное или квадратное уравнение',
      'система или нестандартная модель',
    ][level - 1] ?? '';
  const svoyo = section === undefined ? '' : UROVNI_11[section][level - 1];
  return `Сложность ${zv}: ${svoyo === '' ? obshchee : svoyo}`;
}
