/** Пример под правилом: короткий разбор по шагам. */
export interface Primer {
  uslovie: string;
  shagi: { title: string; text: string; tex?: string }[];
  otvet?: string;
}

/** Таблица по периодам, набранная руками: ячейки — TeX без долларов. */
export interface TablitsaRuchnaya {
  scheme: TableScheme;
  period: 'month' | 'year';
  /** Подписи периодов: «1», «2», «…», «n». */
  labels: string[];
  rows: string[][];
  /** Строка «Итого»: по столбцам, пустая строка — пусто. */
  itog?: string[];
  podpis?: string;
}

export type Blok =
  | {
      vid: 'kartochka';
      rol: Rol;
      title: string;
      text: string;
      tex?: string;
      spisok?: string[];
      /** «Пример» под правилом. У правила и у «Важно» пример обязателен. */
      primer?: Primer;
      /** «Почему это работает» — обязательно у «Важно». */
      pochemu?: string;
    }
  | { vid: 'tablitsa'; title: string; tablitsa: TablitsaRuchnaya }
  | { vid: 'proporciya'; title: string; stroki: [string, string][]; vyvod: string }
  | {
      vid: 'risunok';
      risunok: 'dve-shemy' | 'lesenka-dif' | 'lesenka-ann';
      title: string;
      podpis: string;
    }
  | { vid: 'razbor'; title: string; prototypeId: string; seed: string }
  | { vid: 'priznaki'; title: string; stroki: { vizhu: string; tip: string; pochemu: string }[] }
  | { vid: 'opredeli'; title: string; zadachi: { text: string; tip: string; priznak: string }[] }
  | { vid: 'delimost' };

export interface Podrazdel {
  id: string;
  title: string;
  bloki: Blok[];
}

export interface Glava {
  id: string;
  title: string;
  lead: string;
  podrazdely: Podrazdel[];
}

