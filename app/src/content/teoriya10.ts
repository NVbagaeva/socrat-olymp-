/** Отсылка к примеру: «(см. пример «Торможение» в разделе 4)». */
const SSYLKA = /\s*\(см\. [^)]*\)/g;

/**
 * Рамка для печати без примеров (шпаргалка, лист генератора): отсылки
 * «(см. пример …)» там вели бы в пустоту — убираем их; подпись таблицы,
 * отсылающая к шагу примера, тоже не нужна.
 */
export function bezSsylok(b: BlokTeorii10): BlokTeorii10 {
  const chisto = (t: string) => t.replace(SSYLKA, '');
  switch (b.vid) {
    case 'vazhno':
    case 'vyvod':
      return { ...b, paras: b.paras.map(chisto) };
    case 'lovushka':
      return { ...b, oshibka: chisto(b.oshibka), pravilno: chisto(b.pravilno) };
    case 'tablica': {
      const { podpis: _podpis, ...bez } = b;
      return bez;
    }
    default:
      return b;
  }
}

