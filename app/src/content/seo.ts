/** Задание, раздел которого ещё готовится: честный заголовок без обещаний. */
export function metaZaglushki(no: number): Metadata {
  return {
    ...ogRazdela(no),
    /* Пока раздел готовится, в поиске он не нужен; ссылки с него работают. */
    robots: { index: false, follow: true },
    title: `Задание ${no} ЕГЭ профиль: ${TEMA[no] ?? ''} — раздел готовится`,
    description: `${LEAD[no] ?? ''} Раздел с теорией и тренажёром готовится; пока можно заниматься другими заданиями банка.`,
  };
}

/**
 * H1 страницы раздела: «Задание №13. Финансовая грамотность…» — тот же
 * смысл, что у title. Название, где номер уже есть («Задание №3.
 * Стереометрия»), не меняется.
 */
export function zagolovokRazdela(no: number, nazvanie: string): string {
  return /^Задание/.test(nazvanie) ? nazvanie : `Задание №${no}. ${nazvanie}`;
}

/** Темы раздела для микроразметки LearningResource (teaches). */
export function temyRazdela(no: number): string[] {
  const lead = LEAD[no] ?? '';
  return [
    TEMA[no] ?? '',
    ...lead
      .replace(/[.:—]/g, ',')
      .split(',')
      .map((s) => s.trim()),
  ].filter((s) => s.length > 2 && s.length < 80);
}

/**
 * Вкладка раздела, которая ещё готовится (заглушка «Материал готовится»):
 * честный заголовок и noindex — пустая страница в поиске ученику не
 * поможет. Ссылки с неё работают (follow). Когда вкладка наполнится,
 * страница переходит на metaVkladki.
 */
export function metaZaglushkiVkladki(no: number, vkladka: string): Metadata {
  return {
    title: `Задание ${no} ЕГЭ: ${TEMA[no] ?? ''} — ${vkladka.toLowerCase()} готовится`,
    description: `${vkladka} задания ${no} ЕГЭ профиль готовится. Пока можно заниматься другими вкладками раздела.`,
    robots: { index: false, follow: true },
  };
}

