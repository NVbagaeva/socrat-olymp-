/** Предел длины title: дальше поиск обрезает строку. */
const TITLE_MAX = 75;

/** Начало title и первый хвост, который в него помещается. */
function korotkiy(nachalo: string, hvosty: readonly string[]): string {
  for (const hvost of hvosty) {
    const t = `${nachalo} — ${hvost}`;
    if (t.length <= TITLE_MAX) return t;
  }
  return nachalo;
}

/** Вкладки раздела, у которых свой шаблон. */
