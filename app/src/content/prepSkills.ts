/**
 * Навыки подтемы по её идентификатору (data/functionTypes.ts).
 *
 * У каждой подтемы свой список: новая не дописывается в чужой.
 * Подтема без списка показывает пустое состояние вкладки.
 */
export function prepSkillsFor(type: string): PrepSkill[] {
  if (type === 'linear') {
    return prepSkills;
  }
  if (type === 'quadratic') {
    return quadraticSkills;
  }
  if (type === 'irrational') {
    return irrationalSkills;
  }
  if (type === 'exponential') {
    return exponentialSkills;
  }
  if (type === 'logarithmic') {
    return logarithmicSkills;
  }
  if (type === 'trigonometric') {
    return trigonometricSkills;
  }
  return type === 'rational' ? rationalSkills : [];
}

