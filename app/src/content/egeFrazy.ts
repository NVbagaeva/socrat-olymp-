/** Фраза дня: `den` — номер московского дня, `dni` — сколько дней осталось. */
export function frazaDnya(den: number, dni: number): string {
  const podhodyat = EGE_FRAZY.filter((f) => dni >= (f.ot ?? 1) && dni <= (f.do ?? Infinity));
  return podhodyat[den % podhodyat.length]?.tekst(dni) ?? '';
}
