/**
 * Тексты разделов теории квадратичной функции.
 *
 * Здесь и только здесь лежат слова: компоненты разделов берут их
 * отсюда и своих строк не содержат. Тексты написаны своими словами
 * по тезисам, обозначения единые: y = ax² + bx + c, вершина
 * (x_в; y_в), формы записи — общая, через вершину a(x − m)² + n,
 * через нули a(x − x₁)(x − x₂).
 *
 * Разметка внутри строк: $…$ — формула в записи TeX, набирается
 * KaTeX; **…** — выделение автора. Чертежи — ключи сцен в
 * lib/scenes.ts, рисует их движок graph/.
 */

