export function vseKartochki6(): Kartochka6[] {
  return RAZDELY_TEORII_6.flatMap((r) => r.bloki.flatMap(kartochkiBloka6));
}

/** Карточка и раздел прототипа: «Повторить теорию» и рамки на листах. */
export function TEORIYA_6_DLYA_PROTOTIPA(
  id: string,
): { razdel: string; kartochka: string; title: string } | null {
  for (const r of RAZDELY_TEORII_6) {
    for (const b of r.bloki) {
      const k = kartochkiBloka6(b).find((x) => x.prototipy.includes(id));
      if (k) {
        return { razdel: r.id, kartochka: k.id, title: k.title };
      }
    }
  }
  return null;
}

