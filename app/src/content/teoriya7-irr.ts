/**
 * Теория №7, раздел «Иррациональные уравнения» — большой блок на всю
 * ширину: вступление, легенда ролей, три вида квадратного корня и
 * кубический корень (у каждого своя карточка, свой цвет и схема
 * равносильного перехода), живой рисунок посторонних корней, итоговая
 * таблица. Рисует components/tasks/zadanie7/Irracionalnye7.tsx.
 *
 * Роли в схемах одни во всех карточках:
 *   uravnenie — уравнение, которое решаем (тёмно-синий);
 *   uslovie   — условие, которое ОБЯЗАТЕЛЬНО проверить (золотисто-оранжевый);
 *   samo      — условие, которое выполняется само (серый с галочкой).
 * Роль всегда подписана словом — в ч/б печати цвета нет.
 *
 * Каждый вид — карточка теории (Kartochka7): к ней привязаны прототипы,
 * на неё ведёт «Повторить теорию», её короткие блоки печатаются в рамках
 * теории листов генератора. Примеры пересчитывает автотест
 * (lib/zadanie7/irrProverka.ts, pnpm test:uravneniya).
 */

import type { Kartochka7 } from './teoriya7';

export type RolIrr7 = 'uravnenie' | 'uslovie' | 'samo';

export const ROLI_IRR_7: Record<RolIrr7, { slovo: string; legenda: string }> = {
  uravnenie: { slovo: 'решаем', legenda: 'уравнение, которое решаем' },
  uslovie: { slovo: 'проверяем обязательно', legenda: 'условие, которое обязательно проверить' },
  samo: { slovo: 'выполняется само', legenda: 'условие, которое проверять не нужно' },
};

/** Строка правой части схемы: формула (TeX без $) или слова. */
export interface StrokaIrr7 {
  rol: RolIrr7;
  tex?: string;
  /** Слова вместо формулы: «корней нет». */
  tekst?: string;
  /** Короткая причина рядом (у «выполняется само»). */
  prichina?: string;
}

/** Ветка схемы: «если $a<0$» → результат. Система — фигурная скобка. */
export interface VetkaIrr7 {
  esli?: string;
  sistema: StrokaIrr7[];
  /** Строки под скобкой: «выполняется само». */
  samo?: StrokaIrr7[];
}

export interface SkhemaIrr7 {
  /** Исходное уравнение, TeX без $. */
  iskhodnoe: string;
  vetki: VetkaIrr7[];
}

export interface ShagIrr7 {
  /** Подпись этапа: «Тип и план», «Условие», «Преобразования», … */
  label: string;
  paras: string[];
}

export interface PrimerIrr7 {
  /** Ключ проверки в lib/zadanie7/irrProverka.ts. */
  id: string;
  title: string;
  /** Задача открытого банка (F…) или своя. */
  bank?: string;
  uslovie: string;
  shagi: ShagIrr7[];
  otvet: string;
  lovushka?: boolean;
}

export type TonIrr7 = 'siniy' | 'fiolet' | 'biryuza' | 'seryy';

/** Рамка внутри карточки: «Почему…» с шагами или «Важно» абзацами. */
export interface RamkaIrr7 {
  vid: 'pochemu' | 'vazhno';
  title: string;
  shagi?: string[];
  paras?: string[];
}

export interface VidIrr7 {
  kartochka: Kartochka7;
  ton: TonIrr7;
  /** «Вид 1», «Нечётная степень». */
  metka: string;
  skhema: SkhemaIrr7;
  /** Пояснения под схемой: роль и текст. */
  poyasneniya: { rol: RolIrr7; tekst: string }[];
  ramki: RamkaIrr7[];
  /** Живой рисунок посторонних корней (вид 2). */
  grafik?: boolean;
  primery: PrimerIrr7[];
  /** Если прототипов в №7 нет: «пригодится в №13». */
  zametka?: string;
}

export interface BlokIrr7 {
  vstuplenie: string[];
  vidy: VidIrr7[];
  /** Рамка «Можно ли просто проверить подстановкой?». */
  podstanovka: { title: string; paras: string[] };
  tablica: {
    title: string;
    head: string[];
    rows: { ton: TonIrr7; cells: string[] }[];
  };
  grafik: {
    title: string;
    legenda: { tex: string; ton: 'koren' | 'nash' | 'chuzhoy' }[];
    podpis: string;
    pokazat: string;
    skryt: string;
  };
}

