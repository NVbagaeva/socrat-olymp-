export interface Shag2 {
  /** Подпись этапа: что делаем. */
  label: string;
  /** Пояснение словами: что делаем и зачем; формулы в $…$. */
  paras?: string[];
  /** Выкладки: TeX без долларов, каждая строка — своя формула. */
  lines?: string[];
  /** Проверка ответа — оформляется отдельной плашкой. */
  check?: boolean;
}

export interface Tip2 {
  /** Якорь адреса: …/zadaniya/2/#dlina. */
  id: string;
  no: string;
  /** Название типа — без формул: карточка читается с первого взгляда. */
  nazvanie: string;
  /** Одна строка «что найти» — тоже без формул. */
  nayti: string;
  /** Прототипы банка, где встречается тип (коды каталога). */
  prototipy: string;
  /** Широкая карточка: базовый навык и итоговый тип. */
  wide?: boolean;
  /** Рисунок разбора с катетами; миниатюра — тот же рисунок без них. */
  risunok: Risunok;
  uslovie: string;
  shagi: Shag2[];
  /** Ответ: TeX в $…$. */
  otvet: string;
  /** Блок опорных задач этого типа (slug из lib/vektory/prep/bloki.ts). */
  opornye: string;
  /** Прототип, с которым открывается тренажёр. */
  trenazher: string;
}

