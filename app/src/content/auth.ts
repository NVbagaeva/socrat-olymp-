/** «11.10.2026» из ГГГГ-ММ-ДД — так дата редакции написана в самих документах. */
export function editionRu(version: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(version);
  return m ? `${m[3]}.${m[2]}.${m[1]}` : version;
}

/** «11 октября 2026» из ISO. */
/** «16 ноября, 18:30» по Москве — до какого момента открыт доступ. */
export function momentRu(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return '';
  return date.toLocaleString('ru-RU', {
    day: 'numeric',
    month: 'long',
    hour: '2-digit',
    minute: '2-digit',
    timeZone: 'Europe/Moscow',
  });
}

export function dateRu(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return '';
  return date.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' });
}

/** Минимальная длина пароля. Та же цифра стоит в настройках Supabase. */
export const PASSWORD_MIN = 8;

export function emailLooksValid(value: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value.trim());
}
