const zadachi = (slug: string, spisok: Omit<MikroZadacha, 'id'>[]): MikroZadacha[] =>
  spisok.map((z, i) => ({ ...z, id: `b15-${slug}-${String(i + 1).padStart(2, '0')}` }));

/** m/n в TeX. */
const T = (m: number, n = 1): string => tex(zapis(m, n));

/**
 * Перебором в сотых: наименьшее x ≥ 0, при котором x · n = m · 100.
 * Это m/n, найденное без деления, — запись бланка.
 */
function podborSotyh(m: number, n: number): string {
  for (let x = 0; x <= 10_000_000; x += 1) if (x * n === m * 100) return zapis(x, 100);
  throw new Error(`не нашлось: ${m}/${n}`);
}

/** Перебором: наименьшее натуральное n, при котором n · a = b. */
function podborTselogo(a: number, b: number): string {
  for (let n = 1; n <= 10_000_000; n += 1) if (n * a === b) return String(n);
  throw new Error(`не нашлось: ${b}/${a}`);
}

