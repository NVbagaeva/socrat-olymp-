/** Перебором: сколько из n предметов помечено, если помечены первые k. */
const schitat = (n: number, pomecheno: (i: number) => boolean): number =>
  Array.from({ length: n }, (_, i) => i).filter(pomecheno).length;

const zadachi = (slug: string, spisok: Omit<MikroZadacha, 'id'>[]): MikroZadacha[] =>
  spisok.map((z, i) => ({ ...z, id: `b5-${slug}-${String(i + 1).padStart(2, '0')}` }));

