/**
 * Общая теория «Единицы измерения» и «Степени десяти» — одна на
 * задания №10 (прикладные задачи) и №11 (текстовые задачи).
 *
 * Три блока:
 *   1. Как переводить единицы: большая → меньшая — умножаем,
 *      меньшая → большая — делим; опора на то, что точно знаем.
 *   2. Составные единицы (км/ч ↔ м/с): скорость — дробь, числитель и
 *      знаменатель переводим отдельно.
 *   3. Степени десяти: умножение, деление, нулевая и отрицательная
 *      степень, степень степени, приставки.
 *
 * Готовых правил «v км/ч → v/3,6 м/с» здесь нет намеренно: ученик
 * каждый раз опирается на опорный факт («1 ч = 60 мин») и решает,
 * умножать или делить.
 *
 * Вся математика — KaTeX: строки абзацев — с $…$, формулы — TeX без $.
 * Единицы пишутся внутри формулы (\text{ км/ч}) — так «км/ч» не рвётся
 * на телефоне. Числа всех формул пересчитывает автотест
 * (pnpm test:edinicy): каждая цепочка «a = b = c» сверяется с учётом
 * единиц.
 *
 * Тексты — свои.
 */

/** Вид рамки: цвет как в справочнике по планиметрии. */
export type TipRamki =
  /** «Определение» — синий. */
  | 'def'
  /** «Свойство / правило» — бирюзовый. */
  | 'svo'
  /** «Формула» — золотисто-оранжевый. */
  | 'teo'
  /** «Важно» — терракотовый. */
  | 'vaz'
  /** «Главный вопрос» — тёмно-синий, крупно. */
  | 'vopros'
  /** «Где пригодится» — тёмно-синий. */
  | 'gde';

/** Строка рамки: абзац (с $…$) или выносная формула. */
export type Stroka = string | { f: string };

/** Пример под кнопкой «Пример ▸»: формула и подпись, что сделали. */
export interface MiniPrimer {
  /** Строки выкладки (TeX без $); строка с «=» в начале продолжает предыдущую. */
  tex: string[];
  podpis: string;
}

/** Шаг разбора: подпись и выкладка. */
export interface ShagRazbora {
  podpis: string;
  tex: string[];
}

export type SlotStepeni = 'lestnitsa' | 'nano' | 'mega' | 'kosmos';

export type BlokEdinic =
  | { vid: 'tekst'; paras: string[]; illyustraciya?: SlotStepeni }
  | { vid: 'ramka'; tip: TipRamki; metka?: string; title?: string; stroki: Stroka[] }
  /** Схема из двух цветных стрелок. */
  | {
      vid: 'strelki';
      strelki: { otkuda: string; kuda: string; deystvie: string; pochemu: string }[];
    }
  /** Опорные факты — таблица только фактов, по группам. */
  | { vid: 'fakty'; title: string; gruppy: { title: string; fakty: string[] }[] }
  /** Примеры под кнопкой «Пример ▸». */
  | { vid: 'primery'; knopka?: string; title?: string; primery: MiniPrimer[] }
  /** Разбор по шагам: каждый шаг — строка с подписью. */
  | {
      vid: 'razbor';
      title: string;
      shagi: ShagRazbora[];
      vyvod?: string;
      /** Свёрнут под кнопкой «Пример ▸». */
      svernut?: boolean;
    }
  /** Две колонки: «так» и «так» — один и тот же результат. */
  | {
      vid: 'dveKolonki';
      tip: TipRamki;
      metka?: string;
      title: string;
      vvod?: string;
      kolonki: [Kolonka, Kolonka];
      vyvod: string;
    }
  /** Таблица приставок. */
  | {
      vid: 'pristavki';
      title: string;
      vvod: string;
      rows: { pristavka: string; oboz: string; mnozhitel: string; primer: string }[];
      illyustracii?: SlotStepeni[];
      posle?: Stroka[];
    }
  /** Место для примера из банка: его подставляет задание (№10). */
  | { vid: 'izBanka' }
  /** «Где пригодится»: пункты со ссылками. */
  | { vid: 'gde'; title: string; punkty: { tekst: string; href?: string; ssylka?: string }[] };

export interface Kolonka {
  title: string;
  stroki: Stroka[];
}

