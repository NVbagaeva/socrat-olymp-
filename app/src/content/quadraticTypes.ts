/**
 * «Типы задач в этом разделе» на вкладке «О задании» подтемы
 * «Квадратичная функция»: плашки и разборы по клику.
 *
 * Каждая плашка — тип задачи. По клику под ней раскрывается разбор:
 * два примера в том же оформлении, что примеры теории линейной функции
 * (content/theoryRich.ts, блок example): условие, рисунок слева, шаги
 * справа, проверка на адекватность, ответ.
 *
 * Правило рисунков разборов: ответ с рисунка не читается. Пример 1 —
 * искомая точка в окне, но обе её координаты нецелые (не на линиях
 * сетки); пример 2 — точка за рамкой не ближе клетки (graph/hidden.js).
 * Рисунки — lib/theoryFigures.ts, их проверяет scripts/check-about-examples.mjs:
 * числа ниже и параметры рисунков — одни и те же.
 *
 * Метод во всех разборах один: формулы по рисунку → приравниваем →
 * один корень виден (общая точка в узле), второй по теореме Виета через
 * сумму корней → ордината подстановкой в более простую формулу и
 * проверкой во вторую → проверка на адекватность. Свободный член прямой
 * — m: буква b занята коэффициентом параболы (как в опорных задачах).
 *
 * Разметка внутри строк: $…$ — формула TeX, **…** — выделение.
 */

