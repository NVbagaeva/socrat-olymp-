function equate(lines: string[]) {
  return { label: 'Шаг 3. Приравниваем правые части', lines };
}

/** Шаг 4: один корень виден, второй — по Виету через сумму корней. */
function vieta(sum: string, sumTex: string, x2: string) {
  return {
    label: 'Шаг 4. Второй корень — по теореме Виета',
    paras: [
      `Один корень виден на рисунке: отмеченная точка $(2;\\, 0)$, $x_1 = 2$. Дискриминант не нужен — по теореме Виета сумма корней равна ${sum}:`,
    ],
    lines: [`x_1 + x_2 = ${sumTex}`, `x_2 = ${x2}`],
  };
}

/** Шаг 5: ордината — в более простую формулу, проверка — во вторую. */
function ordinate(simple: string, other: string, why: string) {
  return {
    label: 'Шаг 5. Ордината — подстановкой в более простую формулу',
    paras: [why],
    lines: [simple, other],
  };
}

