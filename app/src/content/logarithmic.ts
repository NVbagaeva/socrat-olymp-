/**
 * Подтема «Логарифмическая функция» задания №12: всё, чем она отличается
 * от подтемы «Линейная функция» по конфигу. Признаки стоят в
 * data/functionTypes.ts у записи logarithmic, тексты — здесь.
 *
 * Обозначения — как в открытом банке ФИПИ: f(x) = logₐ x,
 * f(x) = b + logₐ x, f(x) = logₐ(x + b).
 *
 * «Типы задач»: пять типов банка, каждая плашка раскрывает разбор.
 * Метод во всех разборах один: две отмеченные точки в узлах сетки →
 * система → показательная запись → a → формула с числом → b → формула
 * полностью → вычисление → проверка по графику. Ответ с рисунка не
 * читается: искомая точка за рамкой. Рисунки — lib/theoryFigures.ts
 * (log-ex-*), числа те же. Примеры — не из открытого банка.
 *
 * Разметка внутри строк: $…$ — формула TeX, **…** — выделение.
 */

