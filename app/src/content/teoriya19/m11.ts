/**
 * Глава метода 11 «Квадратные неравенства с параметром».
 *
 * Глава только про НЕРАВЕНСТВА. Уравнения с квадратным трёхчленом —
 * тип уравнения «степени не выше второй», теорема Виета, расположение
 * корней относительно числа и промежутка — разобраны в методе 9
 * (подметод «Квадратный трёхчлен»); здесь на них ссылка, и на них
 * глава строится: множество решений квадратного неравенства читается
 * по параболе, а вопрос «при всех x из отрезка» сводится либо к
 * расположению корней (метод 9), либо к наименьшему значению на отрезке.
 *
 * Подметоды (Glava19.podmetody):
 *
 *   1. общая идея — тип неравенства («степени не выше второй», если
 *      старший коэффициент может обратиться в нуль: сначала линейное
 *      неравенство) и множество решений по параболе: шесть картинок
 *      «знак A × знак D», строгое и нестрогое;
 *   2. на всей прямой — «при всех x», «не имеет решений», «имеет
 *      решение»: A > 0 и D < 0 плюс линейный случай; переход к
 *      отрицанию; D < 0 или D ≤ 0;
 *   3. на промежутке — «при всех x из отрезка / луча» (наименьшее
 *      значение: вершина внутри или вне; или расположение корней),
 *      «множество решений содержит отрезок», «хотя бы одно решение на
 *      отрезке» (через отрицание);
 *   4. множество решений — отрезок длины L, «все решения лежат на
 *      отрезке» (содержится — не путать с «содержит»), система
 *      квадратного и линейного неравенства;
 *   5. итоги — алгоритм, типичные ошибки, образец оформления.
 *
 * Все задачи составлены для раздела. Ответ каждой проверен перебором
 * параметра: scripts/verify_param/m11.py (id задач совпадают) — знак
 * левой части на густой сетке x (на всей прямой — до ±10⁷, на отрезке —
 * ровно по отрезку) плюс точные особые точки: вершина и концы
 * промежутка, где значение бывает ровно нулём, — так строгое
 * неравенство отличается от нестрогого. Там же — заведомо неверные
 * ответы (забыт линейный случай, «при всех x» без знака A, D ≤ 0
 * вместо D < 0, проверена только вершина вне отрезка, перепутаны
 * «содержит» и «содержится»), которые перебор обязан опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, корни, промежутки,
 * точки, объединения.
 *
 * Рисунки: парабола первым цветом, другое положение — третьим цветом
 * пунктиром, прямая (линейный случай) — вторым. Множество решений —
 * толстыми отрезками акцентного цвета на оси x, исключённые точки —
 * пустыми кружками; отрезок из условия — толстым отрезком цвета осей,
 * его концы — точками того же цвета.
 */

