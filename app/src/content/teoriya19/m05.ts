/** Боковая парабола x = c − y² — ломаной по точкам. */
function bokovaya(c: number, y: [number, number]): [number, number][] {
  const n = Math.ceil((y[1] - y[0]) / 0.04);
  return Array.from({ length: n + 1 }, (_, i) => {
    const v = y[0] + ((y[1] - y[0]) * i) / n;
    return [c - v * v, v];
  });
}

