/** Корень возрастающей или убывающей на [p; q] функции f(x) = c — делением пополам. */
function koren(f: (x: number) => number, c: number, p: number, q: number): number {
  let [l, r] = [p, q];
  const zl = Math.sign(f(l) - c);
  for (let i = 0; i < 80; i++) {
    const m = (l + r) / 2;
    if (Math.sign(f(m) - c) === zl) l = m;
    else r = m;
  }
  return (l + r) / 2;
}

