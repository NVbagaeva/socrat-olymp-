/**
 * Глава метода 13 «Свойства функций: непрерывность, монотонность, нечётность».
 *
 * Уравнение не решают «в лоб», а смотрят на свойства функций в нём.
 * Строго монотонная функция каждое значение принимает один раз — поэтому
 * f(u) = f(v) равносильно u = v, а уравнение f(x) = c имеет не больше
 * одного корня. Непрерывная функция на отрезке принимает все значения
 * между наименьшим и наибольшим — поэтому f(x) = a имеет решение ровно
 * при a ∈ E(f), а число корней складывается по кускам монотонности.
 * Нечётная монотонная функция: f(u) + f(v) = 0 равносильно u = −v.
 *
 * Глава опирается на другие и их не повторяет: «единственное решение» по
 * симметрии x → −x — метод 5 (чётность), границы частей уравнения —
 * метод 8 (оценка), расположение корней трёхчлена и замена — метод 9,
 * синус на отрезке — метод 12.
 *
 * Подметоды (Glava19.podmetody):
 *
 *   1. общая идея — суть и когда применять;
 *   2. монотонность: f(u) = f(v) ⇔ u = v, не больше одного корня,
 *      монотонность сумм и сложных функций, обратные функции;
 *   3. непрерывность: теорема о промежуточном значении, множество
 *      значений на отрезке [min; max], «имеет решение ⇔ a ∈ E(f)», счёт
 *      корней по кускам монотонности;
 *   4. нечётность: f(u) + f(v) = 0 ⇔ u = −v для нечётной монотонной f;
 *   5. итоги — алгоритм, типичные ошибки, образец оформления.
 *
 * Все задачи составлены для раздела. Ответ каждой проверен перебором
 * параметра: scripts/verify_param/m13.py (id задач совпадают) — корни
 * исходного уравнения, записанного как в условии (без сведения к u = v),
 * ищутся по x на отрезке из условия, концы отрезка проверяются точно,
 * касание считается одним корнем. Там же — заведомо неверные ответы
 * (конец E(f) не той строгости, E(f) по концам без вершины, двойной
 * корень за два, забытая область определения), которые перебор обязан
 * опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, корни, промежутки,
 * точки, объединения.
 *
 * Рисунки: график функции первым цветом — на отрезке из условия
 * сплошной, вне его пунктиром; горизонталь y = a вторым цветом, другое
 * положение — третьим пунктиром; множество значений E(f) — толстым
 * отрезком акцентного цвета на оси y; концы отрезка и вершины — точками
 * первого цвета, корни — точками цвета пересечения.
 */

