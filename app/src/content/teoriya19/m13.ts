/** Корни x³ − x + a = 0 (|a| < 2√3/9) — тригонометрической формулой. */
function korniKubicheskogo(a: number): number[] {
  const r = 2 / S3;
  const phi = Math.acos(((-3 * S3) / 2) * a);
  return [0, 1, 2].map((k) => r * Math.cos(phi / 3 - (2 * PI * k) / 3));
}

