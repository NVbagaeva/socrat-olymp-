  'График y = |x + 1| с вершиной A(−1; 0): при a = 0 прямая y = 0 касается его только в A; пунктиром — прямая y = −(x − 1)/2 (a = −1/2), общие точки B(−1/3; 2/3) и C(−3; 2)',
