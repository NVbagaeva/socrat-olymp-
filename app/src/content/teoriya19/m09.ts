/**
 * Глава метода 9 «Аналитический способ».
 *
 * Уравнение или неравенство решается напрямую, алгеброй, а параметр
 * остаётся буквой: корни выражаются через a явно, а там, где от a
 * зависит ход решения (старший коэффициент, знак выражения, на которое
 * делим, область определения, раскрытие модуля), решение ветвится на
 * случаи. Ответ — объединение ответов всех веток «дерева случаев».
 *
 * Плашка метода, три разбора, шесть опорных задач и девять заданий
 * тренировочной работы. Все задачи составлены для раздела. Ответ каждой
 * проверен перебором параметра: scripts/verify_param/m09.py (id задач
 * совпадают); корни там ищутся общим поиском по густой сетке x —
 * плотной около нуля и логарифмической до ±10⁷, чтобы корень, который
 * при старшем коэффициенте около нуля уходит далеко, не терялся.
 * Совпавшие корни перебор считает одной точкой, выколотые точки и
 * корни вне области определения — не корни. Там же — заведомо неверные
 * ответы (потерян случай a = 1, совпавший корень посчитан дважды,
 * посчитан корень вне области), которые перебор обязан опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, промежутки, отдельные
 * точки, объединения — без сумм вида $1+\sqrt3$.
 *
 * Рисунки: график левой части или две части уравнения — первым и вторым
 * цветом, другое значение параметра — третьим цветом пунктиром;
 * корни — точками с буквами, выколотые точки — пустыми кружками.
 */

