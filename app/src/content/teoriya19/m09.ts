/**
 * Глава метода 9 «Аналитический способ».
 *
 * Аналитический способ — общее название рассуждений о числе корней
 * «по формулам», без картинки как главного аргумента. Глава большая и
 * разбита на подметоды (Glava19.podmetody), у каждого свои карточки,
 * разборы, опорные и задания:
 *
 *   1. общая идея — дерево случаев и как выбрать подметод;
 *   2. линейные уравнения kx = b и сводящиеся к ним (дробь, модуль);
 *   3. замена t = g(x): сколько корней x даёт один корень t, и как
 *      «ровно n корней по x» переводится в условия на корни по t;
 *   4. квадратный трёхчлен — главный блок: сначала тип уравнения
 *      («степени не выше второй», если старший коэффициент может
 *      обратиться в нуль), затем теорема Виета и расположение корней
 *      относительно числа и промежутка — по параболе;
 *   5. итоги — алгоритм, типичные ошибки, образец оформления.
 *
 * Явные корни x(a), которые проверяют на ограничения, отмечая их на
 * прямой параметра, — это метод 10 «Метод прямой параметра»; здесь на
 * него только ссылка.
 *
 * Все задачи составлены для раздела. Ответ каждой проверен перебором
 * параметра: scripts/verify_param/m09.py (id задач совпадают); корни
 * там ищутся общим поиском по густой сетке x — плотной около нуля и
 * логарифмической до ±10⁷, чтобы корень, который при старшем
 * коэффициенте около нуля уходит далеко, не терялся. Совпавшие корни
 * считаются одной точкой, выколотые точки и корни вне области — не
 * корни. Там же — заведомо неверные ответы (забыт случай «старший
 * коэффициент — нуль», забыто D ≥ 0, «оба корня внутри» через
 * f(p)·f(q) < 0, неверный перевод корней t в корни x, потерян
 * граничный случай), которые перебор обязан опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, промежутки, точки,
 * объединения.
 *
 * Рисунки: парабола-схема для каждого расположения корней — первым
 * цветом; число M или концы промежутка — точками на оси, промежуток —
 * толстым отрезком; другое положение — третьим цветом пунктиром.
 */

