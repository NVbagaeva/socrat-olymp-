function okr(
  cx: number,
  cy: number,
  r: number,
  cvet = 'lineA',
  style: 'solid' | 'dashed' = 'solid',
): Figura19 {
  return { type: 'circle', at: [cx, cy], radius: r, color: cvet, width: 3.2, style };
}

/** Точки кривой y = f(x) на [ot; do] — для границы закрашенной области. */
function vyborka(f: (x: number) => number, ot: number, dO: number, n = 80): [number, number][] {
  return Array.from({ length: n + 1 }, (_, i) => {
    const x = ot + ((dO - ot) * i) / n;
    return [x, f(x)] as [number, number];
  });
}

