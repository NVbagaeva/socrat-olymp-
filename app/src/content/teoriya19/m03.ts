const XA: [string, string] = ['x', 'a'];

/** Край полосы p ≤ x ≤ q: тонкий тёмный пунктир — не спутать с прямыми a = c. */
function polosa(c: number, y: [number, number]) {
  return otrezokNa(c, y[0], c, y[1], 'cross', 'dashed', 1.4);
}

/** Окно на плоскости (x; a). */
function okno(
  x: [number, number],
  y: [number, number],
  deleniya?: { x?: number[]; y?: number[] },
): Okno19 {
  return { x, y, osi: XA, ...(deleniya === undefined ? {} : { deleniya }) };
}

