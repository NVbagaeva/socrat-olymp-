/**
 * Глава метода 14 «Метод упрощающего значения».
 *
 * В задаче есть значение переменной (или параметра, или второй
 * переменной), при котором она резко упрощается: x = 0, x = 1, x = a,
 * нуль скобки перед параметром, нуль модуля, заданный корень, известная
 * точка системы. Подставляем это значение — получаем уравнение или
 * неравенство на параметр (кандидатов) или уравнение, распавшееся на
 * простые, — и обязательно проверяем, выполнено ли всё требование задачи.
 *
 * Отличие от метода 7 (инвариант): там свойство требуется при ВСЕХ
 * значениях переменной, и подстановки удобных значений дают только
 * необходимые условия. Здесь значение выбирается ОДНО — потому что оно
 * названо в условии или потому что при нём исчезает параметр, — и
 * надо понимать, что именно даёт подстановка: равносильное условие
 * («x₀ — корень»), достаточное («нашёлся корень при любом b») или
 * необходимое («при b = 0 корень обязан быть»). Глава ссылается на
 * метод 10 (счёт корней, выписанных явно) и метод 7 и их не повторяет.
 *
 * Подметоды (Glava19.podmetody):
 *
 *   1. общая идея — суть, когда применять, как выбрать значение и что
 *      даёт подстановка; отличие от метода 7;
 *   2. упрощающее значение переменной: заданный корень x = x₀ или
 *      решение неравенства, x = a; область определения в этой точке;
 *   3. значение, обнуляющее множитель или модуль: при нём параметр
 *      исчезает, это корень при любом a, остальное — после деления;
 *      «решение при любом b» — что даёт x, обнуляющий b, и что даёт b = 0;
 *   4. удобное значение параметра: уравнение — квадратное относительно a,
 *      оно даёт явные семейства корней x(a); счёт — как в методе 10;
 *   5. система: подстановка известной точки — кандидаты, затем проверка
 *      остальных решений;
 *   6. итоги — алгоритм, типичные ошибки, образец оформления.
 *
 * Все задачи составлены для раздела. Ответ каждой проверен перебором
 * параметра: scripts/verify_param/m14.py (id задач совпадают) —
 * неравенство или уравнение подставляется в заданной точке как в
 * условии, число корней ищется по x на сетке у исходного уравнения,
 * «при любом b» — по сетке b. Там же — заведомо неверные ответы
 * (кандидаты без проверки, значение вне области, только достаточное
 * условие за ответ, совпавшие корни дважды), которые перебор обязан
 * опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, корни, промежутки,
 * точки, объединения.
 *
 * Рисунки: график или семейство графиков первым цветом, найденное
 * значение — вторым, отброшенный кандидат — третьим пунктиром; точка,
 * где проверяется условие, — акцентом (выполнено) или цветом
 * пересечения (нарушено).
 */

