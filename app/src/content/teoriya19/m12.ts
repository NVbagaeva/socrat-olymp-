/**
 * Глава метода 12 «Тригонометрические уравнения с параметром».
 *
 * Неизвестная стоит под синусом, косинусом или тангенсом. От
 * алгебраических уравнений такие отличаются двумя вещами: значения
 * синуса и косинуса ограничены отрезком [−1; 1], а корней из-за
 * периода бесконечно много — поэтому вопрос почти всегда «сколько
 * корней на отрезке», и отвечает на него картинка: дуга промежутка на
 * единичной окружности или кусок графика.
 *
 * Глава опирается на методы 8–10 и их не повторяет: таблица «сколько
 * корней x даёт корень t» и расположение корней трёхчлена — метод 9
 * (подметоды «Замена» и «Квадратный трёхчлен»), явные корни и счёт на
 * прямой параметра — метод 10, оценка — метод 8. Здесь — что из этого
 * следует для синуса, косинуса и тангенса на заданном промежутке.
 *
 * Подметоды (Glava19.podmetody):
 *
 *   1. общая идея — суть и когда применять;
 *   2. простейшие sin x = a, cos x = a, tg x = a: когда есть решения,
 *      сколько корней на промежутке — окружность и график, концы
 *      промежутка, a = ±1 — один корень на периоде; таблица
 *      соответствия «промежуток × значение t → число корней x»;
 *   3. замена t = sin x (cos x, tg x): ограничение на t, перевод «ровно
 *      n корней x» в условия на корни t, трёхчлен — инструментами
 *      методов 9 и 10;
 *   4. a sin x + b cos x = c — вспомогательный угол, |c| ≤ √(a² + b²),
 *      сдвиг отрезка;
 *   5. ограниченность — сумма квадратов, области значений (см. метод 8);
 *   6. отбор корней серии на отрезке, когда параметр стоит в аргументе;
 *   7. итоги — алгоритм, типичные ошибки, образец оформления.
 *
 * Все задачи составлены для раздела. Ответ каждой проверен перебором
 * параметра: scripts/verify_param/m12.py (id задач совпадают) — корни
 * исходного уравнения ищутся по x ровно на промежутке из условия
 * (замкнутый конец в сетке точно, открытый — исключён), касание
 * sin x = 1 считается одним корнем, совпавшие корни — одной точкой. Там
 * же — заведомо неверные ответы (забыто |t| ≤ 1, корни x посчитаны по
 * числу корней t, t = ±1 за два корня, конец промежутка, совпадение
 * корней t), которые перебор обязан опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, корни, промежутки,
 * точки, объединения; числа π в ответах нет.
 *
 * Рисунки: единичная окружность первым цветом — дуга промежутка
 * сплошная, остальное пунктиром (risunok.duga), как график вне отрезка;
 * прямая y = t (x = t для косинуса) вторым цветом, другое положение —
 * третьим пунктиром; корни — точки цвета пересечения, точки прямой вне
 * дуги — пустыми кружками, концы промежутка — точками первого цвета.
 * Деления осей — доли π строкой (deleniya парами [где, подпись]).
 */

