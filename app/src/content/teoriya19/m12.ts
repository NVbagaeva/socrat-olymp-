/** Точка окружности под углом x. */
const NA_KRUGE = (
  x: number,
  bukva: string | null,
  vykolota = false,
  cvet: Tochka19['color'] = 'cross',
) => tochka(Math.cos(x), Math.sin(x), bukva, vykolota, cvet);

/**
 * Состав рисунка на единичной окружности: дуга промежутка [ot; do]
 * сплошная, остальная окружность — пунктиром (без дуги — вся окружность
 * сплошная). Сцену собирает scena(OKNO_KRUG, …) с подписью для диктора.
 */
function naKruge(
  dugaX: [number, number] | null,
  sostav: { curves?: Krivaya19[]; points?: Tochka19[]; shapes?: Figura19[] },
) {
  const okr =
    dugaX === null
      ? [okruzhnost(0, 0, 1, 'lineA')]
      : [
          duga(0, 0, 1, dugaX[1], dugaX[0] + 2 * PI, 'lineA', 'dashed'),
          duga(0, 0, 1, dugaX[0], dugaX[1], 'lineA'),
        ];
  return {
    curves: [...okr, ...(sostav.curves ?? [])],
    shapes: sostav.shapes ?? [],
    points: sostav.points ?? [],
  };
}

