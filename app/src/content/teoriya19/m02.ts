/* ── Фигуры ───────────────────────────────────────────────────────── */

function okr(
  cx: number,
  cy: number,
  r: number,
  cvet = 'lineA',
  style: 'solid' | 'dashed' = 'solid',
): Figura19 {
  return { type: 'circle', at: [cx, cy], radius: r, color: cvet, width: 3.2, style };
}

function krug(cx: number, cy: number, r: number, cvet = 'lineA'): Figura19 {
  return {
    type: 'circle',
    at: [cx, cy],
    radius: r,
    color: cvet,
    width: 3.2,
    fill: cvet,
    fillOpacity: 0.12,
  };
}

function otrezok(
  p: [number, number],
  q: [number, number],
  cvet = 'lineA',
  style: 'solid' | 'dashed' = 'solid',
): Figura19 {
  return { type: 'segment', from: p, to: q, color: cvet, width: 3.2, style };
}

function romb(a: number, b: number, cvet = 'lineA'): Figura19[] {
  const v: [number, number][] = [
    [a, 0],
    [0, b],
    [-a, 0],
    [0, -b],
  ];
  return v.map((p, i) => otrezok(p, v[(i + 1) % 4]!, cvet));
}

const polu =
  (r: number, cx = 0, cy = 0) =>
  (x: number) => {
    const v = r * r - (x - cx) * (x - cx);
    return v < 0 ? null : Math.sqrt(v) + cy;
  };

