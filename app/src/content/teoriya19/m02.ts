/** Ромб p|x − x0| + q|y| = r: вершины по кругу. */
function romb(x0: number, polX: number, polY: number): [number, number][] {
  return [
    [x0 + polX, 0],
    [x0, polY],
    [x0 - polX, 0],
    [x0, -polY],
  ];
}

