/** Верхняя полуокружность радиуса r с центром O. */
function poluokr(r: number) {
  return (x: number) => Math.sqrt(Math.max(0, r * r - x * x));
}

/** Гипербола y = c/x; около асимптоты x = 0 не рисуется. */
function giperbola(c: number) {
  return (x: number) => (Math.abs(x) < 0.12 ? null : c / x);
}

const GIP_MOD = (x: number) => (Math.abs(x) < 0.12 ? null : 1 / Math.abs(x));

