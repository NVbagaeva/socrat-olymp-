/**
 * Глава метода 10 «Метод прямой параметра».
 *
 * Метод для уравнений с ограничениями (корень, логарифм, знаменатель)
 * и для вопросов о корнях на отрезке. Три хода: корни находятся явно,
 * формулами x₁(a), x₂(a), … — квадратный трёхчлен с параметром
 * раскладывается через дискриминант (часто полный квадрат по a) или по
 * теореме Виета; каждый корень проверяется по ограничениям — у него своё
 * множество значений a; и только потом всё сводится на одну прямую
 * параметра: полоса на каждый корень, особые точки (границы полос и
 * совпадения корней), число различных корней на каждом промежутке и в
 * каждой особой точке. Число корней в особой точке считается
 * подстановкой, а не читается по закрашенному концу полосы.
 *
 * От метода 9 (аналитический способ) глава отличается тем, что дерева
 * случаев нет: корни найдены сразу, вся работа — проверка корней и счёт
 * на прямой параметра.
 *
 * Плашка метода, три разбора, пять опорных задач и девять заданий
 * тренировочной работы. Все задачи составлены для раздела. Ответ каждой
 * проверен перебором параметра: scripts/verify_param/m10.py (id задач
 * совпадают) — корни исходного уравнения ищутся по x, ограничения дают
 * nan, совпавшие корни считаются одной точкой. Там же — заведомо неверные
 * ответы (пропущено совпадение корней, граница решена по закраске точки,
 * не проверено ограничение), которые перебор обязан опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, промежутки, отдельные
 * точки, объединения.
 *
 * Рисунки — прямая параметра (risunok.pryamayaParametra): ось a, над ней
 * по полосе на корень (закрашенный конец входит, пустой — нет), пунктиром
 * особые точки, сверху число корней: серым — на промежутках, акцентным
 * цветом — в особых точках.
 */

