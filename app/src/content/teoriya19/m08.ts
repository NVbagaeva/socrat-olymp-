/**
 * Глава метода 8 «Метод оценки».
 *
 * Обе части уравнения оцениваются числом: если f(x) ≤ M ≤ g(x) на всей
 * области, то f(x) = g(x) ⇔ f(x) = M и g(x) = M одновременно (метод
 * мини-максов). Те же оценки дают «сумма неотрицательных равна нулю ⇔
 * каждое слагаемое — нуль» и множество значений выражения: уравнение
 * f(x) = c разрешимо, когда c между наименьшим и наибольшим значением f.
 * Параметр входит в границу оценки: ответ — те a, при которых границы
 * сходятся и достигаются в одной и той же точке.
 *
 * Плашка метода, три разбора, пять опорных задач и девять заданий
 * тренировочной работы. Все задачи составлены для раздела. Ответ каждой
 * проверен перебором параметра: scripts/verify_param/m08.py (id задач
 * совпадают); корни там ищутся на густой сетке по x и, кроме того, точно
 * в точках, где обе части могут коснуться (как x = 0 в проверке метода 5).
 * Там же — заведомо неверные ответы (значения, при которых границы равны,
 * но достигаются в разных точках; неточная оценка; потерянная область),
 * которые перебор обязан опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, $\sqrt2$, промежутки,
 * пустое множество — без сумм вида $1+\sqrt3$.
 *
 * Рисунки: две части уравнения — первым и вторым цветом, граница оценки
 * y = M — вспомогательным пунктиром; при отброшенном значении — третий
 * цвет пунктиром; точка касания — буквой.
 */

