const PI = Math.PI;

const COS_PI = (x: number) => Math.cos(PI * x);

/** √(x² − 5x + 4) + |(x − 2)(x − a)| — левая часть разбора 2; на (1; 4) не определена. */
const G_R2 = (a: number) => (x: number) => {
  const p = x * x - 5 * x + 4;
  return p < 0 ? null : Math.sqrt(p) + Math.abs((x - 2) * (x - a));
};

/** x + 1/x; около нуля не рисуется. */
const X_1X = (x: number) => (Math.abs(x) < 0.15 ? null : x + 1 / x);

