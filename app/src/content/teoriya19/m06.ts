/** Квадрат (ромб) |x| + |y| = c — ломаной по вершинам. */
function romb(c: number): [number, number][] {
  return [
    [c, 0],
    [0, c],
    [-c, 0],
    [0, -c],
  ];
}

/** Корень непрерывной f на [lo; hi] со сменой знака — делением пополам. */
function koren(f: (x: number) => number, lo: number, hi: number): number {
  let a = lo;
  let b = hi;
  for (let i = 0; i < 80; i++) {
    const m = (a + b) / 2;
    if (Math.sign(f(m)) === Math.sign(f(a))) a = m;
    else b = m;
  }
  return (a + b) / 2;
}

