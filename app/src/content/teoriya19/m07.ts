/**
 * Глава метода 7 «Метод инварианта».
 *
 * Свойство должно выполняться при всех значениях какой-то переменной:
 * «неравенство верно при всех x», «x = 1 — корень при любом b»,
 * «выражение не зависит от x», «функция чётная». Значит, оно выполняется
 * и при удобных значениях этой переменной (x = 0, π/2, π, b = 0, вершина,
 * нуль модуля): подстановки дают необходимые условия на параметр, а потом
 * каждый кандидат проверяется для всех значений переменной.
 *
 * Плашка метода, три разбора, пять опорных задач и девять заданий
 * тренировочной работы. Все задачи составлены для раздела. Ответ каждой
 * проверен перебором параметра: scripts/verify_param/m07.py (id задач
 * совпадают); «при всех x» там проверяется на густой сетке по x и точно
 * в особых точках, «при любом b» — на сетке по b. Там же — заведомо
 * неверные ответы (кандидаты одной подстановки, необходимые условия,
 * принятые за ответ), которые перебор обязан опровергнуть.
 *
 * Ответы записаны так, чтобы их разбирала общая автопроверка
 * (lib/zadanie16/otvet.ts, chislo16): целые, дроби, промежутки с
 * бесконечностью, пустое множество $\varnothing$ — без сумм вида $1+\sqrt3$.
 *
 * Рисунки: при найденном значении — второй цвет, при отброшенном
 * кандидате — третий цвет пунктиром; точки, где проверяется свойство, —
 * буквами.
 */

