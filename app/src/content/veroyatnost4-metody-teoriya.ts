/** Короткий пример под правилом: у правила всегда есть разобранный случай. */
export interface MiniPrimer {
  tekst: string;
  formula?: string;
}

/** Рамка с правилом: текст, формула и пример с обоснованием. */
export interface RamkaPravila {
  vid: VidRamki;
  title: string;
  tekst: string[];
  formula?: string;
  podpis?: string;
  primer: MiniPrimer;
}

/** Шаг решения: что делаем и зачем — словами, ниже формула. */
export interface Shag {
  tekst: string;
  formula?: string;
}

/** Разобранная задача главы. Картинка — primery/<id>-360.webp. */
export interface ZadachaMetoda {
  id: string;
  metka: string;
  uslovie: string;
  kartinkaAlt: string;
  shagi: Shag[];
  /** Ответ так, как его пишут в бланк: «0,35». */
  otvet: string;
  proverka: string;
}

export interface OshibkaMetoda {
  title: string;
  neverno: string;
  pochemu: string;
  verno: string;
}

export interface GlavaMetoda4 {
  /** Метод списка А: id из lib/veroyatnost/metody4.ts. */
  metod: string;
  /** Картинка карточки: metody/<kartinka>-240.webp. */
  kartinka: string;
  kartinkaAlt: string;
  kogda: { lead: string; slova: string[]; primer: MiniPrimer };
  /** Главная рамка — определение или формула метода. */
  glavnaya: RamkaPravila;
  /** Вторая рамка: что такое исход, таблица, дерево, лайфхак. */
  dopolnenie: RamkaPravila;
  algoritm: string[];
  zadachi: ZadachaMetoda[];
  /** Связь с соседним заданием (глава 5 → теория №5). */
  svyaz?: RamkaPravila & { ssylka: string };
  oshibki: OshibkaMetoda[];
  interaktiv: { lead: string };
}

