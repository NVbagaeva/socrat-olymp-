import type { StsenaId } from '@/lib/proizvodnaya/stseny';
import type { Gruppa } from '@/lib/proizvodnaya/types';

const TG = '\\operatorname{tg}';

/* ── Блоки ───────────────────────────────────────────────────── */

export interface PText {
  type: 'text';
  paras: string[];
  /** Первый абзац крупнее — вводная строка раздела. */
  lead?: boolean;
}

export interface PMainFormula {
  type: 'main-formula';
  chip: string;
  formula: string;
  note: string;
  figure?: StsenaId;
}

export interface PStep {
  no: string;
  title: string;
  paras?: string[];
  /** Итог шага в рамке. */
  boxed?: string;
}

export interface PSteps {
  type: 'steps';
  items: PStep[];
}

export interface PRemember {
  type: 'remember';
  title?: string;
  paras: string[];
}

export interface PMemo {
  type: 'memo';
  items: string[];
}

/** Подраздел с якорем: на него ведёт подпункт «Содержания». */
export interface PSub {
  type: 'sub';
  id: string;
  no: string;
  title: string;
  blocks: PBlock[];
}

export interface PExampleStep {
  label: string;
  paras?: string[];
  lines?: string[];
  /** Проверка на здравый смысл выделена своим цветом. */
  check?: boolean;
}

/** Разобранный пример с рисунком сцены. */
export interface PExample {
  type: 'example';
  title: string;
  condition: string;
  figure: StsenaId;
  steps: PExampleStep[];
  answer: string;
}

/** Разобранный пример из реестра прототипов: k-й прототип группы. */
export interface PProto {
  type: 'proto';
  gruppa: Gruppa;
  /** Номер прототипа внутри группы, с нуля. */
  nomer: number;
  title: string;
}

/** Два рисунка рядом с подписями. */
export interface PPair {
  type: 'pair';
  items: { figure: StsenaId; caption: string }[];
}

export interface PFigure {
  type: 'figure';
  figure: StsenaId;
  caption?: string;
}

/** Таблица «вопрос — где смотреть». Заголовки и ячейки — со строками $…$. */
export interface PTable {
  type: 'table';
  head: string[];
  rows: string[][];
}

export type PBlock =
  | PText
  | PMainFormula
  | PSteps
  | PRemember
  | PMemo
  | PSub
  | PExample
  | PProto
  | PPair
  | PFigure
  | PTable;

export interface RazdelTeorii9 {
  /** Идентификатор: он же якорь прокрутки. */
  id: string;
  /** Название в «Содержании» и в заголовке раздела: без формул. */
  title: string;
  blocks: PBlock[];
}

