/**
 * Разборы основных типов задач про параболу на вкладке «О задании»
 * квадратичной подтемы: знак $a$, значение $a$, свободный член $c$,
 * коэффициент $b$, формула по графику, значение функции, аргумент по
 * значению. Плашки с разборами собираются в content/quadraticTypes.ts.
 *
 * Метод в каждом разборе — тот же, что в карточках «Ключевых методов»
 * (content/quadraticMetody.ts): вершина $(m;\, n)$, запись через вершину
 * $a(x - m)^2 + n$, шаг от вершины, формула вершины $x_{\text{в}} = -b/(2a)$.
 * Расхождений с карточками быть не должно: ученик читает их подряд.
 *
 * Правило рисунков — как у разборов пересечений: ответ с рисунка не
 * читается. Значение функции и аргумент — по два примера: ответ в окне,
 * но не в узле сетки, и ответ за рамкой не ближе клетки
 * (graph/hidden.js). У остальных типов — один пример. Числа и рисунки —
 * lib/quadraticBasics.ts и lib/theoryFigures.ts; их пересчитывает
 * scripts/check-about-examples.mjs.
 *
 * Разметка внутри строк: $…$ — формула TeX, **…** — выделение.
 */

