/** Запись через вершину по рисунку: вершина и узел, шаг от вершины. */
function vertexStep(
  label: string,
  vertex: string,
  node: string,
  dx: string,
  dy: string,
  a: string,
) {
  return {
    label,
    paras: [
      `Вершина $(m;\\, n) = ${vertex}$. Отмечен узел $${node}$: сдвиг от вершины $\\Delta x = ${dx}$, $\\Delta y = ${dy}$.`,
    ],
    lines: [`a = ${dy} : ${dx}^2 = ${a}`],
  };
}

