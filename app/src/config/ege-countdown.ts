/**
 * Обратный отсчёт до ЕГЭ по математике — плашка на главной
 * (components/landing/otschyot). Все даты, время и подписи — здесь.
 *
 * ┌────────────────────────────────────────────────────────────────────┐
 * │ Проект расписания, после утверждения приказа проверить.            │
 * │                                                                    │
 * │ Дата 7 июня 2027 — из ПРОЕКТА расписания ЕГЭ-2027 (математика      │
 * │ базового и профильного уровней). Когда приказ утвердят:            │
 * │   1) сверить `data` и `vremya` у первой цели и у пересдачи;        │
 * │   2) поставить им `proekt: false` — строка «по проекту расписания  │
 * │      ЕГЭ-2027» под отсчётом пропадёт.                              │
 * └────────────────────────────────────────────────────────────────────┘
 *
 * Время — московское, как в расписании: отсчёт у ученика в любом
 * часовом поясе один и тот же. Цели идут по порядку дат; когда день
 * экзамена прошёл, плашка сама переходит к следующей. Когда кончатся
 * все — плашка исчезает с главной, поэтому в конце списка всегда держим
 * экзамен следующего учебного года.
 */

export type EgeCel = {
  /** Короткое имя цели — для тестов и разметки. */
  id: string;
  /** День экзамена по Москве: ГГГГ-ММ-ДД. */
  data: string;
  /** Начало экзамена по Москве: ЧЧ:ММ. */
  vremya: string;
  /**
   * Подпись над отсчётом — без слова «осталось»: его плашка дописывает
   * сама и согласует с числом («остался 21 день», «осталось 5 дней»).
   */
  podpis: string;
  /** С какого дня считать кольцо «пройдено учебного года»: ГГГГ-ММ-ДД. */
  nachaloGoda: string;
  /** Подпись последних суток. */
  zavtra: string;
  /** Строка под отсчётом в последние сутки. */
  zavtraSovet: string;
  /** День экзамена: заголовок и строка под ним. */
  segodnya: string;
  segodnyaTekst: string;
  /** Дата прописью для дня экзамена — в центре кольца. */
  dataSlovami: string;
  /** Мелкая строка под отсчётом; видна, пока `proekt: true`. */
  primechanie: string;
  /** true — дата не утверждена, показываем `primechanie`. */
  proekt: boolean;
};

