/**
 * Проекция пространства на плоскость чертежа.
 *
 * Одна на весь раздел: косоугольная (кабинетная) проекция — та самая,
 * которой рисуют стереометрию в учебниках.
 *
 *   X = x + a·y,   Y = −(z + b·y)
 *
 * Почему именно она. Требование к чертежу такое: переднее ребро
 * основания AB горизонтально, ребро AD уходит по диагонали в глубину,
 * вертикальные рёбра вертикальны. Все три условия сразу ортогональная
 * проекция дать не может: если в ней горизонтально ложится одно
 * направление горизонтальной плоскости, перпендикулярное ему встаёт
 * строго вертикально и сливается с боковыми рёбрами. Косоугольная даёт
 * все три, потому что направление проецирующих лучей не перпендикулярно
 * плоскости чертежа.
 *
 * Что это стоит: шар проецируется не в круг, а в эллипс, вытянутый
 * примерно на 8 %, а горизонтальная окружность — в эллипс, наклонённый
 * примерно на 4°. Оба числа — плата за горизонтальное AB, и оба
 * настраиваются одним параметром DEPTH_SCALE.
 *
 * Оси в пространстве: x вправо, y в глубину (от зрителя), z вверх.
 */

import { type Vec2, type Vec3, cross, dot, normalize } from './vec';

/** Угол оси глубины на чертеже, от горизонтали. Как в старых чертежах. */
const DEPTH_ANGLE = (60 * Math.PI) / 180;
/** Сокращение по глубине: отрезок в глубину рисуется во столько раз короче. */
const DEPTH_SCALE = 0.4;

/** Горизонтальная составляющая оси глубины. */
export const DEPTH_X = DEPTH_SCALE * Math.cos(DEPTH_ANGLE);
/** Вертикальная составляющая оси глубины. */
export const DEPTH_Y = DEPTH_SCALE * Math.sin(DEPTH_ANGLE);

/** Точка чертежа: X вправо, Y вниз, как в SVG. */
export function project(p: Vec3): Vec2 {
  return [p[0] + DEPTH_X * p[1], -(p[2] + DEPTH_Y * p[1])];
}

/**
 * Направление на зрителя — вдоль проецирующего луча.
 * Проверка: project(p + t·TOWARD) = project(p) при любом t.
 */
export const TOWARD: Vec3 = normalize([DEPTH_X, -1, DEPTH_Y]);

/** Глубина: у более близкой к зрителю точки больше. */
export function depth(p: Vec3): number {
  return dot(p, TOWARD);
}

/**
 * Любая точка проецирующего луча, проходящего через точку чертежа.
 * Нужна тем проверкам видимости, которые ищут пересечение луча с телом.
 */
export function rayPoint(q: Vec2): Vec3 {
  return [q[0], 0, -q[1]];
}

/** Точка горизонтальной окружности: угол отсчитывается от оси x. */
export function circlePoint(center: Vec3, r: number, u: number): Vec3 {
  return [center[0] + r * Math.cos(u), center[1] + r * Math.sin(u), center[2]];
}

/**
 * Угол контурной образующей цилиндра: там горизонтальная нормаль
 * перпендикулярна лучу зрения. Второй контур — на π больше.
 */
export const SILHOUETTE = Math.atan(DEPTH_X);

/**
 * Ближняя половина горизонтальной окружности: нормаль смотрит
 * на зрителя, значит точка видна, а не спрятана телом.
 */
export function nearSide(u: number): boolean {
  return Math.sin(u - SILHOUETTE) < 0;
}

/**
 * Насколько контурная образующая конуса отстоит от контура цилиндра:
 * sin ψ = r·b / (h·√(1+a²)), где h — высота до вершины.
 * У конуса вершиной вверх образующие уходят за контур, вершиной вниз
 * (сосуд) — наоборот, поэтому знак задаёт вызывающая сторона.
 */
export function coneTangent(r: number, apexHeight: number): number {
  const s = (r * DEPTH_Y) / (apexHeight * Math.hypot(1, DEPTH_X));
  return Math.asin(Math.max(-1, Math.min(1, s)));
}

/* Пара единичных векторов плоскости, перпендикулярной лучу зрения:
   в ней лежит контур шара. */
const RING_X: Vec3 = normalize([TOWARD[1], -TOWARD[0], 0]);
const RING_Y: Vec3 = normalize(cross(TOWARD, RING_X));

/**
 * Точка контура шара: большой круг, перпендикулярный лучу зрения.
 * Угол 0 — правая точка контура, дальше против часовой стрелки.
 */
export function spherePoint(center: Vec3, r: number, u: number): Vec3 {
  const x = -Math.cos(u);
  const y = Math.sin(u);
  return [
    center[0] + r * (x * RING_X[0] + y * RING_Y[0]),
    center[1] + r * (x * RING_X[1] + y * RING_Y[1]),
    center[2] + r * (x * RING_X[2] + y * RING_Y[2]),
  ];
}
