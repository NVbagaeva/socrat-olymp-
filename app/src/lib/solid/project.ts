/**
 * Проекция пространства на плоскость чертежа.
 *
 * Одна на весь раздел: ортогональная (параллельная) проекция, взгляд
 * спереди-справа и чуть сверху. Почему такая, а не «кабинетная»
 * из учебника:
 *
 * - сфера остаётся кругом, а горизонтальная окружность — правильным
 *   эллипсом с горизонтальной большой осью, как рисуют цилиндры
 *   и конусы в учебниках; в косоугольной проекции эллипс наклонён,
 *   а шар вытянут;
 * - вертикальные рёбра остаются вертикальными;
 * - параллельные прямые остаются параллельными, отношения отрезков
 *   на одной прямой сохраняются — на чертеже можно ставить середины;
 * - одни и те же формулы дают и многогранники, и тела вращения, и их
 *   комбинации: видимость считается в одном пространстве.
 *
 * Углы подобраны так, чтобы ни одно ребро правильного основания
 * (треугольник, квадрат, шестиугольник) не ложилось вдоль луча зрения:
 * самое сокращённое ребро сохраняет не меньше 0,6 своей длины, а у
 * пятиугольника — 0,46. Основание цилиндра — эллипс с отношением осей
 * около 0,42, вертикаль сокращается до 0,91, переднее ребро
 * параллелепипеда наклонено примерно на 14°.
 */

import { type Vec2, type Vec3, dot } from './vec';

/** Поворот вокруг вертикали: зритель смещён вправо от передней грани. */
const AZIMUTH = (30 * Math.PI) / 180;
/** Подъём взгляда над горизонтом. */
const ELEVATION = (25 * Math.PI) / 180;

const cosA = Math.cos(AZIMUTH);
const sinA = Math.sin(AZIMUTH);
const cosE = Math.cos(ELEVATION);
const sinE = Math.sin(ELEVATION);

/** Экранная ось X в пространстве (единичная). */
export const RIGHT: Vec3 = [cosA, sinA, 0];
/** Экранная ось Y в пространстве: вверх по чертежу. */
export const UP: Vec3 = [-sinA * sinE, cosA * sinE, cosE];
/** Направление к зрителю: чем больше глубина по нему, тем ближе точка. */
export const TOWARD: Vec3 = [sinA * cosE, -cosA * cosE, sinE];

/** Точка чертежа: X вправо, Y вниз, как в SVG. */
export function project(p: Vec3): Vec2 {
  return [dot(p, RIGHT), -dot(p, UP)];
}

/** Глубина к зрителю: у более близкой точки больше. */
export function depth(p: Vec3): number {
  return dot(p, TOWARD);
}

/** Сжатие горизонтальной окружности по вертикали чертежа. */
export const ELLIPSE_RATIO = sinE;
/** Сжатие вертикального отрезка. */
export const VERTICAL_RATIO = cosE;

/**
 * Угол на горизонтальной окружности, отсчитанный от экранной оси X.
 * Точка окружности радиуса r с центром c: c + r·(cos u·RIGHT_H + sin u·DEPTH_H),
 * где на чертеже она даёт (r cos u, −r sin φ sin u): u = 0 — самая правая
 * точка, u = π/2 — самая дальняя (верхняя на чертеже).
 */
export function circlePoint(center: Vec3, r: number, u: number): Vec3 {
  return [
    center[0] + r * (Math.cos(u) * cosA - Math.sin(u) * sinA),
    center[1] + r * (Math.cos(u) * sinA + Math.sin(u) * cosA),
    center[2],
  ];
}

/** Угол u для направления, заданного в пространстве (горизонтальная составляющая). */
export function circleAngle(dir: Vec3): number {
  const x = dir[0] * cosA + dir[1] * sinA;
  const y = -dir[0] * sinA + dir[1] * cosA;
  return Math.atan2(y, x);
}
