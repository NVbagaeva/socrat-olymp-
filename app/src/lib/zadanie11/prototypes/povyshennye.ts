/** Минуты как часы: 160 мин → «2 ч 40 мин» и дробь 8/3. */
function chasyMinuty(m: number): string {
  const h = Math.floor(m / 60);
  const mm = m % 60;
  return `${h > 0 ? `${h} ч` : ''}${h > 0 && mm > 0 ? ' ' : ''}${mm > 0 ? `${mm} мин` : ''}`;
}

/**
 * Два мастера: первый делает на r деталей в час меньше второго; заказ
 * из N₁ деталей первый делает на tm минут дольше, чем второй — заказ из
 * N₂ деталей. ask 'vtoroy' — производительность второго, 'pervyy' —
 * первого. Подвох — разница во времени в минутах: перевести в часы, а
 * отрицательный корень квадратного уравнения отбросить.
 */
export function mastera(p: Record<string, number | string>): Solved {
  const r = num(p, 'r');
  const N1 = num(p, 'N1');
  const N2 = num(p, 'N2');
  const tm = num(p, 'tm');
  const ask = str(p, 'ask', ['vtoroy', 'pervyy'] as const);
  const tq = q(tm, 60);
  /* y — производительность второго: N₁/(y − r) − N₂/y = tm/60 ⇒ tm·y² − (tm·r + 60(N₁ − N₂))·y − 60·N₂·r = 0. */
  const kv = kvadrat(tm, -(tm * r + 60 * (N1 - N2)), -60 * N2 * r, 'y');
  const y = val(kv.roots[1]);
  if (!(y > r) || !Number.isInteger(y)) throw new Error(`№11: производительность ${y} ${JSON.stringify(p)}`);
  const ans = ask === 'vtoroy' ? y : y - r;
  return {
    uslovie: `Первый мастер делает на ${txt(r)} деталей в час меньше второго. Заказ из ${txt(N1)} деталей первый выполняет на ${chasyMinuty(tm)} дольше, чем второй выполняет заказ из ${txt(N2)} деталей. Сколько деталей в час делает ${ask === 'vtoroy' ? 'второй' : 'первый'} мастер?`,
    answer: ans,
    etapy: etapy(
      [
        'Обозначаем',
        [`Пусть второй мастер делает $y$ деталей в час, тогда первый — $y-${d(r)}$. Разница во времени: ${chasyMinuty(tm)} $=${fq(tq)}$ ч.`],
      ],
      [
        'Уравнение по времени',
        [
          `$\\dfrac{${d(N1)}}{y-${d(r)}}-\\dfrac{${d(N2)}}{y}=${fq(tq)}$.`,
          `Умножаем на $60y(y-${d(r)})$ и переносим всё в одну часть: $${kv.ishodnoe}$.`,
          ...kv.lines,
        ],
      ],
      [
        'Отбор и ответ',
        [
          `Производительность положительна и больше $${d(r)}$: $y=${d(y)}$.`,
          ask === 'vtoroy'
            ? `Второй мастер делает $${d(y)}$ деталей в час.`
            : `Первый мастер делает $${d(y)}-${d(r)}=${d(ans)}$ деталей в час.`,
          otvet(ans),
        ],
      ],
    ),
    tables: [
      rabota(
        [
          ['Первый мастер', d(N1), `y-${d(r)}`, `\\dfrac{${d(N1)}}{y-${d(r)}}`],
          ['Второй мастер', d(N2), 'y', `\\dfrac{${d(N2)}}{y}`],
        ],
        [', дет.', ', дет./ч', ', ч'],
      ),
    ],
    hints: [
      vopros(
        `Сколько часов в ${chasyMinuty(tm)}?`,
        `$${fq(tq)}$`,
        [`$${d(Math.floor(tm / 60))}{,}${d(tm % 60)}$`, `$${d(tm)}$`].filter((o) => o !== `$${fq(tq)}$`),
        'В часе 60 минут — минуты делим на 60.',
      ),
      vopros(
        'Какое уравнение по времени?',
        `$\\dfrac{${d(N1)}}{y-${d(r)}}-\\dfrac{${d(N2)}}{y}=${fq(tq)}$`,
        [
          `$\\dfrac{${d(N2)}}{y}-\\dfrac{${d(N1)}}{y-${d(r)}}=${fq(tq)}$`,
          `$\\dfrac{${d(N1)}}{y+${d(r)}}-\\dfrac{${d(N2)}}{y}=${fq(tq)}$`,
        ],
        'Первый работает дольше: из его времени вычитаем время второго.',
      ),
      chtoSprashivayut(ask === 'vtoroy' ? 'производительность второго' : 'производительность первого', [
        ask === 'vtoroy' ? 'производительность первого' : 'производительность второго',
        'время работы',
      ]),
    ],
    lifehacks: [],
  };
}

/**
 * Плот и яхта: из A в B по течению отправился плот, через z ч — яхта;
 * она дошла до B (S км) и сразу вернулась в A. К этому времени плот
 * проплыл R км. Скорость течения vt; найти собственную скорость яхты.
 * Подвох — время яхты в пути равно времени плота минус задержка.
 */
export function plotYahta(p: Record<string, number | string>): Solved {
  const S = num(p, 'S');
  const vt = num(p, 'vt');
  const z = num(p, 'z');
  const R = num(p, 'R');
  const Tq = sub(q(R, vt), q(z));
  /* T(v² − vt²) = 2Sv ⇒ T·v² − 2S·v − T·vt² = 0; T = n/m — умножаем на m. */
  const kv = kvadrat(Tq.n, -2 * S * Tq.m, -Tq.n * vt * vt, 'v');
  const v = val(kv.roots[1]);
  if (!(v > vt)) throw new Error(`№11: скорость яхты ${v} ${JSON.stringify(p)}`);
  return {
    uslovie: `Расстояние между пристанями A и B равно ${txt(S)} км. Из A в B по течению реки отправился плот, а через ${txt(z)} ч вслед за ним — яхта, которая, дойдя до B, сразу повернула обратно и вернулась в A. К этому времени плот проплыл ${txt(R)} км. Найдите скорость яхты в неподвижной воде, если скорость течения равна ${txt(vt)} км/ч.`,
    answer: v,
    etapy: etapy(
      [
        'Время в пути',
        [
          `Плот плывёт со скоростью течения: $${d(R)}$ км он прошёл за $${d(R)}:${d(vt)}=${fq(q(R, vt))}$ ч. Яхта вышла на $${d(z)}$ ч позже: она в пути $${fq(Tq)}$ ч.`,
        ],
      ],
      [
        'Уравнение',
        [
          `Пусть $v$ — скорость яхты в неподвижной воде. По течению $v+${d(vt)}$, против — $v-${d(vt)}$: $\\dfrac{${d(S)}}{v+${d(vt)}}+\\dfrac{${d(S)}}{v-${d(vt)}}=${fq(Tq)}$.`,
          `Приводим к общему знаменателю: $${kv.ishodnoe}$.`,
          ...kv.lines,
        ],
      ],
      [
        'Отбор и ответ',
        [`Скорость яхты больше скорости течения: $v=${d(v)}$ км/ч.`, otvet(v)],
      ],
    ),
    tables: [
      dvizhenie([
        ['Яхта по течению', d(S), `v+${d(vt)}`, `\\dfrac{${d(S)}}{v+${d(vt)}}`],
        ['Яхта против течения', d(S), `v-${d(vt)}`, `\\dfrac{${d(S)}}{v-${d(vt)}}`],
        ['Плот', d(R), d(vt), fq(q(R, vt))],
      ]),
    ],
    hints: [
      vopros('Сколько часов плыл плот?', `$${fq(q(R, vt))}$`, [`$${fq(q(S, vt))}$`, `$${d(R)}$`]),
      vopros('Сколько часов была в пути яхта?', `$${fq(Tq)}$`, [
        `$${fq(q(R, vt))}$`,
        `$${fq(add(q(R, vt), q(z)))}$`,
      ]),
      chtoSprashivayut('скорость яхты в неподвижной воде', ['скорость по течению', 'время в пути']),
    ],
    lifehacks: [],
  };
}

/**
 * Две бригады одинаковых рабочих (n₁ и n₂ человек) одновременно начали
 * одинаковые заказы; через d дней k рабочих перешли из второй бригады в
 * первую, и заказы закончились одновременно. Сколько дней заняла работа?
 * Подвох — объём заказа в «человеко-днях» одинаков у обеих бригад, а
 * в ответе — всё время, а не только после перехода.
 */
export function brigady(p: Record<string, number | string>): Solved {
  const n1 = num(p, 'n1');
  const n2 = num(p, 'n2');
  const dd = num(p, 'd');
  const k = num(p, 'k');
  const tq = q((n2 - n1) * dd, n1 - n2 + 2 * k);
  const t = val(tq);
  if (!(t > 0) || !Number.isInteger(t)) throw new Error(`№11: дней после перехода ${t} ${JSON.stringify(p)}`);
  const T = dd + t;
  return {
    uslovie: `Две бригады одинаково работающих рабочих одновременно начали выполнять два одинаковых заказа. В первой бригаде ${txt(n1)} рабочих, во второй — ${txt(n2)}. Через ${txt(dd)} дней ${txt(k)} рабочих перешли из второй бригады в первую, и оба заказа были выполнены одновременно. Сколько дней заняла работа?`,
    answer: T,
    etapy: etapy(
      [
        'Обозначаем',
        [
          `Объём работы меряем в «человеко-днях»: один рабочий за день делает одну единицу. Пусть после перехода прошло $t$ дней.`,
        ],
      ],
      [
        'Уравнение',
        [
          `Первая бригада: $${d(n1)}\\cdot${d(dd)}+${d(n1 + k)}t$. Вторая: $${d(n2)}\\cdot${d(dd)}+${d(n2 - k)}t$. Заказы одинаковые: $${d(n1 * dd)}+${d(n1 + k)}t=${d(n2 * dd)}+${d(n2 - k)}t$.`,
          `$${d(n1 - n2 + 2 * k)}t=${d((n2 - n1) * dd)}$, $t=${d(t)}$.`,
        ],
      ],
      ['Ответ на вопрос задачи', [`Всего: $${d(dd)}+${d(t)}=${d(T)}$ дней.`, otvet(T)]],
    ),
    tables: [
      rabota(
        [
          ['Первая бригада', `${d(n1 * dd)}+${d(n1 + k)}t`, `${d(n1)}\\to${d(n1 + k)}`, `${d(dd)}+t`],
          ['Вторая бригада', `${d(n2 * dd)}+${d(n2 - k)}t`, `${d(n2)}\\to${d(n2 - k)}`, `${d(dd)}+t`],
        ],
        [', чел.-дн.', ', чел.', ', дн.'],
      ),
    ],
    hints: [
      vopros(
        `Сколько рабочих стало в первой бригаде после перехода?`,
        `$${d(n1 + k)}$`,
        [`$${d(n1)}$`, `$${d(n2 - k)}$`],
      ),
      vopros('Чему равно $t$ — дней после перехода?', `$${d(t)}$`, [`$${d(T)}$`, `$${d(dd)}$`].filter((o) => o !== `$${d(t)}$`)),
      chtoSprashivayut('всё время работы', ['время после перехода', `первые ${txt(dd)} дней`]),
    ],
    lifehacks: [],
  };
}
