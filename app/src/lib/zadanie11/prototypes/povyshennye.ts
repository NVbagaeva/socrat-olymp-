/**
 * Две одинаковые трубы, каждая наполняет бассейн за t ч. Первые d ч
 * работала одна, затем обе. Сколько часов заняло наполнение? Подвох —
 * ответ — всё время, а не только время совместной работы.
 */
export function dveTruby(p: Record<string, number | string>): Solved {
  const t = num(p, 't');
  const dd = num(p, 'd');
  if (dd >= t) throw new Error(`№11: одна труба успела бы наполнить сама ${JSON.stringify(p)}`);
  const ost = q(t - dd, t);
  const vmeste = val(q(t - dd, 2));
  const T = Math.round((dd + vmeste) * 1e9) / 1e9;
  return {
    uslovie: `Каждая из двух труб с одинаковой пропускной способностью может наполнить бассейн за ${txt(t)} ч. Через ${txt(dd)} ч после того, как одна труба наполняла бассейн, подключили вторую трубу, и бассейн наполнили две трубы вместе. Сколько часов потребовалось на наполнение бассейна?`,
    answer: T,
    etapy: etapy(
      [
        'Обозначаем',
        [
          `Объём бассейна примем за $1$. Каждая труба за час наполняет $\\dfrac{1}{${d(t)}}$ бассейна. Обе вместе работали $x$ ч.`,
        ],
      ],
      [
        'Сколько осталось',
        [
          `За $${d(dd)}$ ч одна труба наполнила $\\dfrac{${d(dd)}}{${d(t)}}$, осталось $1-\\dfrac{${d(dd)}}{${d(t)}}=${fq(ost)}$.`,
        ],
      ],
      [
        'Уравнение',
        [
          `Две трубы за час наполняют $\\dfrac{2}{${d(t)}}$: $\\dfrac{2x}{${d(t)}}=${fq(ost)}$, $x=${d(vmeste)}$.`,
        ],
      ],
      ['Ответ на вопрос задачи', [`Всего: $${d(dd)}+${d(vmeste)}=${d(T)}$ ч.`, otvet(T)]],
    ),
    tables: [
      rabota(
        [
          ['Одна труба', `\\dfrac{${d(dd)}}{${d(t)}}`, `\\dfrac{1}{${d(t)}}`, d(dd)],
          ['Две трубы', `\\dfrac{2x}{${d(t)}}`, `\\dfrac{2}{${d(t)}}`, 'x'],
        ],
        [', доля', ', 1/ч', ', ч'],
      ),
    ],
    hints: [
      vopros(
        `Какую часть бассейна наполнила одна труба за ${txt(dd)} ч?`,
        `$\\dfrac{${d(dd)}}{${d(t)}}$`,
        [`$\\dfrac{1}{${d(t)}}$`, `$\\dfrac{${d(t)}}{${d(dd)}}$`],
      ),
      vopros('Какую часть наполняют две трубы за час?', `$\\dfrac{2}{${d(t)}}$`, [
        `$\\dfrac{1}{${d(2 * t)}}$`,
        `$\\dfrac{1}{${d(t)}}$`,
      ]),
      chtoSprashivayut('всё время наполнения', [
        'время совместной работы',
        `время работы одной трубы — ${txt(dd)} ч`,
      ]),
    ],
    lifehacks: [],
  };
}

/**
 * Смешали a%-й и b%-й растворы и получили p₁%; добавили m кг воды —
 * стало p₂%. Сколько килограммов a%-го (b%-го) раствора взяли?
 * Подвох — сначала по воде найти массу смеси, и только потом делить её.
 */
export function rastvorIVoda(p: Record<string, number | string>): Solved {
  const a = num(p, 'a');
  const b = num(p, 'b');
  const p1 = num(p, 'p1');
  const m = num(p, 'm');
  const p2 = num(p, 'p2');
  const ask = str(p, 'ask', ['a', 'b'] as const);
  const vv = typeof p.vv === 'string' && p.vv !== '' ? p.vv : 'кислоты';
  const MQ = q(p2 * m, p1 - p2);
  const M = val(MQ);
  const xQ = div(mul(q(p1 - b), MQ), q(a - b));
  const x = val(xQ);
  const y = val(sub(MQ, xQ));
  if (!(x > 0 && y > 0)) throw new Error(`№11: массы не положительны ${JSON.stringify(p)}`);
  const ans = ask === 'a' ? x : y;
  return {
    uslovie: `Смешали ${txt(a)}-процентный и ${txt(b)}-процентный растворы ${vv} и получили ${txt(p1)}-процентный раствор. Если к полученному раствору добавить ${txt(m)} кг чистой воды, то получится ${txt(p2)}-процентный раствор. Сколько килограммов ${txt(ask === 'a' ? a : b)}-процентного раствора использовали для получения смеси?`,
    answer: ans,
    etapy: etapy(
      [
        'Масса смеси',
        [
          `Пусть смесь весит $M$ кг, ${vv} в ней $${d(p1 / 100)}M$. Вода ${vv} не добавляет: $${d(p1 / 100)}M=${d(p2 / 100)}(M+${d(m)})$.`,
          `Умножим на $100$: $${d(p1)}M=${d(p2)}M+${d(p2 * m)}$, $${d(p1 - p2)}M=${d(p2 * m)}$, $M=${d(M)}$.`,
        ],
      ],
      [
        'Состав смеси',
        [
          `Пусть $${pct(a)}$-го раствора $x$ кг, тогда $${pct(b)}$-го — $${d(M)}-x$ кг.`,
          `${vv[0]!.toUpperCase()}${vv.slice(1)}: $${d(a / 100)}x+${d(b / 100)}(${d(M)}-x)=${d(p1 / 100)}\\cdot${d(M)}$.`,
          `Умножим на $100$: $${d(a)}x+${d(b)}(${d(M)}-x)=${d(p1 * M)}$, $${d(a - b)}x=${d((p1 - b) * M)}$, $x=${d(x)}$.`,
        ],
      ],
      [
        'Ответ на вопрос задачи',
        [
          ask === 'a'
            ? `Спрашивают массу $${pct(a)}$-го раствора: $${d(x)}$ кг.`
            : `Спрашивают массу $${pct(b)}$-го раствора: $${d(M)}-${d(x)}=${d(y)}$ кг.`,
          otvet(ans),
        ],
      ],
    ),
    tables: [
      koncentraciya([
        { label: 'I', mvv: `${d(a / 100)}x`, mr: 'x', p: d(a) },
        { label: 'II', mvv: `${d(b / 100)}(M-x)`, mr: 'M-x', p: d(b) },
        { label: 'смесь', mvv: `${d(p1 / 100)}M`, mr: 'M', p: d(p1) },
        { label: 'с водой', mvv: `${d(p2 / 100)}(M+${d(m)})`, mr: `M+${d(m)}`, p: d(p2) },
      ]),
    ],
    hints: [
      vopros(`Меняется ли масса ${vv}, когда доливают воду?`, 'нет', [
        `да, растёт на $${d(m)}$ кг`,
        'да, уменьшается',
      ]),
      vopros('Чему равна масса смеси до добавления воды?', `$${d(M)}$ кг`, [
        `$${d(M + m)}$ кг`,
        `$${d(m)}$ кг`,
      ]),
      chtoSprashivayut(`массу $${pct(ask === 'a' ? a : b)}$-го раствора`, [
        `массу $${pct(ask === 'a' ? b : a)}$-го раствора`,
        'массу всей смеси',
      ]),
    ],
    lifehacks: [],
  };
}

/**
 * Из A в B выехал автобус, через t₀ ч за ним — автомобиль со скоростью v;
 * автомобиль догнал автобус в K и вернулся в A, когда автобус прибыл в B
 * (AB = S). Найти AK. Подвох — скорость автобуса неизвестна: два условия
 * по времени дают квадратное уравнение на AK, отрицательный корень
 * отбрасывается.
 */
export function avtobusIAvtomobil(p: Record<string, number | string>): Solved {
  const S = num(p, 'S');
  const v = num(p, 'v');
  const t0 = num(p, 't0');
  /* 2x² + (t₀v − S)x − S·t₀v = 0; t₀v может быть половинным — умножаем на 2. */
  const tv = t0 * v;
  const k = Number.isInteger(tv) ? 1 : 2;
  const kv = kvadrat(2 * k, (tv - S) * k, -S * tv * k);
  const x = val(kv.roots[1]);
  if (!(x > 0 && x < S)) throw new Error(`№11: встреча вне AB ${JSON.stringify(p)}`);
  const u = Math.round((x / (t0 + x / v)) * 1e9) / 1e9;
  return {
    uslovie: `Из города А в город Б выехал автобус, а через ${txt(t0)} ч со скоростью ${txt(v)} км/ч следом за ним выехал автомобиль, догнал автобус в городе К и повернул обратно. Когда автомобиль вернулся в А, автобус прибыл в Б. Найдите расстояние от А до К, если расстояние между городами А и Б равно ${txt(S)} км.`,
    answer: x,
    etapy: etapy(
      ['Обозначаем', [`Пусть $AK=x$ км, скорость автобуса — $u$ км/ч.`]],
      [
        'Два условия по времени',
        [
          `До встречи автобус ехал на $${d(t0)}$ ч дольше автомобиля: $\\dfrac{x}{u}=${d(t0)}+\\dfrac{x}{${d(v)}}$.`,
          `Автобус ехал весь путь, пока автомобиль догонял и возвращался: $\\dfrac{${d(S)}}{u}=${d(t0)}+\\dfrac{2x}{${d(v)}}$.`,
        ],
      ],
      [
        'Уравнение на $x$',
        [
          `Разделим второе на первое — $u$ сократится: $\\dfrac{${d(S)}}{x}=\\dfrac{${d(t0)}+\\dfrac{2x}{${d(v)}}}{${d(t0)}+\\dfrac{x}{${d(v)}}}$, то есть $${d(S)}(${d(tv)}+x)=x(${d(tv)}+2x)$.`,
          `Раскрываем скобки и переносим всё в одну часть${k === 2 ? ', умножив на $2$' : ''}: $${kv.ishodnoe}$.`,
          ...kv.lines,
        ],
      ],
      [
        'Отбор и ответ',
        [
          `Расстояние положительно: $x=${d(x)}$ км. Скорость автобуса тогда $u=${d(u)}$ км/ч — меньше скорости автомобиля, всё сходится.`,
          otvet(x),
        ],
      ],
    ),
    hints: [
      vopros(
        'Сколько времени автобус был в пути до города К?',
        `$${d(t0)}+\\dfrac{x}{${d(v)}}$ ч`,
        [`$\\dfrac{x}{${d(v)}}$ ч`, `$\\dfrac{x}{${d(v)}}-${d(t0)}$ ч`],
        'Автобус выехал раньше на всё время задержки.',
      ),
      vopros('Сколько времени ехал автомобиль туда и обратно?', `$\\dfrac{2x}{${d(v)}}$ ч`, [
        `$\\dfrac{x}{${d(v)}}$ ч`,
        `$\\dfrac{${d(S)}}{${d(v)}}$ ч`,
      ]),
      chtoSprashivayut('расстояние $AK$', ['скорость автобуса', 'расстояние $AB$']),
    ],
    lifehacks: ['divide-equation'],
  };
}
