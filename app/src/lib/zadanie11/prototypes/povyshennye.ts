/**
 * Подтип раздела «Варианты повышенной сложности» для задания №11.
 * Устроен как подтипы РБ (таблица A | p | t, этапы, подсказки), но в
 * SUBTYPES не входит: в тренажёр, банк и «Собрать вариант» не попадает,
 * числа задаёт вариант.
 */

import { chtoSprashivayut, etapy, num, rabota, vopros } from '../kit';
import { d, txt } from '../num';
import type { Solved } from '../types';
import { otvet } from './common';

/**
 * Три одинаковых рабочих, каждый выполняет работу за t ч. Второй
 * подключается через d1 ч после первого, третий — ещё через d2 ч.
 * Сколько часов заняла вся работа? Подвох — у каждого своё время:
 * T, T − d1, T − d1 − d2, а не одно общее.
 */
export function ocheredno(p: Record<string, number | string>): Solved {
  const t = num(p, 't');
  const d1 = num(p, 'd1');
  const d2 = num(p, 'd2');
  const s = d1 + d2;
  const T = Math.round(((t + d1 + s) / 3) * 1e9) / 1e9;
  if (T <= s) throw new Error(`№11: третий не успевает подключиться ${JSON.stringify(p)}`);
  const t2 = `T-${d(d1)}`;
  const t3 = `T-${d(s)}`;
  return {
    uslovie: `Три рабочих могут выполнить работу, каждый в одиночку, за ${txt(t)} ч. Первый начал работу; через ${txt(d1)} ч к нему присоединился второй, а ещё через ${txt(d2)} ч — третий. Сколько часов заняла вся работа?`,
    answer: T,
    etapy: etapy(
      [
        'Обозначаем',
        [
          `Всю работу примем за $1$. Каждый за час делает $\\dfrac{1}{${d(t)}}$ работы. Вся работа заняла $T$ ч.`,
        ],
      ],
      [
        'Время каждого',
        [
          `Первый работал $T$ ч, второй — $${t2}$ ч, третий — $${t3}$ ч (он подключился через $${d(d1)}+${d(d2)}=${d(s)}$ ч).`,
        ],
      ],
      [
        'Уравнение',
        [
          `Вместе они сделали всю работу: $\\dfrac{T}{${d(t)}}+\\dfrac{${t2}}{${d(t)}}+\\dfrac{${t3}}{${d(t)}}=1$.`,
          `Умножаем на $${d(t)}$: $3T-${d(d1 + s)}=${d(t)}$, $3T=${d(t + d1 + s)}$.`,
        ],
      ],
      ['Ответ', [`$T=${d(t + d1 + s)}:3=${d(T)}$.`, otvet(T)]],
    ),
    tables: [
      rabota(
        [
          ['Первый', `\\dfrac{T}{${d(t)}}`, `\\dfrac{1}{${d(t)}}`, 'T'],
          ['Второй', `\\dfrac{${t2}}{${d(t)}}`, `\\dfrac{1}{${d(t)}}`, t2],
          ['Третий', `\\dfrac{${t3}}{${d(t)}}`, `\\dfrac{1}{${d(t)}}`, t3],
        ],
        [', доля', ', 1/ч', ', ч'],
      ),
    ],
    hints: [
      vopros('Какую часть работы рабочий делает за час?', `$\\dfrac{1}{${d(t)}}$`, [
        `$${d(t)}$`,
        `$\\dfrac{1}{${d(3 * t)}}$`,
      ]),
      vopros('Сколько часов работал третий?', `$${t3}$`, [`$${t2}$`, `$T-${d(d2)}$`, '$T$']),
      vopros(
        'Какое уравнение?',
        `$\\dfrac{T}{${d(t)}}+\\dfrac{${t2}}{${d(t)}}+\\dfrac{${t3}}{${d(t)}}=1$`,
        [
          `$\\dfrac{3T}{${d(t)}}=1$`,
          `$\\dfrac{T}{${d(t)}}+\\dfrac{${t2}}{${d(t)}}+\\dfrac{${t3}}{${d(t)}}=${d(t)}$`,
        ],
      ),
      chtoSprashivayut('сколько часов заняла вся работа', [
        'сколько часов работал третий',
        'за сколько часов работу сделали бы трое вместе',
      ]),
    ],
    lifehacks: [],
  };
}
