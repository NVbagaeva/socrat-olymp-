/** Масса вещества: m·p/100 в TeX. */
const vesh = (m: string, p: number): string => (p === 0 ? '0' : `${d(p / 100)}\\cdot ${m}`);

/** Вещество аналога в родительном падеже («соли»); без него — «вещества». */
const veshchestvo = (p: Params, def = 'вещества'): string =>
  typeof p.vv === 'string' && p.vv in VESHCHESTVA ? klyuch(VESHCHESTVA, p.vv, 'kislota').rod : def;

/** Уравнение смеси — по строке массы вещества. */
