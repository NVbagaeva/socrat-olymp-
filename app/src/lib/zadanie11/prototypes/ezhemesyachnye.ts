/* ── Плот и катер: катер туда и обратно со стоянкой, плот плывёт всё время ─ */

/**
 * Катер выходит из B в A (S км), стоит st ч и возвращается в B; за всё
 * время T₀ (с выхода до возвращения) плот, пущенный в A в момент выхода
 * катера, плывёт по течению. Скорость течения x: S/(v − x) + S/(v + x) =
 * T₀ − st, x² = v² − 2Sv/(T₀ − st); путь плота — x·T₀. Подвох — найти
 * скорость течения и остановиться, или умножить на время без стоянки.
 */
export function plotIKater(p: Record<string, number | string>): Solved {
  const S = num(p, 'S');
  const v = num(p, 'v');
  const T0 = num(p, 'T0');
  const st = num(p, 'st');
  const T = q(T0 - st);
  const c2 = sub(q(v * v), div(q(2 * S * v), T));
  const c = Math.sqrt(val(c2));
  if (!Number.isInteger(Math.round(c * 1e9) / 1e9))
    throw new Error(`№11: скорость течения не целая ${JSON.stringify(p)}`);
  const t = drobnoe({
    nuli: [v, -v],
    lo: 0,
    hi: v,
    pochemu: 'скорость течения положительна и меньше собственной скорости катера',
    znamenatel: `(${d(v)}+x)(${d(v)}-x)`,
    posle: [
      `$${d(S)}(${d(v)}-x)+${d(S)}(${d(v)}+x)=${fq(T)}(${d(v * v)}-x^2)$, то есть $${d(2 * S * v)}=${fq(T)}(${d(v * v)}-x^2)$.`,
      `$${d(v * v)}-x^2=${fq(div(q(2 * S * v), T))}$, $x^2=${fq(c2)}$, $x=\\pm${d(c)}$.`,
    ],
    roots: [-c, c],
  });
  const ans = t.root * T0;
  return {
    uslovie: '',
    answer: ans,
    etapy: etapy(
      [
        'Обозначаем',
        [
          `Скорость течения — $x$ км/ч. Против течения катер идёт со скоростью $${d(v)}-x$, по течению — $${d(v)}+x$.`,
        ],
      ],
      [
        'Время в движении',
        [
          `С выхода до возвращения прошло $${d(T0)}$ ч, из них $${d(st)}$ ч — стоянка; в движении катер был $${d(T0)}-${d(st)}=${fq(T)}$ ч.`,
        ],
      ],
      ['Уравнение', [`$\\dfrac{${d(S)}}{${d(v)}-x}+\\dfrac{${d(S)}}{${d(v)}+x}=${fq(T)}$.`]],
      t.odz,
      t.reshenie,
      ['Отбор корней', t.otbor],
      [
        'Путь плота',
        [
          `Плот плывёт со скоростью течения $${d(t.root)}$ км/ч всё время — $${d(T0)}$ ч, стоянка катера его не останавливает.`,
          `$${d(t.root)}\\cdot${d(T0)}=${d(ans)}$ км.`,
          otvet(ans),
        ],
      ],
    ),
    tables: [
      dvizhenie([
        ['Против течения', d(S), `${d(v)}-x`, `\\dfrac{${d(S)}}{${d(v)}-x}`],
        ['По течению', d(S), `${d(v)}+x`, `\\dfrac{${d(S)}}{${d(v)}+x}`],
      ]),
    ],
    hints: [
      vopros('Сколько часов катер был в движении?', `$${fq(T)}$`, [
        `$${d(T0)}$`,
        `$${d(T0 + st)}$`,
      ]),
      vopros(
        'Какое уравнение?',
        `$\\dfrac{${d(S)}}{${d(v)}-x}+\\dfrac{${d(S)}}{${d(v)}+x}=${fq(T)}$`,
        [
          `$\\dfrac{${d(S)}}{${d(v)}-x}+\\dfrac{${d(S)}}{${d(v)}+x}=${d(T0)}$`,
          `$\\dfrac{${d(2 * S)}}{${d(v)}}=${fq(T)}$`,
        ],
      ),
      t.hintKoren,
      vopros('Сколько часов плывёт плот?', `$${d(T0)}$`, [`$${fq(T)}$`, `$${d(st)}$`]),
      chtoSprashivayut('путь плота', ['скорость течения', 'время в пути катера']),
    ],
    lifehacks: ['fast-count'],
  };
}

/* ── Арифметическая прогрессия: сумма за n дней ─────────────────── */

/**
 * В первый день a, каждый следующий — на r больше; сколько всего за n
 * дней. Подвох — найти последний член (a + (n − 1)r) вместо суммы или
 * взять n·r вместо (n − 1)r.
 */
export function summaProgressii(p: Record<string, number | string>): Solved {
  const a = num(p, 'a');
  const r = num(p, 'r');
  const n = num(p, 'n');
  const an = a + (n - 1) * r;
  const S = ((a + an) * n) / 2;
  return {
    uslovie: '',
    answer: S,
    etapy: etapy(
      [
        'Обозначаем',
        [
          `Количества по дням — арифметическая прогрессия: $a_1=${d(a)}$, разность $r=${d(r)}$, дней $n=${d(n)}$.`,
        ],
      ],
      ['Последний день', [`$a_{${n}}=a_1+(n-1)r=${d(a)}+${d(n - 1)}\\cdot${d(r)}=${d(an)}$.`]],
      [
        'Сумма',
        [
          `$S_{${n}}=\\dfrac{a_1+a_{${n}}}{2}\\cdot n=\\dfrac{${d(a)}+${d(an)}}{2}\\cdot${d(n)}=${d((a + an) / 2)}\\cdot${d(n)}=${d(S)}$.`,
          otvet(S),
        ],
      ],
    ),
    hints: [
      vopros('Чему равно количество в последний день?', `$${d(an)}$`, [
        `$${d(a + n * r)}$`,
        `$${d(n * r)}$`,
      ]),
      vopros('По какой формуле найти сумму?', '$S_n=\\dfrac{a_1+a_n}{2}\\cdot n$', [
        '$S_n=a_n\\cdot n$',
        '$S_n=a_1+(n-1)r$',
      ]),
      chtoSprashivayut('сколько всего за все дни', [
        'сколько в последний день',
        'на сколько больше',
      ]),
    ],
    lifehacks: ['fast-count'],
  };
}

/* ── Проценты: на сколько процентов больше купишь при меньшей цене ─ */

/**
 * Сумма денег та же, цена единицы раньше b, теперь a > b. На сколько
 * процентов больше единиц можно было купить раньше? (a/b − 1)·100%.
 * Подвох — посчитать (a − b)/a — процент от новой цены.
 */
export function bolshePriNizkoyCene(p: Record<string, number | string>): Solved {
  const sum = num(p, 'sum');
  const a = num(p, 'a');
  const b = num(p, 'b');
  const kNow = sum / a;
  const kWas = sum / b;
  const ans = Math.round((a / b - 1) * 100 * 1e9) / 1e9;
  const nepr = Math.round(((a - b) / a) * 100 * 1e9) / 1e9;
  return {
    uslovie: '',
    answer: ans,
    etapy: etapy(
      [
        'Сколько можно купить',
        [`Сейчас: $${d(sum)}:${d(a)}=${d(kNow)}$ шт.; раньше: $${d(sum)}:${d(b)}=${d(kWas)}$ шт.`],
      ],
      [
        'На сколько процентов больше',
        [
          `Сравниваем с тем, что можно купить сейчас: $\\dfrac{${d(kWas)}}{${d(kNow)}}=${d(kWas / kNow)}$, то есть больше на $${pct(ans)}$.`,
          `Короче: количество обратно пропорционально цене, $\\dfrac{${d(a)}}{${d(b)}}=${d(a / b)}$.`,
          otvet(ans),
        ],
      ],
    ),
    hints: [
      vopros('Как связаны количество и цена при той же сумме?', 'Обратно пропорционально', [
        'Прямо пропорционально',
        'Никак',
      ]),
      vopros(
        'Во сколько раз больше можно было купить раньше?',
        `$\\dfrac{${d(a)}}{${d(b)}}=${d(a / b)}$`,
        [`$\\dfrac{${d(b)}}{${d(a)}}$`, `$${d(a - b)}$`],
      ),
      chtoSprashivayut('на сколько процентов больше', [
        `на сколько процентов меньше ($${pct(nepr)}$)`,
        'во сколько раз больше',
      ]),
    ],
    lifehacks: ['fast-count'],
  };
}
