/** Слово сюжета аналога (kit.slovo) — короче. */
const sl = (p: Params, k: string, def: string): string => slovoSyuzheta(p, k, def);

/** «зарплата» → «зарплаты» / «зарплату»: доход женского рода на -а/-я. */
function rodZh(s: string): string {
  return s.replace(/а$/, 'ы').replace(/я$/, 'и');
}
function vinZh(s: string): string {
  return s.replace(/а$/, 'у').replace(/я$/, 'ю');
}

