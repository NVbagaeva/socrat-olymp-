/**
 * Раздел ПТ — движение протяжённых тел (ПТ-01 … ПТ-04).
 *
 * «Прошёл мимо» — путь равен сумме длин; навстречу скорости
 * складываются, в одном направлении — вычитаются. Удобно смотреть из
 * системы отсчёта одного из поездов.
 */

import { chtoSprashivayut, dvizhenie, etapy, num, osh, slovo, str, vopros } from '../kit';
import { d, div, fq, mul, q, sub, txt, val } from '../num';
import { sk, zaglavnaya, SLOVA } from '../sklonenie';
import type { Subtype } from '../types';
import { otvet } from './common';

/* ── ПТ-01 Поезд через тоннель / мимо лесополосы ─────────────── */

const PT01: Subtype = {
  id: 'PT-01',
  section: 'PT',
  title: 'Поезд мимо столба, лесополосы, через тоннель',
  level: 1,
  keywords: ['поезд', 'тоннель', 'лесополоса', 'столб'],
  solve(p) {
    const form = str(p, 'form', ['tonnel', 'lesopolosa'] as const);
    const L1 = num(p, 'L1');
    const L2 = num(p, 'L2');
    const v = num(p, 'v');
    const S = q(L1 + L2, 1000);
    const tMin = val(mul(div(S, q(v)), q(60)));
    const chto =
      form === 'tonnel'
        ? `через тоннель, длина которого ${txt(L2)} м`
        : `мимо лесополосы, длина которой ${txt(L2)} м`;
    return {
      uslovie: `Сколько времени будет проходить поезд длиной ${txt(L1)} м ${chto}, если скорость поезда ${txt(v)} км/ч? Ответ дайте в минутах.`,
      answer: tMin,
      etapy: etapy(
        [
          'Путь',
          [
            `Поезд проходит ${slovo(p, 'prep', form === 'tonnel' ? 'тоннель' : 'лесополосу')} от момента, когда голова поезда поравнялась с началом препятствия, до момента, когда хвост миновал его конец: путь равен сумме длин, $${d(L1)}+${d(L2)}=${d(L1 + L2)}$ м $=${fq(S, true)}$ км.`,
          ],
        ],
        ['Время в часах', [`$t=\\dfrac{${fq(S, true)}}{${d(v)}}=${fq(div(S, q(v)))}$ ч.`]],
        [
          'Ответ на вопрос задачи',
          [`В минутах: $${fq(div(S, q(v)))}\\cdot60=${d(tMin)}$ мин.`, otvet(tMin)],
        ],
      ),
      tables: [dvizhenie([['Поезд', fq(S, true), d(v), 'x']])],
      hints: [
        vopros('Какой путь проходит поезд?', 'сумму своей длины и длины препятствия', [
          'только длину препятствия',
          'только свою длину',
        ]),
        vopros('Сколько это в километрах?', `$${fq(S, true)}$`, [
          `$${d(L1 + L2)}$`,
          `$${fq(q(L2, 1000), true)}$`,
        ]),
        chtoSprashivayut('время в минутах', ['время в часах', 'длину поезда']),
      ],
      lifehacks: ['fast-count'],
    };
  },
};

/* ── ПТ-02 Два поезда навстречу ──────────────────────────────── */

const PT02: Subtype = {
  id: 'PT-02',
  section: 'PT',
  title: 'Два поезда навстречу',
  level: 1,
  keywords: ['скорый', 'пассажирский', 'навстречу', 'параллельным путям', 'длину поезда'],
  oshibki: ['navstrechu', 'put-mimo'],
  solve(p) {
    const v1 = num(p, 'v1');
    const v2 = num(p, 'v2');
    const L = num(p, 'L');
    const t = num(p, 't');
    /* «Найди ошибку»: скорости вычли или путь «мимо» — одна длина. */
    const oshibka = osh(p);
    const vychli = oshibka === 'navstrechu';
    const odnaDlina = oshibka === 'put-mimo';
    const vs = vychli ? Math.abs(v1 - v2) : v1 + v2;
    const ms = q(vs * 5, 18);
    const path = mul(ms, q(t));
    const ans = odnaDlina ? val(path) : val(sub(path, q(L)));
    /* Аналог: другие поезда (скоростной и пригородный, пассажирский и товарный). */
    const a = slovo(p, 'poezdA', 'скорый');
    const aRod = slovo(p, 'poezdARod', 'скорого');
    const bRod = slovo(p, 'poezdBRod', 'пассажирского');
    return {
      uslovie: `По двум параллельным железнодорожным путям навстречу друг другу следуют скорый и пассажирский поезда, скорости которых равны соответственно ${txt(v1)} км/ч и ${txt(v2)} км/ч. Длина пассажирского поезда равна ${txt(L)} метрам. Найдите длину скорого поезда, если время, за которое он прошёл мимо пассажирского, равно ${sk(t, SLOVA.sekundam)}. Ответ дайте в метрах.`,
      answer: ans,
      etapy: etapy(
        [
          'Скорость сближения',
          [
            vychli
              ? `Скорости вычитаются: $${d(Math.max(v1, v2))}-${d(Math.min(v1, v2))}=${d(vs)}$ км/ч $=${d(vs)}\\cdot\\dfrac{1000}{3600}=${fq(ms)}$ м/с.`
              : `Навстречу скорости складываются: $${d(v1)}+${d(v2)}=${d(vs)}$ км/ч $=${d(vs)}\\cdot\\dfrac{1000}{3600}=${fq(ms)}$ м/с.`,
          ],
        ],
        [
          'Путь',
          [
            `За $${d(t)}$ с поезда сместились друг относительно друга на $${fq(ms)}\\cdot${d(t)}=${fq(path)}$ м.`,
          ],
        ],
        odnaDlina
          ? ['Уравнение', [`Этот путь — длина ${aRod} поезда: $x=${fq(path)}$.`]]
          : ['Уравнение', ['Этот путь — сумма длин поездов: $x+' + d(L) + '=' + fq(path) + '$.']],
        [
          'Ответ на вопрос задачи',
          [
            odnaDlina
              ? `$x=${d(ans)}$ м — длина ${aRod} поезда.`
              : `$x=${fq(path)}-${d(L)}=${d(ans)}$ м — длина ${aRod} поезда.`,
            otvet(ans),
          ],
        ],
      ),
      tables: [
        dvizhenie(
          [[`${zaglavnaya(a)} относительно ${bRod}`, odnaDlina ? 'x' : `x+${d(L)}`, fq(ms), d(t)]],
          ['', '$S$, м', '$v$, м/с', '$t$, с'],
          `Смотрим из ${bRod} поезда: скорости ${vychli ? 'вычитаются' : 'складываются'}`,
        ),
      ],
      hints: [
        vopros('Как найти скорость сближения поездов, идущих навстречу?', 'сложить скорости', [
          'вычесть скорости',
          'взять большую',
        ]),
        vopros('Сколько метров в секунду составляет $36$ км/ч?', '$10$', ['$3{,}6$', '$36$']),
        vopros('Чему равен путь «мимо»?', 'сумме длин поездов', [
          `длине ${aRod} поезда`,
          `длине ${bRod} поезда`,
        ]),
        chtoSprashivayut(`длину ${aRod} поезда`, [`длину ${bRod} поезда`, 'сумму длин']),
      ],
      lifehacks: ['fast-count'],
    };
  },
};

/* ── ПТ-03 Обгон в одном направлении ─────────────────────────── */

const PT03: Subtype = {
  id: 'PT-03',
  section: 'PT',
  title: 'Обгон в одном направлении',
  level: 1,
  keywords: ['товарный', 'пассажирский', 'в одном направлении', 'обгон'],
  solve(p) {
    const v1 = num(p, 'v1');
    const v2 = num(p, 'v2');
    const L = num(p, 'L');
    const t = num(p, 't'); // минуты
    const path = mul(q(v1 - v2), q(t, 60)); // км
    const pathM = val(mul(path, q(1000)));
    const ans = pathM - L;
    /* Аналог: другие поезда (скорый и пригородный, скоростной и пассажирский). */
    const a = slovo(p, 'poezdA', 'пассажирский');
    const aRod = slovo(p, 'poezdARod', 'пассажирского');
    const bRod = slovo(p, 'poezdBRod', 'товарного');
    return {
      uslovie: `По двум параллельным железнодорожным путям в одном направлении следуют пассажирский и товарный поезда, скорости которых равны соответственно ${txt(v1)} км/ч и ${txt(v2)} км/ч. Длина товарного поезда равна ${txt(L)} метрам. Найдите длину пассажирского поезда, если время, за которое он прошёл мимо товарного поезда, равно ${sk(t, SLOVA.minutam)}. Ответ дайте в метрах.`,
      answer: ans,
      etapy: etapy(
        [
          'Скорость сближения',
          [`В одном направлении скорости вычитаются: $${d(v1)}-${d(v2)}=${d(v1 - v2)}$ км/ч.`],
        ],
        [
          'Путь',
          [
            `За $${d(t)}$ мин $=${fq(q(t, 60))}$ ч ${a} сместился относительно ${bRod} на $${d(v1 - v2)}\\cdot${fq(q(t, 60))}=${fq(path, true)}$ км $=${d(pathM)}$ м.`,
          ],
        ],
        ['Уравнение', [`Сумма длин: $x+${d(L)}=${d(pathM)}$.`]],
        ['Ответ на вопрос задачи', [`$x=${d(ans)}$ м.`, otvet(ans)]],
      ),
      tables: [
        dvizhenie(
          [
            [
              `${zaglavnaya(a)} относительно ${bRod}`,
              `\\dfrac{x+${d(L)}}{1000}`,
              d(v1 - v2),
              fq(q(t, 60)),
            ],
          ],
          undefined,
          `Смотрим из ${bRod} поезда: скорости вычитаются`,
        ),
      ],
      hints: [
        vopros('Поезда идут в одном направлении. Скорость сближения?', 'разность скоростей', [
          'сумма скоростей',
          `скорость ${aRod}`,
        ]),
        vopros(`Сколько часов в $${d(t)}$ минутах?`, `$${fq(q(t, 60), true)}$`, [
          `$${d(t / 100)}$`,
          `$${d(t)}$`,
        ]),
        vopros('Чему равен путь «мимо»?', 'сумме длин поездов', [`длине ${bRod}`, 'разности длин']),
        chtoSprashivayut(`длину ${aRod} поезда`, [`длину ${bRod} поезда`, 'сумму длин']),
      ],
      lifehacks: ['fast-count'],
    };
  },
};

/* ── ПТ-04 Два сухогруза ─────────────────────────────────────── */

const PT04: Subtype = {
  id: 'PT-04',
  section: 'PT',
  title: 'Два сухогруза поменялись местами',
  level: 2,
  keywords: ['сухогруз', 'корма', 'нос', 'параллельными курсами'],
  solve(p) {
    const L1 = num(p, 'L1');
    const L2 = num(p, 'L2');
    const a = num(p, 'a');
    const b = num(p, 'b');
    const t = num(p, 't');
    const S = a + L1 + L2 + b;
    const v = div(q(S, 1000), q(t, 60));
    const ans = val(v);
    /* Аналог: танкеры, теплоходы, контейнеровозы. */
    const ktoRod = slovo(p, 'ktoRod', 'сухогруза');
    return {
      uslovie: `По морю параллельными курсами в одном направлении следуют два сухогруза: первый длиной ${txt(L1)} метров, второй — длиной ${txt(L2)} метров. Сначала второй сухогруз отстаёт от первого, и в некоторый момент времени расстояние от кормы первого сухогруза до носа второго составляет ${txt(a)} метров. Через ${sk(t, SLOVA.minutu)} после этого уже первый сухогруз отстаёт от второго так, что расстояние от кормы второго сухогруза до носа первого равно ${txt(b)} метрам. На сколько километров в час скорость первого сухогруза меньше скорости второго?`,
      answer: ans,
      etapy: etapy(
        [
          'Система отсчёта',
          [
            `Смотрим из первого ${ktoRod}: он стоит, второй движется со скоростью $x$ — разностью скоростей.`,
          ],
        ],
        [
          'Путь',
          [
            `Нос второго был в $${d(a)}$ м позади кормы первого, а стал впереди его носа на $${d(b)}+${d(L2)}$ м: всего $${d(a)}+${d(L1)}+${d(L2)}+${d(b)}=${d(S)}$ м $=${fq(q(S, 1000), true)}$ км.`,
          ],
        ],
        ['Уравнение', [`$x\\cdot${fq(q(t, 60))}=${fq(q(S, 1000), true)}$.`]],
        ['Ответ на вопрос задачи', [`$x=${d(ans)}$ км/ч.`, otvet(ans)]],
      ),
      tables: [
        dvizhenie(
          [['Второй относительно первого', fq(q(S, 1000), true), 'x', fq(q(t, 60))]],
          undefined,
          `Смотрим из первого ${ktoRod}`,
        ),
      ],
      hints: [
        vopros(
          `С какой скоростью второй ${slovo(p, 'kto', 'сухогруз')} движется относительно первого?`,
          'с разностью скоростей',
          ['с суммой скоростей', 'со своей скоростью'],
        ),
        vopros('Какой путь он прошёл относительно первого?', `$${d(S)}$ м`, [
          `$${d(a + b)}$ м`,
          `$${d(a + b + L1)}$ м`,
        ]),
        vopros(`Сколько часов в $${d(t)}$ минутах?`, `$${fq(q(t, 60), true)}$`, [
          `$${d(t / 100)}$`,
          `$${d(t)}$`,
        ]),
        chtoSprashivayut('разность скоростей в км/ч', ['скорость первого', 'путь в метрах']),
      ],
      lifehacks: ['fast-count'],
    };
  },
};

