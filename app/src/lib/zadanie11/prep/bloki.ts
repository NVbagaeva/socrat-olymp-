type Vid = [string, (r: Rng) => MikroZadacha | null];

/**
 * Микрозадача на проценты по общей схеме разбора: что за 100 %,
 * краткая запись, x, пропорция, правило, сокращение, ответ
 * (lib/zadanie11/proporciya). Подсказки — тем же путём.
 */
function procentMikro(
  uslovie: string,
  otvet: number,
  z: Zveno,
  sto: string,
  itog: string[],
  hints: HintStep[],
  znachenie: number,
): MikroZadacha | null {
  const zz: Zveno = { ...z, pervoe: true };
  const r = reshitZveno(zz);
  if (Math.abs(r.znachenie - znachenie) > 1e-9) return null;
  const et = etapy(shag100(sto), ...r.etapy, ['Ответ на вопрос задачи', [...itog, otv(otvet)]]);
  const razbor = et.flatMap((e) => [`**${e.title}**`, ...e.lines]);
  return chislo(uslovie, otvet, [...hints, ...podskazkiZvena(zz, r)], razbor);
}

/** Блок: виды задач чередуются по десяти местам. */
function blok(
  no: string,
  razdel: RazdelBloka,
  slug: string,
  nazvanie: string,
  lead: string,
  zapomni: string[],
  vidy: Vid[],
): Blok {
  const id = `P11-${no}`;
  const zadachi: Mikro[] = Array.from({ length: 10 }, (_, i) => {
    const vid = vidy[i % vidy.length] as Vid;
    return { id: `${id}-${String(i + 1).padStart(2, '0')}`, nazvanie: vid[0], generate: vid[1] };
  });
  const opis = OPISANIYA_BLOKOV_11[no];
  if (opis === undefined) {
    throw new Error(`Нет описания блока ${no} в content/opornye11.ts`);
  }
  return { id, slug, no, razdel, nazvanie, lead, zapomni, ...opis, zadachi };
}

/* ── 00 Разминка: задачи раздела РЗ ─────────────────────────────── */

function izRazminki(id: string): Vid {
  const st = RZ.find((x) => x.id === id);
  if (st === undefined) {
    throw new Error(`Нет подтипа ${id}`);
  }
  return [
    st.title,
    (r) => {
      const gen = GEN_RZ[id];
      const z = gen ? gen(r) : null;
      if (!z) {
        return null;
      }
      const s = st.solve(z.params);
      if (Math.abs(s.answer - z.answer) > 1e-9) {
        return null;
      }
      const razbor = s.etapy.flatMap((e) => [`**${e.title}**`, ...e.lines]);
      if (s.vybor) {
        const right = s.vybor.options[s.vybor.correct] as string;
        return vyborZadacha(
          s.uslovie,
          right,
          s.vybor.options.filter((o) => o !== right),
          s.hints,
          [...razbor.slice(0, -1), otv(right)],
        );
      }
      return chislo(s.uslovie, s.answer, s.hints, razbor);
    },
  ];
}

