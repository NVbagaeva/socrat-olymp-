/**
 * Модель задания «Наибольшее и наименьшее значение функции, точки
 * экстремума» (номер хранения 21; номер ЕГЭ — из content/struktura.js).
 *
 * Классификация — две оси (docs/ege-2027-struktura-shag-0.md, раздел 8):
 *   что спрашивают — A точка максимума / минимума, B наибольшее /
 *   наименьшее значение на отрезке, V наибольшее / наименьшее значение
 *   без отрезка;
 *   какая функция — 1 многочлен, 2 степенная с корнем, 3 дробно-
 *   рациональная, 4 произведение с e^x, 5 с логарифмом,
 *   6 тригонометрическая, 7 сложная (монотонная внешняя функция).
 *
 * Группа (вид функции) → прототип (P01 «точка экстремума кубического
 * многочлена») → задача: параметры. Условие, разбор по этапам, подсказки
 * и ответ строит прототип по параметрам. Самотест (selftest.ts)
 * пересчитывает ответ независимо — численно, по самой функции.
 */

import type { Rng } from '@/lib/veroyatnost/generator';

/** Вид функции — группа классификации. */
export type VidId = 1 | 2 | 3 | 4 | 5 | 6 | 7;

/** Что спрашивают. */
export type VoprosId = 'A' | 'B' | 'V';

/** Параметры задачи: числа и выбор формы записи. */
export type Params = Record<string, number | string>;

/** Этап разбора: заголовок и строки с формулами в $…$. */
export interface Etap {
  title: string;
  lines: string[];
}

/** Шаг подсказки: вопрос и кнопки-ответы, одна верная. */
export interface HintStep {
  question: string;
  options: string[];
  correct: number;
  comment?: string;
}

/** Решённая задача. */
export interface Solved {
  /** Ответ для бланка: целое или конечная десятичная дробь. */
  answer: number;
  /** Функция, TeX без $: «y = x^3 - 75x + 19». */
  funkciya: string;
  /** Производная, TeX без $; null — решается без производной. */
  proizvodnaya: string | null;
  etapy: Etap[];
  hints: HintStep[];
}

/**
 * Независимый пересчёт для самотеста: сама функция обычной арифметикой
 * и где искать ответ. Для вопроса A — точка, в которой функция больше
 * (меньше) всех соседних; для B — наибольшее / наименьшее на отрезке;
 * для V — на всей области определения (её отрезок для перебора).
 */
export interface Chisla {
  f(x: number): number;
  /** Отрезок перебора: для B — отрезок условия, для A и V — область поиска. */
  otrezok: [number, number];
  /** Что ищем. */
  cel: 'max' | 'min';
  /** Ответ — точка (A) или значение (B, V). */
  chto: 'tochka' | 'znachenie';
}

/** Прототип задачи. */
export interface Prototype {
  id: string;
  vid: VidId;
  vopros: VoprosId;
  /** Короткое название типа для карты задания и фильтра тренажёра. */
  title: string;
  /** Пример функции для карты задания, TeX без $. */
  primer: string;
  /** Случайные параметры аналога. */
  gen(r: Rng): Params;
  /** Текст условия с формулами в $…$. */
  uslovie(p: Params): string;
  solve(p: Params): Solved;
  chisla(p: Params): Chisla;
}
