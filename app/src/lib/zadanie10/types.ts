/**
 * Модель задания №10 «Задачи с прикладным (физическим) содержанием».
 *
 * Группа (I–V) → прототип (П-01 «Мост: длина ванты») → задача:
 * параметры + текст условия. Ответ, таблица «Дано», разбор по этапам,
 * панель вычислений и пошаговые подсказки строит одна функция
 * прототипа `solve(params)` — и для задач открытого банка ФИПИ, и для
 * аналогов. Ответ в JSON банка — контроль этой функции (самотест).
 *
 * Условие ФИПИ хранится текстом как есть (с формулами в $…$), условие
 * аналога — тоже текстом: его написал автор банка по шаблону сюжета.
 */

/** Группы классификации: подстановка, квадратичные, степени, показательные, тригонометрия. */
export type GroupId = 'I' | 'II' | 'III' | 'IV' | 'V';

/** Параметры задачи: числа условия и выбор формы вопроса. */
export type Params = Record<string, number | string>;

/** Навыки — блоки «Опорных задач» и подписи «что тренирует прототип». */
export type SkillId =
  'podstanovka' | 'edinicy' | 'koren' | 'kv-neravenstvo' | 'stepen' | 'logarifm' | 'trigonometriya';

/** Строка таблицы «Дано»: обозначение, значение, единицы, что это. */
export interface DanoRow {
  /** TeX обозначения без $: «v_0». */
  oboz: string;
  /** TeX значения без $: «24», «\\dfrac{1}{700}». */
  znach: string;
  /** Единицы обычным текстом: «м/с». Пусто — безразмерная. */
  ed: string;
  /** Что это: «начальная скорость». */
  smysl: string;
}

/** Этап разбора: «Шаг 1. Что дано» и строки с формулами в $…$. */
export interface Etap {
  title: string;
  lines: string[];
}

/** Шаг подсказки: вопрос и кнопки-ответы, одна верная. */
export interface HintStep {
  question: string;
  options: string[];
  correct: number;
  /** Что сказать после верного ответа: одна строка с $…$. */
  comment?: string;
}

/** Строка панели «Считаем с умом»: пояснение и выкладка. */
export interface CalcLine {
  tekst: string;
  /** TeX без $; пусто — только пояснение. */
  tex?: string;
}

export interface Solved {
  /** Ответ числом: целое или конечная десятичная дробь. */
  answer: number;
  /** Что ищем: TeX обозначения без $ («t», «R_2»). */
  iskomoe: string;
  /** Единицы ответа: «с», «мин», «°». */
  edinicy: string;
  dano: DanoRow[];
  etapy: Etap[];
  /** Панель «Вычисления с умным сокращением» (раскрывается). */
  vychisleniya: CalcLine[];
  hints: HintStep[];
}

export interface Prototype {
  /** Код в данных: «P01». На сайте — «П-01». */
  id: string;
  /** Номер в классификации: 1…29 — ФИПИ, 30+ — из курса. */
  no: number;
  group: GroupId;
  /** Название сюжета: «Мост: длина ванты». */
  title: string;
  /** Главная формула сюжета, TeX без $. */
  formula: string;
  /** Что ищут: «длину ванты по формуле цепи». */
  ask: string;
  /** Навыки, которые тренирует прототип. */
  skills: SkillId[];
  /** Номера задач задачника, из которых собран прототип (пусто — из курса). */
  fipiNos: string;
  /** Альтернативный текст иллюстрации сюжета (слот картинки). */
  alt: string;
  solve(params: Params): Solved;
}

/** Задача банка: ФИПИ или аналог. */
export interface BankItem {
  /** «F001» — задача ФИПИ, «P01-a07» — аналог. */
  id: string;
  prototypeId: string;
  source: 'fipi' | 'analog';
  /** Номер в задачнике — только у ФИПИ. */
  no?: number;
  text: string;
  params: Params;
  answer: number;
  /** Сюжет аналога: «дрон», «электросамокат»; у ФИПИ — пусто. */
  plot?: string;
  /** Современный сюжет для подростков. */
  modern?: boolean;
}
