export interface PlotFull extends Plot {
  person: Person;
  /** «Кира», «Кофейня „Зерно“» — подлежащее. */
  subject: string;
  g: Gender;
  firm: boolean;
}

/** Сюжет по seed: тема, кто и зачем. `allowFirm` — можно ли брать организацию. */
export function pickPlot(
  rng: Rng,
  opts: { kind?: 'credit' | 'deposit'; allowFirm?: boolean } = {},
): PlotFull {
  const deck = rng.pick(DECKS);
  const person = rng.pick(PEOPLE);
  const year = rng.int(2026, 2030);
  const firmPick =
    opts.allowFirm !== false && opts.kind !== 'deposit' && deck.firms && rng.next() < 0.5
      ? rng.pick(deck.firms)
      : null;
  if (firmPick) {
    return {
      deck: deck.title,
      who: firmPick.name,
      goal: firmPick.goal,
      year,
      person,
      subject: firmPick.name,
      g: 'f',
      firm: true,
    };
  }
  const goal = rng.pick(opts.kind === 'deposit' ? deck.deposit : deck.credit);
  return {
    deck: deck.title,
    who: person.name,
    goal,
    year,
    person,
    subject: person.name,
    g: person.g,
    firm: false,
  };
}

/** Глагол прошедшего времени по роду: v(p, 'взял', 'взяла'). */
export const v = (p: { g: Gender }, m: string, f: string): string => (p.g === 'f' ? f : m);
