export function blokBySlug13(slug: string): Blok13 | undefined {
  return BLOKI_13.find((b) => b.slug === slug);
}

export function blokById13(id: string): Blok13 | undefined {
  return BLOKI_13.find((b) => b.id === id);
}

function seedsOf(prototypeId: string): string[] {
  return BANK_13.filter(([id]) => id === prototypeId).map(([, seed]) => seed);
}

/**
 * Десять задач блока. Обычный блок — по кругу по прототипам, у каждого
 * следующий seed банка; повышенные задачи встают в конец. «Определи тип» —
 * по одной задаче на прототип, последний seed банка.
 */
export function zadachiBloka(b: Blok13): ZadachaBloka[] {
  if (b.vid === 'tip') {
    return b.prototipy.map((prototypeId, i) => {
      const seeds = seedsOf(prototypeId);
      return { no: i + 1, prototypeId, seed: seeds[seeds.length - 1] ?? 'b1' };
    });
  }
  const rank = (id: string) => (PROTOTYPE_BY_ID[id]?.difficulty === 'hard' ? 1 : 0);
  const order = b.prototipy;
  const seeds = order.map(seedsOf);
  const out: ZadachaBloka[] = [];
  for (let round = 0; out.length < ZADACH_V_BLOKE; round += 1) {
    let added = false;
    order.forEach((prototypeId, i) => {
      const seed = seeds[i]?.[round];
      if (seed !== undefined && out.length < ZADACH_V_BLOKE) {
        out.push({ no: out.length + 1, prototypeId, seed });
        added = true;
      }
    });
    if (!added) break;
  }
  return out
    .sort((x, y) => rank(x.prototypeId) - rank(y.prototypeId))
    .map((z, i) => ({ ...z, no: i + 1 }));
}
