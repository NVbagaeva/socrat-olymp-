/* sheet/typography.js — мелочи набора, без которых лист выглядит
   черновиком.

   Правила ровно три:
     1. Неразрывный пробел после коротких слов (в, на, и, из, по, за…),
        чтобы предлог не оставался в конце строки один.
     2. Неразрывный пробел перед тире: тире не начинает строку.
     3. Кавычки-ёлочки и длинное тире вместо дефиса между словами.

   Разметку функция не портит: текст внутри тегов и атрибутов
   не трогается — строка разбирается на куски по угловым скобкам,
   и правила применяются только к тексту между тегами.
*/

var NBSP = ' ';
var MDASH = '—';

/* Слова, после которых пробел делается неразрывным: одна или две
   буквы. Список не перечисляется вручную — важна длина, а не слово.

   Разделитель перед словом выражение не съедает: иначе «и в окне»
   потребовало бы второго прохода, а подряд идущих коротких слов
   в русском тексте сколько угодно. Что слово короткое, а не хвост
   длинного, проверяет функция замены по символу слева. */
var SHORT = /([А-Яа-яЁёA-Za-z]{1,2})([ \t]+)/g;
var LETTER = /[А-Яа-яЁёA-Za-z]/;

function plain(text) {
  var out = String(text);

  /* Кавычки: пара прямых — в ёлочки. Внутренние кавычки в проекте
     не встречаются, поэтому вложенных «лапок» здесь нет. */
  out = out.replace(/"([^"]*)"/g, '«$1»');

  /* Дефис между пробелами — это тире. */
  out = out.replace(/ - /g, ' ' + MDASH + ' ');

  /* Перед тире пробел неразрывный. */
  out = out.replace(/ ([—–])/g, NBSP + '$1');

  /* После коротких слов — тоже. */
  out = out.replace(SHORT, function (whole, word, gap, at, source) {
    var before = at === 0 ? '' : source.charAt(at - 1);
    /* Хвост длинного слова коротким не считается. */
    if (LETTER.test(before)) { return whole; }
    return word + NBSP;
  });

  return out;
}

/**
 * Тот же набор поверх готовой разметки: куски внутри < … > остаются
 * как есть, текст между ними обрабатывается.
 */
function markup(html) {
  return String(html).split(/(<[^>]*>)/).map(function (piece) {
    return piece.charAt(0) === '<' ? piece : plain(piece);
  }).join('');
}

/** Экранирование текста между тегами. Кавычки здесь не трогаем:
   их превращает в ёлочки сам набор, а в тексте узла они безопасны. */
function escape(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/** Экранирование значения атрибута: там кавычка закрыла бы атрибут. */
function attr(value) {
  return escape(value).replace(/"/g, '&quot;');
}

/** Текст в разметку: сначала экранируем, потом набираем. */
function text(value) {
  return plain(escape(value));
}

const api = { plain: plain, markup: markup, escape: escape, attr: attr, text: text,
              NBSP: NBSP, MDASH: MDASH };

export default api;
export { plain, markup, escape, attr, text, NBSP, MDASH };
