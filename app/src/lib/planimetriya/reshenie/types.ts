/**
 * Решение задачи №1 по шагам: для школьника, который занимается сам.
 *
 * У каждого этапа — понятная подпись («Какой это треугольник»,
 * «Сумма углов треугольника»), пояснение словами — что делаем и
 * почему — и выкладка KaTeX. Вычисления с делением идут «с умом»:
 * сначала сокращаем, признаки делимости — в раскрывающейся панели.
 * В конце — сверка ответа с рисунком.
 *
 * Подсказки ученику — вопросы с кнопками-ответами: на каждом вопросе
 * на чертеже подсвечивается нужный элемент (слой подсказки сцены).
 */

export interface Sokr {
  tekst: string;
  /** Выкладка TeX без долларов (может быть пустой). */
  tex: string;
}

export interface ShagResheniya {
  /** Подпись этапа: что делаем. */
  zagolovok: string;
  /** Пояснение словами, формулы в $…$. */
  tekst: string[];
  /** Выкладки TeX без долларов: набираются крупно, по строке. */
  formuly?: string[];
  /** Сокращение «с умом»: шаги с признаками делимости — в раскрывающейся панели. */
  sokrashchenie?: Sokr[];
  /** Какой слой подсказки чертежа показать на этом шаге. */
  sloy?: number;
}

export interface VoprosPodskazki {
  vopros: string;
  /** Кнопки-ответы, формулы в $…$. Верная — под номером verno. */
  knopki: string[];
  verno: number;
  /** Пояснение после верного ответа. */
  poyasnenie: string;
  /** Слой чертежа, который подсвечивается на этом вопросе. */
  sloy?: number;
}

export interface Reshenie {
  shagi: ShagResheniya[];
  voprosy: VoprosPodskazki[];
  /** Сверка ответа с рисунком: «угол тупой — ответ больше 90°, сходится». */
  sverka: string;
  /** Ответ числом (тот же, что otvet прототипа). */
  otvet: number;
}
