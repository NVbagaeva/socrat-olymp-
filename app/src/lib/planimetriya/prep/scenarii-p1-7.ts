/** Последний шаг после «катет = сторона · отношение»: подставить и посчитать — ученик сам. */
function podstavOtvet(
  katet: string,
  storona: string,
  dlina: number,
  otnoshenie: string,
  znam: number,
  gipotenuza: boolean,
): ShagScenariya {
  const udobno =
    dlina % znam === 0 && dlina !== znam
      ? ` Удобно сначала разделить $${t(dlina)}$ на знаменатель дроби, потом умножить на числитель.`
      : '';
  return {
    vopros: `$${katet} = ${t(dlina)}\\cdot ${otnoshenie}$ — это уже ответ?`,
    knopki: [`Нет: подставь $${otnoshenie}$ из условия и посчитай`, 'Да, так и записать'],
    verno: 0,
    da: `в ответ пишут число. Подставь $${otnoshenie}$ из условия, умножь и посчитай сам.${udobno}${
      gipotenuza
        ? ` Проверка: катет $${katet}$ должен выйти короче гипотенузы $${storona} = ${t(dlina)}$.`
        : ''
    }`,
    utochnenie: `В записи ещё стоит $${otnoshenie}$, а не число. Чему он равен по условию?`,
    fakt: null,
  };
}

