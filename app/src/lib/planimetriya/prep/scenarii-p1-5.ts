/** «в 2 раза», «в 9 раз». */
function raz(n: number): string {
  const d = n % 10;
  const dd = n % 100;
  return d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? 'раза' : 'раз';
}

/** Первый вопрос любой задачи блока: что дано и что найти. */
