export interface ShagRazbora {
  /** Что делаем — заголовок шага, коротко. */
  chto: string;
  /** Почему это работает — абзацы словами. */
  zachem: readonly string[];
  /** Формулы шага (TeX без долларов), каждая отдельной строкой. */
  formuly?: readonly string[];
  /** Пункт задачи №15: с этого шага начинается пункт «а» или «б». */
  punkt?: 'а' | 'б';
}

export interface RazborStereo {
  /** Тип задачи (id из TIPY_3). */
  tip: string;
  /** Откуда задача (№3): прототип банка и его числа. У №15 прототипов нет. */
  prototip?: string;
  params?: Readonly<Record<string, unknown>>;
  /** Номер задачи в открытом банке ФИПИ; нет — задача банка прошлых лет. */
  fipi?: string;
  uslovie: string;
  model: () => Model;
  shagi: readonly ShagRazbora[];
  /** Ответ числом — для сверки с банком (№3) или с расчётом по модели (№15). */
  otvet: number;
  /** Ответ записью TeX, когда он не целое число: «$6\\sqrt{30}$». */
  otvetTex?: string;
  /**
   * Независимая проверка ответа (№15): та же величина, посчитанная по
   * координатам модели. Тест сверяет её с otvet.
   */
  proverka?: () => number;
}

/** Окружность горизонтальным многоугольником: сечение тела вращения. */
function krug(center: Vec3, r: number, n = 48): Section['points'] {
  return Array.from({ length: n }, (_, k): Vec3 => {
    const t = (2 * Math.PI * k) / n;
    return [center[0] + r * Math.cos(t), center[1] + r * Math.sin(t), center[2]];
  });
}

