type Kl = readonly [number, number, number];

const near = (a: number, b: number) => Math.abs(a - b) < 1e-9;
const okr = (x: number) => Math.round(x * 1e6) / 1e6;

/* ── Тела ───────────────────────────────────────────────────────── */

/**
 * Тело из клеток сетки xs × ys × zs: клетка [i, j, k] занимает
 * [xs[i], xs[i+1]] × [ys[j], ys[j+1]] × [zs[k], zs[k+1]].
 */
function korobki(xs: readonly number[], ys: readonly number[], zs: readonly number[], kletki: readonly Kl[]): Polyhedron {
  const telo = kubiki(kletki, 1);
  return {
    ...telo,
    vertices: telo.vertices.map(([i, j, k]): Vec3 => [xs[i] ?? 0, ys[j] ?? 0, zs[k] ?? 0]),
  };
}

/** Клетка тела в настоящих координатах: углы с наименьшими и наибольшими координатами. */
interface Kletka {
  min: Vec3;
  max: Vec3;
}

function kletkiTela(xs: readonly number[], ys: readonly number[], zs: readonly number[], kletki: readonly Kl[]): Kletka[] {
  return kletki.map(([i, j, k]) => ({
    min: [xs[i] ?? 0, ys[j] ?? 0, zs[k] ?? 0],
    max: [xs[i + 1] ?? 0, ys[j + 1] ?? 0, zs[k + 1] ?? 0],
  }));
}

const OSI = [0, 1, 2] as const;

/** Часть тела — прямоугольный параллелепипед: объём клеток равен объёму их габарита. */
function korobka(chast: readonly Kletka[]): boolean {
  if (chast.length === 0) return false;
  const obem = (a: Vec3, b: Vec3) => (b[0] - a[0]) * (b[1] - a[1]) * (b[2] - a[2]);
  const sum = chast.reduce((s, c) => s + obem(c.min, c.max), 0);
  const [lx, ly, lz] = OSI.map((o) => Math.min(...chast.map((c) => c.min[o])));
  const [hx, hy, hz] = OSI.map((o) => Math.max(...chast.map((c) => c.max[o])));
  return near(sum, obem([lx ?? 0, ly ?? 0, lz ?? 0], [hx ?? 0, hy ?? 0, hz ?? 0]));
}

/** Ось, перпендикулярная плоскому многоугольнику, лежащему в плоскости x, y или z = const. */
function osPloskosti(points: readonly Vec3[]): number | undefined {
  const p0 = points[0];
  if (p0 === undefined) return undefined;
  return OSI.find((o) => points.every((p) => near(p[o], p0[o])));
}

/** Плоский разрез вдоль оси: делит ли он тело на два параллелепипеда. */
function razrezNaKorobki(kl: readonly Kletka[], points: readonly Vec3[]): boolean {
  const os = osPloskosti(points);
  const p0 = points[0];
  if (os === undefined || p0 === undefined) return false;
  const c = p0[os] ?? 0;
  const pod = kl.filter((k) => (k.max[os] ?? 0) <= c + 1e-9);
  const nad = kl.filter((k) => (k.min[os] ?? 0) >= c - 1e-9);
  return pod.length + nad.length === kl.length && korobka(pod) && korobka(nad);
}

/** Протяжённость тела вдоль оси. */
function protyazhennost(body: Polyhedron, os: number): number {
  const c = body.vertices.map((v) => v[os] ?? 0);
  return Math.max(...c) - Math.min(...c);
}

const m = (a: Vec3, b: Vec3, text: number): Measure => ({ a, b, text: String(text) });

/** Все клетки сетки nx × ny × nz, кроме перечисленных. */
function vseKrome(nx: number, ny: number, nz: number, bez: readonly Kl[]): Kl[] {
  const ubrat = new Set(bez.map((k) => k.join(',')));
  const out: Kl[] = [];
  for (let i = 0; i < nx; i += 1)
    for (let j = 0; j < ny; j += 1)
      for (let k = 0; k < nz; k += 1) if (!ubrat.has(`${i},${j},${k}`)) out.push([i, j, k]);
  return out;
}

