type Kub = [number, number, number];

const okr = (x: number) => Math.round(x * 1e6) / 1e6;
const P = (x: number, y: number, z: number): Vec3 => [x, y, z];

/* ── Тела из кубиков и геометрия для пересчёта ─────────────────── */

/** Кубики коробки nx × ny × nz без тех, что отбрасывает bez. */
function korobka(nx: number, ny: number, nz: number, bez: (x: number, y: number, z: number) => boolean = () => false): Kub[] {
  const out: Kub[] = [];
  for (let x = 0; x < nx; x += 1)
    for (let y = 0; y < ny; y += 1)
      for (let z = 0; z < nz; z += 1) if (!bez(x, y, z)) out.push([x, y, z]);
  return out;
}

/** Ступенька, разложенная на единичные кубики (для проекций и «внутри»). */
function kubikiStupenki(s: Stupenka): Kub[] {
  return korobka(s.W, s.D, s.H, (x, _y, z) => z >= (x < s.w ? s.H : s.h));
}

/** Площадь проекции тела из кубиков вдоль оси os: число разных «столбиков». */
function proekciya(spisok: readonly Kub[], os: number): number {
  return new Set(spisok.map((k) => k.filter((_, i) => i !== os).join(','))).size;
}

/** Удвоенная сумма трёх проекций. */
function dvaProekcii(spisok: readonly Kub[]): number {
  return 2 * (proekciya(spisok, 0) + proekciya(spisok, 1) + proekciya(spisok, 2));
}

function vnutri(spisok: readonly Kub[]): (p: Vec3) => boolean {
  const est = new Set(spisok.map((k) => k.join(',')));
  return (p) => est.has(p.map((c) => Math.floor(c)).join(','));
}

/** Точка на грани-цели и её внешняя нормаль (единичная, по оси). */
function centrINormal(points: readonly Vec3[], inside: (p: Vec3) => boolean): { c: Vec3; n: Vec3 } {
  const [a, b, d] = points as [Vec3, Vec3, Vec3];
  const u: Vec3 = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const v: Vec3 = [d[0] - a[0], d[1] - a[1], d[2] - a[2]];
  const w: Vec3 = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
  const len = Math.hypot(...w);
  let n: Vec3 = [w[0] / len, w[1] / len, w[2] / len];
  /* Точка грани — середина диагонали a…d (у прямоугольника — центр,
     у «П» и шестиугольника ступеньки — точка их нижнего прямоугольника). */
  const c: Vec3 = [(a[0] + d[0]) / 2, (a[1] + d[1]) / 2, (a[2] + d[2]) / 2];
  if (inside([c[0] + n[0] * 0.25, c[1] + n[1] * 0.25, c[2] + n[2] * 0.25])) n = [-n[0], -n[1], -n[2]];
  return { c, n };
}

/** Грань не видна ни с одной стороны: луч от неё наружу снова входит в тело. */
function skrytaVProekciyah(points: readonly Vec3[], inside: (p: Vec3) => boolean): boolean {
  const { c, n } = centrINormal(points, inside);
  for (let t = 0.5; t < 30; t += 0.5) {
    if (inside([c[0] + n[0] * t, c[1] + n[1] * t, c[2] + n[2] * t])) return true;
  }
  return false;
}

/* ── Чертежи ────────────────────────────────────────────────────── */

function stupenka(s: Stupenka, alt: string, razmery: boolean, podpisi: readonly string[] = []) {
  const v = vershinyStupenki(s);
  const t = (n: string) => v[n] as Vec3;
  const body = teloStupenki(s, podpisi);
  const model: Model = {
    alt,
    view: 'cabinet',
    bodies: [body],
    ...(razmery
      ? {
          measures: [
            { a: t('A'), b: t('B'), text: String(s.W) },
            { a: t('A2'), b: t('B2'), text: String(s.w) },
            { a: t('A'), b: t('A2'), text: String(s.H) },
            { a: t('B'), b: t('B1'), text: String(s.h) },
            { a: t('B'), b: t('C'), text: String(s.D) },
          ],
        }
      : {}),
  };
  return { model, t, body };
}

function teloKubikov(spisok: readonly Kub[]): Polyhedron {
  return kubiki(spisok, 1);
}

