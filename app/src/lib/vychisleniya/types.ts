/**
 * Модель задания №8: прототип, подтип, сгенерированная задача.
 *
 * Прототип — тип задачи из таксономии (8.A … 8.Z). У прототипа есть
 * подтипы — формы условия одного и того же приёма; каждый подтип
 * помечен уровнем. Генератор подтипа — чистая функция от источника
 * случайных чисел: она либо возвращает задачу, либо null, когда
 * случайные параметры не подошли под ограничения, и тогда берётся
 * следующая попытка.
 */

import type { Rng } from './rng';

export type Group = 'I' | 'II' | 'III' | 'IV' | 'V';

export type Level = 'base' | 'advanced';

/** Параметры задачи: по ним задача узнаётся и исключается повтор. */
export type Params = Record<string, number | string>;

/**
 * Шаг решения: что делаем и почему — простыми словами, и выкладка.
 *
 *   chto — подпись шага: «Возводим степень в степень: показатели
 *          перемножаются». Формулы — в $…$. Без точки в конце.
 *   tex  — выкладка этого шага, формула TeX без долларов.
 *
 * Последний шаг кончается ответом. Вычисления — с умным сокращением:
 * подпись говорит, что на что сокращается и почему, а не «перемножим
 * всё» (см. docs/zadanie-8-razbory.md).
 */
export interface Shag {
  chto: string;
  tex: string;
}

/**
 * Признак делимости, по которому видно сокращение: «3» — сумма цифр
 * делится на 3. Тексты — priznaki.ts; показываются в сворачиваемой
 * панели «Признаки делимости» под решением.
 */
export type Priznak = '2' | '3' | '4' | '5' | '9' | '10' | '25';

/** Что даёт генератор подтипа. */
export interface Draft {
  /** Условие: текст с формулами в $…$. */
  uslovie: string;
  /** Ответ числом. */
  otvet: number;
  /** Решение по шагам; последний шаг кончается ответом. */
  razbor: Shag[];
  /** Признаки делимости, на которых держится сокращение в решении. */
  delimost?: Priznak[];
  params: Params;
  /**
   * Второй, независимый счёт ответа: выражение вычисляется численно
   * из тех же параметров функциями Math. Расхождение с otvet ловит
   * самотест — так же, как poModeli у задания №3.
   */
  proverka: number;
  /**
   * Подпись варианта: что в нём «главное» (основание, пара чисел,
   * угол). Банк не берёт два варианта с одной подписью.
   */
  signature?: string;
}

export interface Podtip {
  /** Идентификатор подтипа внутри прототипа: «1», «2», «chain». */
  id: string;
  level: Level;
  generate(r: Rng): Draft | null;
}

export interface Prototype {
  /** Код из таксономии: 8.A. */
  id: string;
  group: Group;
  /** Название на сайте: «Степени с одним основанием». */
  nazvanie: string;
  podtipy: Podtip[];
  /**
   * Ключи параметров условий, которые уже встречались в открытых
   * источниках: такие варианты генератор не отдаёт.
   */
  isklyucheniya?: string[];
}

/** Сгенерированная задача: черновик плюс откуда она. */
export interface Generated extends Draft {
  prototype: string;
  podtip: string;
  level: Level;
  seed: string;
}
