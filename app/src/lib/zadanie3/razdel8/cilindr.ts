/**
 * Раздел VIII, прототипы P03-84 … P03-87: шар и описанный цилиндр.
 *
 * У шара, вписанного в цилиндр, радиус цилиндра равен радиусу шара,
 * а высота — диаметру. И объём, и полная поверхность цилиндра при
 * этом ровно в полтора раза больше, чем у шара.
 *
 * Полтора здесь не написаны формулой: по объёму это отношение
 * измеренного объёма призмы к объёму шара, полученному по Кавальери
 * (призма минус две пирамиды), а по поверхности — отношение
 * измеренной полной поверхности к измеренной боковой, потому что
 * по теореме Архимеда боковая поверхность описанного цилиндра равна
 * поверхности шара.
 */

import { cylinderOverBallArea, cylinderOverBallVolume } from './common';
import { ballInCylinder } from './drawings';
import { ru } from '../format';
import { type Params, type Prototype, type Variant, num } from '../types';

function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

/* Отношения, измеренные на настоящих телах. Радиус взят любой —
   от него отношение не зависит, и это тоже часть проверки. */
const AREA_RATIO = cylinderOverBallArea(2.5);
const VOLUME_RATIO = cylinderOverBallVolume(3.5);

