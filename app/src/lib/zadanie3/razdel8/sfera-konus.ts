/**
 * Раздел VIII, прототипы P03-88 … P03-91: сфера и конус.
 *
 * Условие «центр сферы совпадает с центром основания конуса»
 * означает, что и окружность основания, и вершина лежат на сфере,
 * то есть радиус основания и высота конуса равны радиусу сферы.
 * Тогда образующая — гипотенуза равнобедренного прямоугольного
 * треугольника, то есть радиус, умноженный на √2, а объём шара
 * ровно вчетверо больше объёма такого конуса.
 *
 * Проверка ни того, ни другого не выписывает: образующая — это
 * измеренное расстояние между двумя точками сферы, а отношение
 * объёмов — отношение измеренных тел (шар по Кавальери, конус
 * пирамидой на описанном многоугольнике).
 */

import { ballOverConeVolume, slantBySphere, solveBySearch } from './common';
import { sphereAroundCone } from './drawings';
import { ru } from '../format';
import { type Params, type Prototype, type Variant, num } from '../types';

function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

/* Отношение объёмов, измеренное на настоящих телах. */
const BALL_OVER_CONE = ballOverConeVolume(4.5);

/** Общая часть условия обоих «сферных» прототипов, дословно. */
