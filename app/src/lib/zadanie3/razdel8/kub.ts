/**
 * Раздел VIII, прототипы P03-81 … P03-83: шар и куб.
 *
 * Шар, вписанный в куб, касается всех шести граней, поэтому его
 * радиус равен половине ребра. «Прямоугольный параллелепипед,
 * описанный около сферы» — тот же куб: касаться всех шести граней
 * сфера может только при равных рёбрах.
 *
 * Проверка: радиус вписанного шара не берётся как половина ребра,
 * а меряется — наименьшим расстоянием от центра куба до плоскостей
 * его граней. Объём куба тоже измеряется по координатам, а объём
 * шара сводится к измеримым телам по принципу Кавальери.
 */

import { ballOverPi, cubeVolume, inradiusOfCube } from './common';
import { ballInCube } from './drawings';
import { ru } from '../format';
import { type Params, type Prototype, type Variant, num } from '../types';

function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

