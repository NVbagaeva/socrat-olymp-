/**
 * Раздел V, прототипы P03-65…68: цилиндрический сосуд.
 *
 * Деталь вытесняет столько жидкости, сколько занимает сама, а при
 * переливании объём не меняется — поэтому все четыре прототипа
 * сводятся к отношению объёмов цилиндров с одинаковым или разным
 * радиусом. Проверка меряет эти объёмы на настоящей 48-угольной
 * призме, а не пересчитывает πr²h.
 */

import { solveBySearch, volumeUnits } from './common';
import { twoVessels, vesselWithRise } from './drawings';
import { razaWord, round, ru } from '../format';
import { type Params, type Prototype, type Variant, num, text } from '../types';

function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

/* ── P03-65. Деталь в сосуде: уровень поднялся на … ──────────────── */

export const P03_65: Prototype = {
  id: 'P03-65',
  razdel: 'V',
  nazvanie: 'Деталь в сосуде: уровень поднялся на …',
  tip: 'объём детали по подъёму уровня жидкости',
  zadachnik: [216, 219],
  status: 'есть',
  format: 'целое',

  uslovie: (p) =>
    `В цилиндрический сосуд налили ${ru(num(p, 'V'))} см³ воды. Уровень жидкости оказался равным ` +
    `${ru(num(p, 'H'))} см. В воду полностью погрузили деталь. При этом уровень жидкости в сосуде ` +
    `поднялся на ${ru(num(p, 'dh'))} см. Найдите объём детали. Ответ выразите в см³.`,

  dopustimo: (p) => num(p, 'V') > 0 && num(p, 'H') > 0 && num(p, 'dh') > 0,

  otvet: (p) => (num(p, 'V') * num(p, 'dh')) / num(p, 'H'),

  poModeli: (p) => {
    /* Сколько кубиков объёма приходится на одну единицу условия:
       считаем по настоящему столбику жидкости высотой H. */
    const scale = num(p, 'V') / volumeUnits(1, num(p, 'H'));
    /* Деталь вытеснила столбик той же ширины высотой dh. */
    return scale * volumeUnits(1, num(p, 'dh'));
  },

  chertezh: () =>
    vesselWithRise(
      'Цилиндрический сосуд с водой: показан уровень жидкости и уровень после погружения детали',
      2.2,
      3.6,
    ),

  shagi: (p) => {
    const V = num(p, 'V');
    const H = num(p, 'H');
    const dh = num(p, 'dh');
    const area = V / H;
    return [
      { text: `Площадь дна: ${ru(V)} : ${ru(H)} = ${ru(area)} см².`, value: area },
      {
        text: `Деталь вытеснила столбик высотой ${ru(dh)} см: ${ru(area)} · ${ru(dh)} = ${ru(area * dh)} см³.`,
        value: area * dh,
      },
    ];
  },

  varianty: [
    variant(1, 'задачник', 'задачник 216', { V: 2800, H: 16, dh: 13 }),
    variant(2, 'задачник', 'задачник 217', { V: 1200, H: 12, dh: 10 }),
    variant(3, 'задачник', 'задачник 218', { V: 1000, H: 8, dh: 3 }),
    variant(4, 'задачник', 'задачник 219', { V: 1400, H: 10, dh: 4 }),
    variant(5, 'домашка', 'домашка 40, вариант 2', { V: 1400, H: 8, dh: 13 }, 2275),
    variant(6, 'домашка', 'домашка 40, вариант 3', { V: 600, H: 5, dh: 3 }, 360),
    variant(7, 'домашка', 'домашка 40, вариант 4', { V: 3000, H: 25, dh: 5 }, 600),
    variant(8, 'новый', 'новый', { V: 900, H: 9, dh: 4 }),
    variant(9, 'новый', 'новый', { V: 2000, H: 20, dh: 7 }),
    variant(10, 'новый', 'новый', { V: 1500, H: 10, dh: 6 }),
  ],
};

/* ── P03-66. Деталь в сосуде: уровень вырос в … раз ──────────────── */

export const P03_66: Prototype = {
  id: 'P03-66',
  razdel: 'V',
  nazvanie: 'Деталь в сосуде: уровень вырос в … раз',
  tip: 'объём детали по тому, во сколько раз поднялся уровень',
  zadachnik: [220, 225],
  status: 'есть',
  format: 'десятичная',

  /* Задачник даёт эту задачу в двух единицах и с двумя формулировками:
     в см³ («налили … увеличился в … раза») и в дм³ («в котором
     находится … поднялся в … раза»). Обе взяты дословно. */
  uslovie: (p) => {
    const V = ru(num(p, 'V'));
    const k = ru(num(p, 'k'));
    const word = razaWord(num(p, 'k'));
    return text(p, 'unit') === 'дм'
      ? `В цилиндрический сосуд, в котором находится ${V} дм³ воды, опустили деталь. При этом ` +
          `уровень жидкости в сосуде поднялся в ${k} ${word}. Чему равен объём детали? ` +
          'Ответ выразите в дм³.'
      : `В цилиндрический сосуд налили ${V} см³ воды. В воду полностью погрузили деталь. При этом ` +
          `уровень жидкости в сосуде увеличился в ${k} ${word}. Найдите объём детали. ` +
          'Ответ выразите в см³.';
  },

  dopustimo: (p) => num(p, 'V') > 0 && num(p, 'k') > 1,

  otvet: (p) => num(p, 'V') * (num(p, 'k') - 1),

  poModeli: (p) => {
    const k = num(p, 'k');
    /* Объём жидкости — один настоящий столбик, после погружения —
       столбик в k раз выше; разница и есть деталь. */
    const scale = num(p, 'V') / volumeUnits(1, 1);
    return scale * (volumeUnits(1, k) - volumeUnits(1, 1));
  },

  chertezh: () =>
    vesselWithRise(
      'Цилиндрический сосуд с водой: показан уровень жидкости и уровень после погружения детали',
      2.6,
      3.4,
    ),

  shagi: (p) => {
    const V = num(p, 'V');
    const k = num(p, 'k');
    const unit = text(p, 'unit') === 'дм' ? 'дм³' : 'см³';
    return [
      {
        text: `Дно не меняется, значит объём вырос во столько же раз, во сколько уровень: в ${ru(k)} ${razaWord(k)}.`,
      },
      {
        text: `Деталь заняла разницу: ${ru(V)} · ${ru(k)} − ${ru(V)} = ${ru(round(V * (k - 1)))} ${unit}.`,
        value: V * (k - 1),
      },
    ];
  },

  varianty: [
    variant(1, 'задачник', 'задачник 220', { V: 500, k: 1.2, unit: 'см' }),
    variant(2, 'задачник', 'задачник 221', { V: 700, k: 1.4, unit: 'см' }),
    variant(3, 'задачник', 'задачник 222', { V: 8, k: 1.5, unit: 'дм' }),
    variant(4, 'задачник', 'задачник 223', { V: 4, k: 2.5, unit: 'дм' }),
    variant(5, 'задачник', 'задачник 224', { V: 10, k: 1.6, unit: 'дм' }),
    variant(6, 'задачник', 'задачник 225', { V: 5, k: 1.8, unit: 'дм' }),
    variant(7, 'домашка', 'домашка 41, вариант 1', { V: 600, k: 1.2, unit: 'см' }, 120),
    variant(8, 'домашка', 'домашка 41, вариант 2', { V: 500, k: 1.4, unit: 'см' }, 200),
    variant(9, 'домашка', 'домашка 41, вариант 3', { V: 700, k: 1.25, unit: 'см' }, 175),
    variant(10, 'домашка', 'домашка 41, вариант 4', { V: 10, k: 1.2, unit: 'дм' }, 2),
  ],
};

/* ── P03-67/68. Перелили в другой сосуд ─────────────────────────── */

function pourProto(
  id: string,
  nazvanie: string,
  zad: [number, number],
  status: 'есть' | 'добавить',
  wider: boolean,
  varianty: readonly Variant[],
): Prototype {
  return {
    id,
    razdel: 'V',
    nazvanie,
    tip: wider
      ? 'уровень падает во столько раз, во сколько выросла площадь дна'
      : 'уровень растёт во столько раз, во сколько уменьшилась площадь дна',
    zadachnik: zad,
    status,
    format: 'целое',

    uslovie: (p) =>
      `В цилиндрическом сосуде уровень жидкости достигает ${ru(num(p, 'h'))} см. На какой высоте ` +
      'будет находиться уровень жидкости, если её перелить во второй цилиндрический сосуд, ' +
      `диаметр которого в ${ru(num(p, 'n'))} ${razaWord(num(p, 'n'))} ${wider ? 'больше' : 'меньше'} ` +
      'диаметра первого? Ответ выразите в сантиметрах.',

    dopustimo: (p) => num(p, 'h') > 0 && num(p, 'n') > 1,

    otvet: (p) => {
      const n = num(p, 'n');
      return wider ? num(p, 'h') / (n * n) : num(p, 'h') * n * n;
    },

    poModeli: (p) => {
      const n = num(p, 'n');
      const r2 = wider ? n : 1 / n;
      /* Объём не меняется: ищем высоту во втором сосуде подбором,
         пока настоящий объём призмы радиуса r2 не сравняется с
         объёмом жидкости в первом сосуде. */
      const volume = volumeUnits(1, num(p, 'h'));
      return solveBySearch(volume, (x) => volumeUnits(r2, x));
    },

    chertezh: () =>
      twoVessels(
        `Два цилиндрических сосуда: у второго диаметр ${wider ? 'больше' : 'меньше'}`,
        wider ? 2 : 0.5,
      ),

    shagi: (p) => {
      const h = num(p, 'h');
      const n = num(p, 'n');
      const answer = wider ? h / (n * n) : h * n * n;
      return [
        {
          text: `Диаметр изменился в ${ru(n)} ${razaWord(n)}, значит площадь дна — в ${ru(n * n)} ${razaWord(n * n)}.`,
          value: n * n,
        },
        {
          text: `Объём тот же, поэтому уровень изменится обратно площади: ${ru(h)} ${wider ? ':' : '·'} ${ru(n * n)} = ${ru(answer)} см.`,
          value: answer,
        },
      ];
    },

    varianty,
  };
}

