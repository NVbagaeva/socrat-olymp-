function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

/* Отношения, измеренные на телах: во сколько раз цилиндр больше
   конуса по объёму и по боковой поверхности при высоте, равной
   радиусу основания. Радиус и высота здесь любые — отношение от
   них не зависит, и это тоже часть проверки. */
const VOLUME_RATIO = cylinderVolume(2.5, 4) / coneVolume(2.5, 4);
const LATERAL_RATIO = cylinderLateral(3, 3) / coneLateral(3, 3);

