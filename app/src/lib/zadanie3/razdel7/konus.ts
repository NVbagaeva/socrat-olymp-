/**
 * Раздел VII, прототипы P03-77 … P03-80: цилиндр и конус с общими
 * основанием и высотой.
 *
 * Объёмы относятся как три к одному, а боковые поверхности — как
 * √2 к одному, когда высота равна радиусу основания.
 *
 * Ни то, ни другое отношение в проверке не выписано формулой: оба
 * измеряются на настоящих телах — призме и пирамиде на одном и том
 * же ОПИСАННОМ около окружности многоугольнике. Апофема описанного
 * многоугольника равна радиусу ровно, поэтому наклонная высота
 * боковой грани пирамиды совпадает с образующей конуса точно, а
 * периметр в отношении сокращается без остатка.
 */

import { coneLateral, coneVolume, cylinderLateral, cylinderVolume } from './common';
import { R, cylinderAndCone } from './drawings';
import { ru } from '../format';
import { type Params, type Prototype, type Variant, num } from '../types';

function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

/* Отношения, измеренные на телах: во сколько раз цилиндр больше
   конуса по объёму и по боковой поверхности при высоте, равной
   радиусу основания. Радиус и высота здесь любые — отношение от
   них не зависит, и это тоже часть проверки. */
const VOLUME_RATIO = cylinderVolume(2.5, 4) / coneVolume(2.5, 4);
const LATERAL_RATIO = cylinderLateral(3, 3) / coneLateral(3, 3);

