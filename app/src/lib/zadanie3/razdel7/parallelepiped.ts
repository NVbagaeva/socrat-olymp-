/**
 * Раздел VII, прототипы P03-74/75: параллелепипед около цилиндра.
 *
 * Если параллелепипед описан около цилиндра, его основание — квадрат
 * со стороной, равной диаметру, а высота совпадает с высотой цилиндра.
 *
 * Проверка формулу 4r²h не повторяет: она строит настоящий
 * параллелепипед и меряет его объём по координатам, а в P03-75
 * подбором делением пополам ищет ту высоту, при которой измеренный
 * объём совпадёт с данным в условии.
 */

import { boxVolume, solveBySearch } from './common';
import { H, boxAroundCylinder } from './drawings';
import { ru } from '../format';
import { type Params, type Prototype, type Variant, num } from '../types';

function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

