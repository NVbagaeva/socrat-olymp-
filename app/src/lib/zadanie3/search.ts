/**
 * Подбор неизвестного делением пополам.
 *
 * Нужен для независимой проверки там, где формула ответа — короткая
 * алгебра с корнем: высота по боковому ребру, ребро по диагонали.
 * Пересчитать тот же корень второй раз — не проверка. Бисекция ищет
 * то же число без формулы вообще: на каждом шаге строится настоящее
 * тело и меряется расстояние или объём в его координатах, пока
 * измерение не совпадёт с данным в условии числом.
 *
 * f должна быть неубывающей на [0, ∞) — у длин, площадей и объёмов
 * это всегда так.
 */
export function solveBySearch(target: number, f: (x: number) => number): number {
  let lo = 0;
  let hi = 1;
  while (f(hi) < target) {
    hi *= 2;
  }
  for (let i = 0; i < 60; i += 1) {
    const mid = (lo + hi) / 2;
    if (f(mid) < target) {
      lo = mid;
    } else {
      hi = mid;
    }
  }
  return (lo + hi) / 2;
}
