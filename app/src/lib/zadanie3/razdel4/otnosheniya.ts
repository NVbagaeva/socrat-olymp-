/**
 * Раздел IV, прототипы P03-58…62: подобные конусы — сечение,
 * параллельное основанию, изменение радиуса или высоты, жидкость
 * в сосуде, отсечённый подобный конус. Все ответы — доли или разы,
 * то есть отношения объёмов или площадей подобных тел.
 *
 * Как проверяется независимо: точная площадь и точный объём конуса
 * содержат π, и другого пути посчитать их с нуля, не используя ту же
 * константу, нет — значит формулу «в квадрате» или «в кубе» саму по
 * себе так не проверить. Но ОТНОШЕНИЕ можно: конус приближается
 * правильной 48-угольной пирамидой (common.ts), и погрешность такого
 * приближения зависит только от числа граней — она одна и та же
 * что у большого тела, что у уменьшенной копии, поэтому в отношении
 * сокращается без остатка. Проверено численно на нескольких примерах:
 * отношение совпадает с точным до последнего знака double.
 */

import { approxBaseArea, approxTotalArea, approxVolume } from './common';
