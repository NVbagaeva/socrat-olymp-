/**
 * Раздел VI «Шар»: прототипы P03-71 … P03-73.
 *
 * Все три задачи — про то, как меняются поверхность и объём шара
 * при изменении радиуса: поверхность растёт как квадрат радиуса,
 * объём — как куб. Поэтому и проверка здесь ни разу не повторяет
 * формулы 4πr² и 4/3·πr³: она строит настоящие многогранники,
 * вписанные в шары, и сравнивает измеренные площади и объёмы.
 * Погрешность приближения одинакова у всех шаров семейства и в
 * отношении сокращается без остатка.
 */

import { areaUnits, approxArea, solveBySearch, volumeUnits } from './common';
import { twoBalls } from './drawings';
import { razaWord, round, ru, tex } from '../format';
import { type Params, type Prototype, type Variant, num } from '../types';

function variant(
  n: number,
  source: Variant['source'],
  ref: string,
  params: Params,
  sourceAnswer?: number,
): Variant {
  return sourceAnswer === undefined
    ? { n, source, ref, params }
    : { n, source, ref, params, sourceAnswer };
}

/* ── P03-71. Радиус шара с суммарной поверхностью ────────────────── */

export const P03_71: Prototype = {
  id: 'P03-71',
  razdel: 'VI',
  nazvanie: 'Радиус шара с суммарной поверхностью',
  tip: 'радиус шара, поверхность которого равна сумме поверхностей двух данных',
  zadachnik: [242, 245],
  status: 'есть',
  format: 'целое',

  uslovie: (p) =>
    `Радиусы двух шаров равны ${ru(num(p, 'a'))} и ${ru(num(p, 'b'))}. Найдите радиус шара, ` +
    'площадь поверхности которого равна сумме площадей поверхностей двух данных шаров.',

  dopustimo: (p) => num(p, 'a') > 0 && num(p, 'b') > 0,

  otvet: (p) => Math.sqrt(num(p, 'a') ** 2 + num(p, 'b') ** 2),

  poModeli: (p) => {
    /* Складываются не квадраты радиусов, а измеренные площади двух
       настоящих многогранников; радиус третьего ищется подбором,
       пока его измеренная площадь не сравняется с суммой. */
    const target = approxArea(num(p, 'a')) + approxArea(num(p, 'b'));
    return solveBySearch(target, (r) => approxArea(r));
  },

  chertezh: () => twoBalls('Два шара: радиусы относятся как три к четырём', 1.8, 2.4),

  shagi: (p) => {
    const a = num(p, 'a');
    const b = num(p, 'b');
    const sum = a * a + b * b;
    return [
      {
        text: 'Поверхность шара растёт как квадрат радиуса, поэтому складываются квадраты радиусов.',
        formula: `${tex(a)}^2 + ${tex(b)}^2 = ${tex(round(a * a))} + ${tex(round(b * b))} = ${tex(round(sum))}`,
        value: sum,
      },
      {
        text: 'Искомый радиус — корень из этой суммы.',
        formula: `\\sqrt{${tex(round(sum))}} = ${tex(round(Math.sqrt(sum)))}`,
        value: Math.sqrt(sum),
      },
    ];
  },

  varianty: [
    variant(1, 'задачник', 'задачник 242', { a: 9, b: 12 }),
    variant(2, 'задачник', 'задачник 243', { a: 16, b: 30 }),
    variant(3, 'задачник', 'задачник 244', { a: 7, b: 24 }),
    variant(4, 'задачник', 'задачник 245', { a: 21, b: 72 }),
    variant(5, 'домашка', 'домашка 45, вариант 1', { a: 5, b: 12 }, 13),
    variant(6, 'домашка', 'домашка 45, вариант 2', { a: 12, b: 35 }, 37),
    variant(7, 'домашка', 'домашка 45, вариант 3', { a: 11, b: 60 }, 61),
    variant(8, 'домашка', 'домашка 45, вариант 4', { a: 8, b: 15 }, 17),
    variant(9, 'новый', 'новый', { a: 20, b: 21 }),
    variant(10, 'новый', 'новый', { a: 9, b: 40 }),
  ],
};

