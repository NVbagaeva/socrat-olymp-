/** Многочлен по убыванию степеней в TeX с переменной v. */
function poly(terms: [number, number][], v = 'x'): string {
  let out = '';
  for (const [c, p] of terms) {
    if (c === 0) {
      continue;
    }
    const abs = Math.abs(c);
    const coef = p > 0 && abs === 1 ? '' : d(abs);
    const xp = p === 0 ? '' : p === 1 ? v : `${v}^{${p}}`;
    out += `${c < 0 ? '-' : out === '' ? '' : '+'}${coef}${xp}`;
  }
  return out === '' ? '0' : out;
}

function nz(r: Rng, lo: number, hi: number): number {
  for (let i = 0; i < 40; i += 1) {
    const x = r.int(lo, hi);
    if (x !== 0) {
      return x;
    }
  }
  return 1;
}

