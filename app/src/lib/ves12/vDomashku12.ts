/**
 * Тип №12 можно положить «В домашку» (этапы 4б и 4е): наборы с ответом
 * выбором формулы (12Q.A, 12Q.G) база сверить не может, их нет и в
 * адаптере «Собрать вариант». Совпадение проверяет scripts/check-dz2.mjs.
 */
export function vDomashku12(tip: string): boolean {
  return tip !== '12Q.A' && tip !== '12Q.G';
}
