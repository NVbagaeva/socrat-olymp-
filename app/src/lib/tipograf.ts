/**
 * Типограф строки текста (формулы $…$ не трогает):
 *  — неразрывный пробел между числом и словом после него: «2 балла»,
 *    «1 балл», «2027 года» не разрываются переносом;
 *  — неразрывный пробел между формулой и словом после неё:
 *    «$1\,250$ тыс. руб.» не оставляет «тыс.» на новой строке;
 *  — дефис между буквами и цифрой — неразрывный: «ЕГЭ-2027» не
 *    рвётся на «ЕГЭ-» и «2027».
 * Результат идёт в Tex / typeset как обычно.
 */
export function tipograf(text: string): string {
  return text
    .split(/(\$[^$]*\$)/)
    .map((kusok, i) => {
      if (i % 2 === 1) return kusok;
      const t = kusok
        .replace(/(\d) (?=[A-Za-zА-Яа-яЁё«])/g, '$1 ')
        .replace(/([A-Za-zА-Яа-яЁё])-(?=\d)/g, '$1‑');
      return i > 0 ? t.replace(/^ (?=[а-яё])/, ' ') : t;
    })
    .join('');
}
