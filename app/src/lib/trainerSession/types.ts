/**
 * Общие типы сессии тренажёра.
 *
 * Сессия — это набор сгенерированных заданий (payload, его формат
 * знает только сам тренажёр) и состояние экрана (ui). Всё остальное —
 * номер версии схемы, время, пауза — общее для всех тренажёров.
 */

/**
 * Версия схемы записи. Меняется, когда формат хранения перестаёт читаться.
 *
 * 2 — в записи число заданий (total), задания хранятся упакованными:
 * вместо готовых чертежей и разборов — параметры, по которым тренажёр
 * собирает их заново (pack/unpack оболочки). Записи версии 1 весили до
 * полутора мегабайт и при входе убираются.
 */
export const TRAINER_SCHEMA_VERSION = 2;

/** Чем закончилось задание: решено само или пройдено по подсказке. */
export type TaskMark = 'right' | 'hinted';

/**
 * То, что сессии нужно знать о состоянии любого экрана задания. Всё
 * остальное (введённый ответ, шаг подсказки, открытые поля) экран
 * добавляет сам: общему модулю оно не нужно, он хранит его как есть.
 *
 * Индексы в marks и tried — позиции в порядке показа (после раскладки
 * подхода), а не номера в пуле заданий.
 */
export interface BaseUi {
  /** Номер текущего задания (с нуля). */
  index: number;
  /** Чем закончилось задание. Нет записи — задание не закрыто. */
  marks: Record<number, TaskMark>;
  /** Задания, в которых ученик ошибся хотя бы раз. */
  tried: Record<number, true>;
  /**
   * Раскладка подхода: индексы заданий пула в порядке показа.
   * null — экран показывает пул как есть.
   */
  order: number[] | null;
  /**
   * Сколько раз ответ не сошёлся за тренировку (в поле, на шагах
   * подсказки). Необязательно: экран без счётчика его не передаёт, и
   * строки «Неверных попыток» в итогах тогда нет.
   */
  misses?: number;
}

/** Служебная часть записи: без заданий и состояния экрана. */
export interface SessionHead {
  scope: string;
  /** Идентификатор тренировки: новый на каждый запуск. */
  id: string;
  createdAt: number;
  updatedAt: number;
  /** Номер записи: растёт с каждой записью, по нему вкладки понимают, кто новее. */
  rev: number;
  /** Вкладка, сделавшая последнюю запись. */
  writer: string;
  paused: boolean;
  /** Активное время тренировки, мс: пауза и скрытая вкладка не считаются. */
  activeMs: number;
  /** Сколько заданий в тренировке: для вопроса «решено X из N» без распаковки заданий. */
  total: number;
}

/** Запись из хранилища после разбора. */
export interface StoredSession extends SessionHead {
  schemaVersion: number;
  /** Состояние экрана на момент последнего действия. null — действий ещё не было. */
  ui: unknown;
  /** Задания тренировки в формате тренажёра. */
  payload: unknown;
}

/** Чем кончилась запись в хранилище. */
export type WriteResult =
  | 'ok'
  /** Не хватило места даже после того, как убраны старые тренировки других разделов. */
  | 'quota'
  /** Хранилища нет или запись запрещена (приватный режим). */
  | 'denied';

/** Результат чтения хранилища. */
export type ReadResult =
  | { status: 'none' }
  | { status: 'ok'; session: StoredSession }
  /** Запись была, но не читается: устарела или повреждена. Из хранилища убрана. */
  | { status: 'reset'; reason: 'version' | 'broken' };
