/**
 * Модель задания №7 «Простейшие уравнения».
 *
 * Группа (I–V) → прототип (П-01 «1/(kx + b) = c») → задача: параметры
 * уравнения и текст условия. Уравнение, разбор по этапам, панель
 * вычислений, пошаговые подсказки и ответ строит прототип по параметрам
 * — одинаково для задач открытого банка ФИПИ и для аналогов. Ответ в
 * JSON банка — контроль: самотест пересчитывает его решателем и
 * независимо, подстановкой в исходное уравнение (`chisla`).
 *
 * Условие ФИПИ хранится текстом как есть (формулы в $…$), условие
 * аналога собирает прототип (`uslovie`).
 */

/** Группы классификации: линейные и степенные, иррациональные, показательные, логарифмические, тригонометрические. */
export type GroupId = 'I' | 'II' | 'III' | 'IV' | 'V';

/** Параметры уравнения: коэффициенты и выбор формы записи. */
export type Params = Record<string, number | string>;

/** Навыки — блоки «Опорных задач» и подписи «что тренирует прототип». */
export type SkillId =
  | 'stepeni'
  | 'korni'
  | 'log-opredelenie'
  | 'log-svoystva'
  | 'proporciya'
  | 'perenos'
  | 'diskriminant'
  | 'trig-krug';

/** Что спрашивают: корень, меньший / больший, наименьший положительный / наибольший отрицательный. */
export type Vopros = 'koren' | 'menshiy' | 'bolshiy' | 'minPol' | 'maxOtr';

/** Этап разбора: «Шаг 1. Тип уравнения и план» и строки с формулами в $…$. */
export interface Etap {
  title: string;
  lines: string[];
}

/** Шаг подсказки: вопрос и кнопки-ответы, одна верная. */
export interface HintStep {
  question: string;
  options: string[];
  correct: number;
  /** Что сказать после верного ответа: одна строка с $…$. */
  comment?: string;
}

/** Строка панели «Считаем с умом»: пояснение и выкладка. */
export interface CalcLine {
  tekst: string;
  /** TeX без $; пусто — только пояснение. */
  tex?: string;
}

export interface Solved {
  /** Ответ для бланка: целое или конечная десятичная дробь. */
  answer: number;
  /** Уравнение, TeX без $. */
  uravnenie: string;
  /** Корни после преобразований — до отбора (у тригонометрии — ближайшие к нулю). */
  korni: number[];
  /** Посторонние корни: отсекли ОДЗ или условие $x\ge0$. */
  postoronnie: number[];
  etapy: Etap[];
  /** Панель «Считаем с умом» (раскрывается). */
  vychisleniya: CalcLine[];
  hints: HintStep[];
}

/**
 * Независимый пересчёт: левая и правая части уравнения как функции x
 * и ОДЗ — прямо по параметрам, обычной арифметикой, без решателя.
 */
export interface Chisla {
  lhs(x: number): number;
  rhs(x: number): number;
  /** Входит ли x в ОДЗ исходного уравнения. */
  odz(x: number): boolean;
  /** Периодическое уравнение (тригонометрия): корней бесконечно много. */
  periodicheskoe?: boolean;
}

export interface Prototype {
  /** Код в данных: «P01». На сайте — «П-01». */
  id: string;
  /** Номер в классификации: 1…28 — список автора, 29+ — дополнения. */
  no: number;
  group: GroupId;
  /** Короткое название: «Дробь с единицей в числителе». */
  title: string;
  /** Общий вид уравнения, TeX без $. */
  formula: string;
  /** Навыки, которые тренирует прототип. */
  skills: SkillId[];
  /** Откуда задачи ФИПИ: «Блок 1, задание 1; Блок 2, задание 2; подборка 6, 8». Пусто — в источниках нет. */
  fipiNos: string;
  /** Уравнение по параметрам, TeX без $. */
  uravnenie(p: Params): string;
  /** Текст условия аналога. */
  uslovie(p: Params): string;
  /** Что спрашивают в задаче с этими параметрами. */
  vopros(p: Params): Vopros;
  chisla(p: Params): Chisla;
  solve(p: Params): Solved;
}

/** Задача банка: ФИПИ или аналог. */
export interface BankItem {
  /** «F001» — задача ФИПИ, «P01-a07» — аналог. */
  id: string;
  prototypeId: string;
  source: 'fipi' | 'analog';
  /** Номер ФИПИ по порядку — только у ФИПИ. */
  no?: number;
  /** Где в источнике: «Блок 1, задание 1 №3», «подборка №7» — только у ФИПИ. */
  gde?: string;
  text: string;
  params: Params;
  answer: number;
}
