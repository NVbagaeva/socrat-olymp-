/**
 * Ответ ученика в тренажёре и опорных задачах №7 — по общему правилу
 * записи ответа (lib/otvet), как в №8 и №3.
 *
 * В бланк ЕГЭ записывают целое число или конечную десятичную дробь.
 * Обыкновенная дробь с верным значением («7/5» вместо «1,4») — не
 * ошибка и не верный ответ: подсказка «запишите десятичной дробью»,
 * попытка не тратится. Прочая неверная запись («5 см», «1e3») —
 * подсказка о формате. Ответ через π (x = π/6 вместо 0,5) — своя
 * подсказка: в №7 это самая частая ошибка записи.
 *
 * Прежде №7 засчитывал любую верную запись числа, дробь тоже
 * (lib/zadanie7/otvet.ts, answerMatches7). Та проверка осталась для
 * листов и самотеста; отпечатки ответов в банке те же.
 */

import { readAnswer, type Reading } from '@/lib/otvet';
import { answerMatches7, estPi } from '../otvet';

export { estPi };

/** Прочитать ответ по правилам бланка и сверить с отпечатком задачи. */
export function readSealed7(vvod: string, seal: string): Reading {
  return readAnswer(vvod, 'trenazher', (value) => answerMatches7(value, seal));
}
