export interface MikroZadacha {
  id: string;
  uslovie: string;
  answer: number;
  podskazka: string;
  razbor: string[];
  /** Независимый пересчёт ответа (только для самотеста). */
  proverka: () => number;
}

export interface BlokOpornyh {
  id: SkillId;
  slug: string;
  no: number;
  nazvanie: string;
  /** Короткое описание для карточки — без формул (правило раздела). */
  opisanie: string;
  /** «Запомни»: правило блока, с формулами. */
  zapomni: string;
  /** Прототипы, где навык нужен. */
  prototipy: string[];
  zadachi: MikroZadacha[];
}

function z(
  id: string,
  uslovie: string,
  answer: number,
  podskazka: string,
  razbor: string[],
  proverka: () => number,
): MikroZadacha {
  return { id, uslovie, answer, podskazka, razbor, proverka };
}

