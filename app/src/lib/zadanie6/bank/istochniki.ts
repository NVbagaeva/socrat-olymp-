import istochnikiJson from '../../../data/zadanie6/istochniki.json';
import type { BankItem } from '../types';

export const ISTOCHNIKI: BankItem[] = istochnikiJson as unknown as BankItem[];

/** Подпись источника на сайте. */
export function podpisIstochnika(it: BankItem): string {
  switch (it.source) {
    case 'fipi':
      return 'открытый банк ФИПИ';
    case 'demo':
      return 'демоверсия ФИПИ';
    default:
      return 'не из открытого банка';
  }
}
