/**
 * Группа I. Диаграмма Эйлера: прямоугольник — опыт $S$, точки —
 * элементарные события, около точки — значение величины $X$ (и её
 * вероятность в 6.1).
 *
 *   6.1  у точек значения и вероятности → $P(X=k)$ — сложить вероятности;
 *   6.2  исходы равновозможны → $P(X=k)$ — число точек : общее число.
 *
 * Параметры: `xs` — значения точек по порядку, `ps` — вероятности в
 * целых долях `den` (только 6.1), `k` — какое значение спрашивают,
 * `v` — буква величины, `sj` — ключ сюжета (у сюжетных задач).
 */

