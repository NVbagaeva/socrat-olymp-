const PO_KLYUCHU = new Map([...SYUZHETY_P01, ...SYUZHETY_P02].map((s) => [s.key, s]));

export function syuzhetEilera(key: string): SyuzhetEilera {
  const s = PO_KLYUCHU.get(key);
  if (s === undefined) {
    throw new Error(`нет сюжета диаграммы ${key}`);
  }
  return s;
}

/* ── Общее ─────────────────────────────────────────────────────────── */

function bukva(p: Params): string {
  return str(p, 'v', BUKVY);
}

/** Номера точек с X = k. */
function nuzhnye(xs: readonly number[], k: number): number[] {
  return xs.map((x, i) => (x === k ? i : -1)).filter((i) => i >= 0);
}

function risEilera(p: Params, sVer: boolean, vydelit?: number[]): Ris {
  const xs = arr(p, 'xs');
  const ps = sVer ? arr(p, 'ps') : [];
  const den = sVer ? num(p, 'den') : 1;
  return {
    vid: 'eiler',
    tochki: xs.map((x, i) => ({
      x: t(x),
      ...(sVer ? { p: pt(ps[i] as number, den) } : {}),
    })),
    zerno: `e|${xs.join(',')}|${ps.join(',')}`,
    ...(vydelit ? { vydelit } : {}),
  };
}

