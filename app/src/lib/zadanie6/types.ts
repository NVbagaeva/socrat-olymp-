/**
 * Модель задания №6 «Случайные величины и распределения».
 *
 * Группа (I–V) → прототип (6.1 «диаграмма Эйлера: сложить вероятности
 * точек») → задача: параметры и текст условия. Рисунок условия
 * (диаграмма Эйлера, дерево, таблица распределения, запись
 * $X\sim(\ldots)$), разбор по шагам, панель «Считаем с умом» и
 * пошаговые подсказки строит прототип по параметрам — одинаково для
 * исходных задач и для аналогов. Ответ в JSON банка — контроль:
 * самотест пересчитывает его решателем (точными дробями) и независимо,
 * обычной арифметикой прямо по параметрам (`pereschet`).
 *
 * Вероятности в параметрах — целые доли общего знаменателя `den`
 * (сотые, тысячные, у 6.13 — простые дроби): так сумма распределения
 * равна 1 ровно, без хвостов двоичной арифметики.
 */

/** Группы классификации: диаграммы Эйлера, условная вероятность, ожидание, оценка вероятности, дисперсия. */
export type GroupId = 'I' | 'II' | 'III' | 'IV' | 'V';

/** Параметры задачи: числа, наборы чисел и ключи формы записи. */
export type Params = Record<string, number | string | number[]>;

/** Навыки — блоки «Опорных задач» и подписи «что тренирует прототип». */
export type SkillId =
  'slozhit' | 'chastoty' | 'derevo' | 'stroka-xp' | 'kvadrat-e' | 'otkloneniya' | 'promezhutok';

/** Строка таблицы: жирный заголовок слева и ячейки (строки с $…$). */
export interface StrokaTablicy {
  zag: string;
  yach: string[];
}

/**
 * Таблица распределения или таблица решения. `vydelit` — номера
 * столбцов (с нуля, без заголовка), которые подсвечены: добавленный
 * столбец «проигрыш», значения, попавшие в промежуток. На листе ученика
 * подсветки нет — она бывает только в разборе.
 */
export interface Tablica {
  stroki: StrokaTablicy[];
  vydelit?: number[];
  /** Подсвеченные строки (добавленная строка $x_ip_i$). */
  vydelitStroki?: number[];
}

/** Точка диаграммы Эйлера: значение величины и (если задана) вероятность. */
export interface TochkaEilera {
  /** Значение случайной величины, TeX без $. */
  x: string;
  /** Вероятность элементарного события, TeX без $; в 6.2 её нет. */
  p?: string;
}

/** Ветвь дерева: родитель (null — из корня), вероятность, имя листа. */
export interface VetvDereva {
  id: string;
  parent: string | null;
  /** Вероятность ветви, TeX без $ (0{,}6). */
  p: string;
  /** Значение вероятности — для произведений под листьями в разборе. */
  pv: number;
  /** Имя листа: a, b, c… У внутренних вершин пусто. */
  imya: string;
}

/** Событие на дереве: овал вокруг подряд стоящих листьев. */
export interface SobytieDereva {
  imya: string;
  listya: string[];
}

export type Ris =
  | {
      vid: 'eiler';
      tochki: TochkaEilera[];
      /** Зерно раскладки точек: одна задача — всегда один рисунок. */
      zerno: string;
      /** Номера выделенных точек — только в разборе. */
      vydelit?: number[];
    }
  | {
      vid: 'derevo';
      vetki: VetvDereva[];
      sobytiya: SobytieDereva[];
      /** Выделенные листья (исходы $A\cap B$) — только в разборе. */
      vydelit?: string[];
      /** Произведения под листьями — только в разборе. */
      proizvedeniya?: boolean;
    }
  | { vid: 'tablica'; tablica: Tablica }
  | { vid: 'zapis'; tex: string };

/** Условие: текст, рисунок и (если есть) вопрос после рисунка. */
export interface Uslovie {
  text: string;
  ris?: Ris;
  posle?: string;
}

/** Этап разбора: «Шаг 1. …», строки с формулами и, если нужно, таблица или рисунок. */
export interface Etap {
  title: string;
  lines: string[];
  tablica?: Tablica;
  ris?: Ris;
}

/** Шаг подсказки: вопрос и кнопки-ответы, одна верная. */
export interface HintStep {
  question: string;
  options: string[];
  correct: number;
  /** Что сказать после верного ответа: одна строка с $…$. */
  comment?: string;
}

/** Строка панели «Считаем с умом»: пояснение и выкладка. */
export interface CalcLine {
  tekst: string;
  /** TeX без $; пусто — только пояснение. */
  tex?: string;
}

export interface Solved {
  /** Ответ для бланка: целое или конечная десятичная дробь. */
  answer: number;
  etapy: Etap[];
  /** Панель «Считаем с умом» (раскрывается). */
  vychisleniya: CalcLine[];
  hints: HintStep[];
}

/**
 * Что должно сходиться ровно: распределение в сумме даёт весь
 * знаменатель, ветви из одной вершины — тоже, проигрышных билетов не
 * меньше нуля. Целые числа — проверка точная.
 */
export interface Summa {
  chto: string;
  /** Целые доли. */
  doli: number[];
  /** Чему равна сумма (знаменатель); у «не меньше нуля» — null. */
  nado: number | null;
}

/** Где сюжетная задача: тема из списка задания. */
export type Tema =
  | 'igry'
  | 'sport'
  | 'dostavka'
  | 'pogoda'
  | 'socseti'
  | 'ekzameny'
  | 'magaziny'
  | 'transport'
  | 'shkola'
  | 'kofeynya';

export interface Prototype {
  /** Код в данных: «P01». На сайте — «6.1». */
  id: string;
  /** Номер в классификации: 1…15 — список автора. */
  no: number;
  group: GroupId;
  /** Короткое название: «Диаграмма Эйлера: вероятности у точек». */
  title: string;
  /** Что спрашивают, одной строкой с $…$. */
  formula: string;
  /** Навыки, которые тренирует прототип. */
  skills: SkillId[];
  /** Откуда исходные задачи: «Математическое ожидание, №1, 4, 9». Пусто — нет. */
  istochnik: string;
  /** Условие по параметрам (текст аналога; у исходных задач текст берётся из банка). */
  uslovie(p: Params): Uslovie;
  /** Рисунок условия по параметрам — общий для исходной задачи и аналога. */
  ris(p: Params): Ris | undefined;
  solve(p: Params): Solved;
  /** Независимый пересчёт ответа обычной арифметикой прямо по параметрам. */
  pereschet(p: Params): number;
  /** Суммы, которые должны сходиться ровно. */
  summy(p: Params): Summa[];
}

/** Откуда задача: открытый банк, демоверсия ФИПИ, образец стороннего банка, аналог. */
export type Istochnik = 'fipi' | 'demo' | 'obrazec' | 'analog';

/** Задача банка. */
export interface BankItem {
  /** «S01» — исходная задача, «P01-a07» — аналог. */
  id: string;
  prototypeId: string;
  source: Istochnik;
  /** Где в источнике: «Математическое ожидание, №3» — у исходных задач. */
  gde?: string;
  /** Номер исходной задачи по порядку. */
  no?: number;
  /** Нейтральная формулировка, как в исходнике, или сюжет. */
  stil: 'fipi' | 'syuzhet';
  /** Тема сюжетной задачи. */
  tema?: Tema;
  /** Короткая метка сюжета для галереи: «лутбоксы». */
  plot?: string;
  text: string;
  posle?: string;
  params: Params;
  answer: number;
}
