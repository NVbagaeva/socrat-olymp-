/**
 * Проверка числового ответа в разделах с допуском.
 *
 * Обёртка над общим модулем ответов lib/otvet: разбор записи один на
 * весь сайт. Здесь — то, чем пользуются разделы, где ответ может быть и
 * обыкновенной дробью (№3, №4, №5, №12, карточки): число из записи
 * бланка или из дроби «a/b» и сравнение с допуском 1e-9.
 *
 * Задание №8 сверяет ответ точно, по нормальной записи
 * (lib/otvet → readAnswer); остальные разделы переходят на точное
 * сравнение по мере того, как их подключают к общим модулям.
 *
 * Модуль без зависимостей от браузера и KaTeX: его берёт клиентский
 * экран задачи.
 */

import { parseNumber } from './otvet';

/**
 * Строка ответа как число: «1,5», «1.5», «−1,5», «3/2». Нечисловая или
 * неоднозначная запись («1e3», «0x10», «/2», «3 1/2», «5 см») — null.
 */
export function parseAnswer(value: string): number | null {
  return parseNumber(value);
}

/** Одно ли это число. Допуск нужен дробям вроде 1/3. */
export function sameNumber(input: string, answer: string): boolean {
  const left = parseAnswer(input);
  const right = parseAnswer(answer);
  return left !== null && right !== null && Math.abs(left - right) < 1e-9;
}
