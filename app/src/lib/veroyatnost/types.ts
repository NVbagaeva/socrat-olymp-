/**
 * Формат прототипа заданий №4 и №5 и его вариантов.
 *
 * Прототип — группа задач задачника с одной формулировкой и одним
 * способом решения; различаются только числа. Здесь описано, из чего
 * такой прототип состоит: шаблон условия, ограничения на числа,
 * формула ответа, вторая независимая проверка перебором исходов,
 * шаги разбора и ровно десять зафиксированных вариантов.
 *
 * Устройство повторяет банк задания №3 (lib/zadanie3/types.ts) с
 * двумя отличиями: чертежа у задачи по вероятности нет, а вторая
 * проверка делается не по трёхмерной модели, а перебором
 * пространства исходов — это честно другой способ счёта, а не та же
 * формула, переписанная второй раз.
 *
 * Варианты не случайные: они лежат в данных и не меняются между
 * заходами. Откуда взят каждый — записано в самом варианте.
 */

import type { Method, Vizual } from './model';

/** Формат ответа, как его ждёт ЕГЭ. */
export type AnswerFormat = 'целое' | 'десятичная';

/** Откуда взят вариант. */
export type Source = 'задачник' | 'конспект' | 'новый';

/** Значения параметров варианта. */
export type Params = Record<string, number | string>;

export interface Variant {
  /** Номер варианта от 1 до 10. */
  n: number;
  source: Source;
  /** Ссылка на источник: «задачник 04, № 17». */
  ref: string;
  params: Params;
}

/**
 * Шаг разбора.
 *
 * `text` — слова шага, `formula` — его формула в TeX: она набирается
 * KaTeX на сборке и приходит в карточку настоящими дробями и
 * курсивными буквами. `value` — число, которое шаг считает; у
 * последнего шага оно равно ответу, это проверяет автотест.
 */
export interface Step {
  text: string;
  formula?: string;
  value?: number;
}

/**
 * Метод решения и рисунок к нему — то, что нужно карточке задачи
 * (раздел 04 референса). Обязательно у каждой задачи задания №4;
 * автотест это проверяет. У задания №5 методики пока нет: его
 * содержание на пять методов не раскладывалось.
 */
export interface Metodika {
  /** Один из пяти методов. */
  metod: Method;
  /**
   * Признаки в условии, по которым метод узнаётся: от одного до трёх.
   * Режим «Узнай метод» показывает их после ответа ученика; до
   * ответа они закрыты, как и сам метод, — иначе подсказывали бы.
   */
  methodHints: readonly string[];
  /** Фраза после «Метод:» — почему здесь именно он. */
  fraza(p: Params): string;
  /**
   * Параметры рисунка: открытая часть уходит вместе с условием,
   * подсветка благоприятного — только вместе с решением, потому что
   * она выдаёт m, а значит и ответ.
   */
  vizual(p: Params): Vizual;
}

export interface Prototype {
  /** Идентификатор: «p4-01». Он же ключ прогресса и фильтра. */
  id: string;
  /** Блок задачника, по которому фильтрует тренажёр. */
  blok: string;
  /** Название прототипа на карточке и в списке. */
  nazvanie: string;
  /** Что именно ищут — одной строкой. */
  tip: string;
  /** Диапазон номеров задачника, откуда прототип собран. */
  zadachnik: readonly [number, number];
  format: AnswerFormat;
  /**
   * До скольких знаков округляется ответ у этого варианта. null —
   * округления нет, и тогда ответ обязан быть целым или конечной
   * десятичной дробью; это проверяет автотест. Число — в условии
   * стоит «результат округлите до …», и бесконечная дробь допустима.
   *
   * Метод, а не поле: у одного прототипа задачника соседние варианты
   * отличаются как раз округлением («в сумме выпадет 7 очков» просят
   * до тысячных, а «4 очка» — до сотых).
   */
  okruglenie(p: Params): 2 | 3 | null;
  /** Условие варианта: формулировка задачника, числа — из параметров. */
  uslovie(p: Params): string;
  /** Ограничения на числа: автотест проверяет их до всего прочего. */
  dopustimo(p: Params): boolean;
  /** Ответ по формуле прототипа. */
  otvet(p: Params): number;
  /** Ответ независимо: перебором пространства исходов. */
  perebor(p: Params): number;
  /** Шаги разбора; значение последнего шага равно ответу. */
  shagi(p: Params): Step[];
  varianty: readonly Variant[];
  /** Метод и рисунок. У задания №4 обязательна — см. checkModel. */
  metodika?: Metodika;
}

/* ── Чтение параметров ───────────────────────────────────────────── */

export function num(p: Params, key: string): number {
  const value = p[key];
  if (typeof value !== 'number') {
    throw new Error(`Параметр ${key} — не число`);
  }
  return value;
}

export function text(p: Params, key: string): string {
  const value = p[key];
  if (typeof value !== 'string') {
    throw new Error(`Параметр ${key} — не строка`);
  }
  return value;
}

/* ── Числа в условии и в ответе ──────────────────────────────────── */

/**
 * Запятая вместо точки: в условии и в ответе десятичная дробь
 * записывается по-русски. Число приводится к виду без хвостовых
 * нулей — «0,2», а не «0,20».
 */
export function dec(value: number): string {
  return String(Math.round(value * 1e9) / 1e9).replace('.', ',');
}

/** Округление до двух или трёх знаков, как просит условие. */
export function round(value: number, digits: 2 | 3): number {
  const factor = digits === 2 ? 100 : 1000;
  return Math.round(value * factor + Number.EPSILON * factor) / factor;
}

/**
 * Конечная ли десятичная дробь. Ответ ЕГЭ пишется в клетки, поэтому
 * 1/3 в банк идти не может — либо другие числа, либо в условии стоит
 * «округлите до сотых».
 */
export function konechnaya(value: number): boolean {
  if (!Number.isFinite(value)) {
    return false;
  }
  const rounded = Math.round(value * 1e9) / 1e9;
  /* Девять знаков после запятой — предел, с которым работает
     отпечаток ответа. Дробь длиннее в клетки всё равно не влезет. */
  return Math.abs(value - rounded) < 1e-12 && /^-?\d+(\.\d{1,4})?$/.test(String(rounded));
}

/* ── Подготовительные задачи ─────────────────────────────────────── */

/**
 * Задача из авторского конспекта.
 *
 * В отличие от прототипа это не шаблон, а одна конкретная задача:
 * условие написано автором и числа в нём не меняются. Поэтому здесь
 * нет ни параметров, ни ограничений — зато есть два независимых
 * счёта ответа, как и в банке: `otvet` и `proverka` приходят к
 * одному числу разными путями (через противоположное событие или
 * прямым перебором исходов), и расхождение роняет сборку.
 */
export interface PrepZadacha {
  /** Идентификатор: он же ключ прогресса. */
  id: string;
  /** Номер задачи в конспекте — по нему автор её и находит. */
  nomer: number;
  /** Условие дословно из конспекта. */
  uslovie: string;
  /** Ответ основным рассуждением. */
  otvet: number;
  /** Тот же ответ другим путём. */
  proverka: number;
  /** Округление, если условие конспекта его просит. */
  okruglenie?: 2 | 3;
  /**
   * Чертёж задачи готовой разметкой SVG. Есть только у тех задач,
   * где без картинки условие не читается — в подготовке №5 такая
   * одна, про паука в лабиринте.
   */
  risunok?: string;
  /** Шаги разбора; значение последнего равно ответу. */
  shagi: Step[];
  /** Метод и рисунок. У задания №4 обязательна — см. checkModel. */
  metodika?: Metodika;
  /**
   * Параметрический прототип этой задачи, если он есть: задача
   * конспекта — его вариант 1, остальные варианты собрал генератор.
   */
  prototip?: Prototype;
}

/** Блок подготовительных задач — заголовок из конспекта. */
export interface PrepBlok {
  id: string;
  /** Заголовок блока дословно из конспекта. */
  nazvanie: string;
  /** Одна строка о том, что отрабатывает блок. */
  tip: string;
  zadachi: readonly PrepZadacha[];
}
