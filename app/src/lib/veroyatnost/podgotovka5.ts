/* ── Блоки ────────────────────────────────────────────────────────────
   Блок — метод из «Ключевых методов решения» (metody5.ts), и задача
   лежит в блоке своего метода: метод узнаётся по главному признаку
   условия и по решающему шагу решения. Порядок блоков — порядок
   методов. У задач конспекта номер и идентификатор прежние, меняется
   только блок; прогресс хранится по идентификатору задачи
   (prepProgress.ts), поэтому решённая задача остаётся решённой в
   новом блоке. Два блока собирают несколько методов: «Сумма и
   произведение вероятностей» — методы 1–3, «Вероятности сложных
   событий» — задачи методов без своего блока (5, 10) и подсчёт
   исходов. В каждом блоке ровно десять задач, от простой к сложной;
   проверка — check-veroyatnost.mjs и check-opornye-5.mjs. */

