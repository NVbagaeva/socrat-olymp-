/** Задачи блока по идентификаторам, в заданном порядке. */
function zadachiBloka(ids: readonly string[]): readonly PrepZadacha[] {
  return ids.map((id) => {
    const zadacha = VSE_ZADACHI.get(id);
    if (zadacha === undefined) {
      throw new Error(`Опорные задачи №5: нет задачи ${id}`);
    }
    return zadacha;
  });
}

