/* ── Перечисления для второй проверки ────────────────────────────── */

function tochnee(value: number): number {
  return Math.round(value * 1e9) / 1e9;
}

/** Обход всех 2ⁿ исходов независимых испытаний с вероятностью p. */
function derevo(n: number, p: number, podhodit: (uspehi: readonly boolean[]) => boolean): number {
  let itog = 0;
  for (let mask = 0; mask < 2 ** n; mask += 1) {
    const uspehi: boolean[] = [];
    let veroyatnost = 1;
    for (let bit = 0; bit < n; bit += 1) {
      const uspeh = (mask >> bit) % 2 === 1;
      uspehi.push(uspeh);
      veroyatnost *= uspeh ? p : 1 - p;
    }
    if (podhodit(uspehi)) {
      itog += veroyatnost;
    }
  }
  return tochnee(itog);
}

/** Обход исходов с разными вероятностями по каждому испытанию. */
function derevoRaznyh(
  p: readonly number[],
  podhodit: (uspehi: readonly boolean[]) => boolean,
): number {
  let itog = 0;
  for (let mask = 0; mask < 2 ** p.length; mask += 1) {
    const uspehi: boolean[] = [];
    let veroyatnost = 1;
    for (let bit = 0; bit < p.length; bit += 1) {
      const uspeh = (mask >> bit) % 2 === 1;
      uspehi.push(uspeh);
      veroyatnost *= uspeh ? (p[bit] as number) : 1 - (p[bit] as number);
    }
    if (podhodit(uspehi)) {
      itog += veroyatnost;
    }
  }
  return tochnee(itog);
}

/** Выбор двух предметов без возвращения: доля подходящих пар. */
function parBezVozvrata(gruppy: readonly number[], a: number, b: number): number {
  const vsego = gruppy.reduce((s, x) => s + x, 0);
  /* Нумеруем предметы подряд: сначала группа 0, потом группа 1 и так
     далее. Предмет знает свою группу — этого хватит для перебора. */
  const gruppaPredmeta = (i: number): number => {
    let ostalos = i;
    for (let g = 0; g < gruppy.length; g += 1) {
      ostalos -= gruppy[g] as number;
      if (ostalos < 0) {
        return g;
      }
    }
    return -1;
  };
  let ok = 0;
  let par = 0;
  for (let i = 0; i < vsego; i += 1) {
    for (let j = 0; j < vsego; j += 1) {
      if (i === j) {
        continue;
      }
      par += 1;
      const gi = gruppaPredmeta(i);
      const gj = gruppaPredmeta(j);
      if ((gi === a && gj === b) || (gi === b && gj === a)) {
        ok += 1;
      }
    }
  }
  return ok / par;
}

/** Все подмножества размера k из n — для схем «переложил k монет». */
function podmnozhestva(n: number, k: number): number[][] {
  if (k === 0) {
    return [[]];
  }
  if (n < k) {
    return [];
  }
  const bez = podmnozhestva(n - 1, k);
  const s = podmnozhestva(n - 1, k - 1).map((nabor) => [...nabor, n - 1]);
  return [...bez, ...s];
}

