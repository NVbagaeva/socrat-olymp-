/**
 * Подсказки-вопросы к опорным задачам №5.
 *
 * У этих задач нет прототипа с параметрами: условие, шаги и ответ
 * записаны как есть (podgotovka5.ts). Поэтому и подсказка у каждой
 * своя, со своими числами. Чтобы не повторять одно и то же семьдесят
 * раз, здесь — сборщики по методам блоков (противоположное событие,
 * сумма несовместных, вложенные события, совместные, независимые,
 * «хотя бы один», выбор без возвращения, дерево) и таблица «задача →
 * подсказка». Нестандартные задачи расписаны вручную.
 *
 * Правила те же, что у прототипов: подсказка не называет ответ,
 * последний шаг — как записать ответ. Автотест (selftest.ts, checkPrep)
 * проверяет каждую подсказку и что она есть у всех задач.
 */

import { tex } from './bank5/obshchee';
import { vopros, zapisShag } from './podskazka';
import type { HintStep, PrepZadacha } from './types';

/** Число в формуле: 0,45 → «0{,}45». */
const t = (x: number): string => tex(x);

/** Последний шаг: как записать ответ. */
const zapis = (znakov: 2 | 3 | null = null): HintStep => zapisShag('десятичная', znakov);

/** Произведение и сумма множителей строкой TeX. */
const proizv = (m: readonly string[]): string => m.join(' \\cdot ');
const summa = (m: readonly string[]): string => m.join(' + ');

/* ── Сборщики по методам ─────────────────────────────────────────── */

/** Противоположное событие: ответ 1 − p. */
function protiv(dano: string, ischem: string, p: number): HintStep[] {
  return [
    vopros(
      `Как связаны события «${dano}» и «${ischem}»?`,
      'Противоположны: всегда случается ровно одно из них',
      ['Несовместны, но бывает и третий случай', 'Независимы: одно не влияет на другое'],
    ),
    vopros('Какое выражение даёт ответ?', `$1 - ${t(p)}$`, [
      `$${t(p)}$`,
      `$${t(p)} \\cdot ${t(p)}$`,
    ]),
    zapis(),
  ];
}

/** Сумма несовместных событий. */
function nesovm(pp: readonly number[]): HintStep[] {
  const m = pp.map(t);
  return [
    vopros('Могут ли эти события случиться одновременно?', 'Нет — события несовместны', [
      'Да — их общую часть нужно вычесть',
    ]),
    vopros('Нужно «одно или другое». Что делать с вероятностями несовместных событий?', 'Сложить', [
      'Перемножить',
      'Взять наибольшую',
    ]),
    vopros('Какое выражение даёт ответ?', `$${summa(m)}$`, [
      `$${proizv(m)}$`,
      `$1 - ${m.join(' - ')}$`,
    ]),
    zapis(),
  ];
}

/** Вложенные события: «больше года, но меньше двух» = p₁ − p₂. */
function vlozh(shire: string, uzhe: string, p1: number, p2: number): HintStep[] {
  return [
    vopros(
      `Как связаны события «${shire}» и «${uzhe}»?`,
      'Второе — часть первого: оно лежит внутри него',
      ['Они несовместны', 'Они противоположны'],
      'Искомое — то, что входит в первое, но не во второе.',
    ),
    vopros('Какое выражение даёт ответ?', `$${t(p1)} - ${t(p2)}$`, [
      `$${t(p1)} + ${t(p2)}$`,
      `$1 - ${t(p2)}$`,
    ]),
    zapis(),
  ];
}

/** Три случая на прямой, даны два крайних: 1 − a − b. */
function kraya(seredina: string, a: number, b: number): HintStep[] {
  return [
    vopros(
      `Как получить вероятность «${seredina}»?`,
      'Из единицы убрать оба крайних случая',
      ['Сложить вероятности крайних случаев', 'Перемножить вероятности крайних случаев'],
      'Три случая на прямой не пересекаются и вместе покрывают всё.',
    ),
    vopros('Какое выражение даёт ответ?', `$1 - ${t(a)} - ${t(b)}$`, [
      `$${t(a)} + ${t(b)}$`,
      `$1 - ${t(a)}$`,
    ]),
    zapis(),
  ];
}

/** Совместные события: P(A ∪ B) = P(A) + P(B) − P(AB). */
function sovmIli(a: number, b: number, ab: number): HintStep[] {
  return [
    vopros('Могут ли события случиться одновременно?', 'Да — дана вероятность, что случатся оба', [
      'Нет — они несовместны',
    ]),
    vopros(
      'Как найти вероятность «одно или другое» для совместных событий?',
      '$P(A) + P(B) - P(AB)$',
      ['$P(A) + P(B)$', '$P(A) \\cdot P(B)$'],
      'Иначе общая часть посчитается дважды.',
    ),
    vopros('Какое выражение даёт ответ?', `$${t(a)} + ${t(b)} - ${t(ab)}$`, [
      `$${t(a)} + ${t(b)}$`,
      `$${t(a)} \\cdot ${t(b)}$`,
    ]),
    zapis(),
  ];
}

/** «Ни в одном» через «хотя бы в одном» совместных событий. */
function sovmNiVOdnom(chto: string, a: number, b: number, ab: number): HintStep[] {
  const hotyaBy = `${chto} хотя бы в одном`;
  return [
    vopros(
      'Какое событие противоположно искомому?',
      `«${hotyaBy}»`,
      [`«${chto} в обоих»`, `«${chto} только в первом»`],
      'Его вероятность найти проще.',
    ),
    vopros(
      `Какова вероятность «${hotyaBy}»?`,
      `$${t(a)} + ${t(b)} - ${t(ab)}$`,
      [`$${t(a)} + ${t(b)}$`, `$${t(a)} \\cdot ${t(b)}$`],
      'События совместны: общую часть вычитаем, чтобы не посчитать её дважды.',
    ),
    vopros('Какое выражение даёт ответ?', `$1 - (${t(a)} + ${t(b)} - ${t(ab)})$`, [
      `$1 - (${t(a)} + ${t(b)})$`,
      `$1 - ${t(ab)}$`,
    ]),
    zapis(),
  ];
}

/** «Больше a, но меньше b» по двум совместным событиям: убираем крайние. */
function sovmMezhdu(pMenshe: number, pBolshe: number): HintStep[] {
  return [
    vopros(
      'Что убрать из всех случаев, чтобы осталось искомое?',
      'Слишком малые и слишком большие значения',
      ['Только слишком малые', 'Случаи, которые попали в оба данных события'],
      'Данные события пересекаются: их общая часть и есть искомое.',
    ),
    vopros(
      'Каковы вероятности крайних случаев?',
      `$1 - ${t(pMenshe)}$ и $1 - ${t(pBolshe)}$`,
      [`$${t(pMenshe)}$ и $${t(pBolshe)}$`, `$1 - ${t(pMenshe)} - ${t(pBolshe)}$`],
      'Каждый крайний случай противоположен одному из данных событий.',
    ),
    vopros('Какое выражение даёт ответ?', `$1 - (1 - ${t(pMenshe)}) - (1 - ${t(pBolshe)})$`, [
      `$${t(pMenshe)} \\cdot ${t(pBolshe)}$`,
      `$1 - ${t(pMenshe)} - ${t(pBolshe)}$`,
    ]),
    zapis(),
  ];
}

/** Независимые события: перемножаем. */
function nezav(chto: string, mnozh: readonly string[], pered?: HintStep): HintStep[] {
  return [
    vopros(`Влияют ли ${chto} друг на друга?`, 'Нет — события независимы', [
      'Да — нужно знать, как они связаны',
    ]),
    ...(pered === undefined ? [] : [pered]),
    vopros('Нужно, чтобы всё случилось сразу. Что делать с вероятностями?', 'Перемножить', [
      'Сложить',
      'Взять наименьшую',
    ]),
    vopros('Какое выражение даёт ответ?', `$${proizv(mnozh)}$`, [
      `$${summa(mnozh)}$`,
      `$1 - ${proizv(mnozh)}$`,
    ]),
    zapis(),
  ];
}

/** «Хотя бы один» через «ни одного». */
function hotya(
  protivopolozhnoe: string,
  nevernye: readonly string[],
  mnozh: readonly string[],
  pered?: HintStep,
): HintStep[] {
  return [
    vopros(
      'Какое событие противоположно искомому?',
      protivopolozhnoe,
      nevernye,
      'Его вероятность найти проще: это один путь по дереву.',
    ),
    ...(pered === undefined ? [] : [pered]),
    vopros(
      'Какова вероятность противоположного события?',
      `$${proizv(mnozh)}$`,
      [`$${summa(mnozh)}$`, `$1 - ${proizv(mnozh)}$`],
      'События независимы — перемножаем.',
    ),
    vopros('Какое выражение даёт ответ?', `$1 - ${proizv(mnozh)}$`, [
      `$${proizv(mnozh)}$`,
      `$1 - (${summa(mnozh)})$`,
    ]),
    zapis(),
  ];
}

/** Вероятность «не случилось» у каждого: шаг перед перемножением. */
function nazad(pp: readonly number[], kto: string): HintStep {
  const verno = pp.map((p) => `$1 - ${t(p)}$`).join(', ');
  const neverno = pp.map((p) => `$${t(p)}$`).join(', ');
  const vdvoe = pp.map((p) => `$${t(p)} \\cdot ${t(p)}$`).join(', ');
  return vopros(
    `С какой вероятностью ${kto}?`,
    verno,
    [neverno, vdvoe],
    'Противоположное событие: из единицы вычитаем.',
  );
}

/** Два предмета без возвращения, разных видов: 2ab / N(N − 1). */
function bezVozvr(N: number, a: number, b: number, A: string, B: string): HintStep[] {
  return [
    vopros(
      'Сколько всего упорядоченных пар — первый, потом второй?',
      `$${N} \\cdot ${N - 1}$`,
      [`$${N} \\cdot ${N}$`, `$${N} + ${N - 1}$`],
      'Второй берут из оставшихся — их на один меньше.',
    ),
    vopros(
      'Сколько подходящих упорядоченных пар?',
      `$2 \\cdot ${a} \\cdot ${b}$`,
      [`$${a} \\cdot ${b}$`, `$${a} + ${b}$`],
      `Подходят два порядка: «${A}, потом ${B}» и наоборот.`,
    ),
    vopros(
      'Какое выражение даёт ответ?',
      `$\\dfrac{2 \\cdot ${a} \\cdot ${b}}{${N} \\cdot ${N - 1}}$`,
      [
        `$\\dfrac{${a} \\cdot ${b}}{${N} \\cdot ${N - 1}}$`,
        `$\\dfrac{2 \\cdot ${a} \\cdot ${b}}{${N} \\cdot ${N}}$`,
      ],
    ),
    zapis(),
  ];
}

interface Put {
  nazv: string;
  p1: string;
  p2: string;
}

/** Дерево: несколько путей, вдоль пути умножаем, пути складываем. */
function derevo(puti: readonly Put[]): HintStep[] {
  const chislo = ['Один', 'Два', 'Три', 'Четыре'][puti.length - 1] ?? String(puti.length);
  const drugoe = puti.length === 2 ? 'Три' : 'Два';
  return [
    vopros(
      'Сколько путей по дереву ведут к нужному событию?',
      `${chislo}: ${puti.map((p) => p.nazv).join('; ')}`,
      ['Один — самый вероятный', `${drugoe} — по числу вариантов в условии`],
    ),
    vopros('Как найти вероятность одного пути?', 'Перемножить вероятности вдоль пути', [
      'Сложить вероятности вдоль пути',
      'Взять вероятность последней ветки',
    ]),
    vopros(
      'Какое выражение даёт ответ?',
      `$${puti.map((p) => `${p.p1} \\cdot ${p.p2}`).join(' + ')}$`,
      [
        `$${puti.map((p) => `${p.p1} + ${p.p2}`).join(' + ')}$`,
        `$${puti[0]?.p1 ?? ''} \\cdot ${puti[0]?.p2 ?? ''}$`,
      ],
      'Пути несовместны — их вероятности складываются.',
    ),
    zapis(),
  ];
}

