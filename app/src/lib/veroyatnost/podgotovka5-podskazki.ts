/**
 * Подсказка опорной задачи: у задачи с прототипом — от прототипа на
 * числах её варианта, у задачи №5 без прототипа — из таблицы выше.
 * Этой же функцией пользуются пул (pool.ts) и автотест (selftest.ts):
 * проверяется ровно то, что увидит ученик.
 */
export function podskazkaOpornoy(zadacha: PrepZadacha): HintStep[] | undefined {
  const prototip = zadacha.prototip;
  if (prototip?.podskazka !== undefined) {
    const params = prototip.varianty.find((v) => v.n === (zadacha.variant ?? 1))?.params;
    return params === undefined ? undefined : prototip.podskazka(params);
  }
  return PODSKAZKI_5[zadacha.id];
}
