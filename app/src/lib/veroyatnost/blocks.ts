/**
 * Блоки банков заданий №4 и №5.
 *
 * Блок — это метод: у №4 пять методов списка А и два раздела списка Б
 * (metody4.ts), у №5 десять методов автора (metody5.ts). Второго
 * списка блоков в проекте нет — банк, тренажёр и вкладка методов
 * называют одно и то же одинаково.
 *
 * Блок — это ещё и порядок: прототипы в тренажёре и в списке идут
 * в том же порядке, что и здесь.
 */

import { OPORNYE_4 } from './metody4';
import { METODY_5 } from './metody5';

export interface Blok {
  /** Идентификатор: он же значение фильтра. */
  id: string;
  /** Название на кнопке фильтра. */
  nazvanie: string;
  /** Короткая форма для узкой ленты чипов. */
  korotko: string;
}

/**
 * Блоки задания №4 — семь разделов списка Б: пять методов списка А
 * плюс геометрическое и статистическое определения. Задачи 1–102
 * задачника разложены по ним диапазонами номеров.
 */
export const BLOKI_4: readonly Blok[] = OPORNYE_4.map((m) => ({
  id: m.id,
  nazvanie: m.nazvanie,
  korotko: m.nazvanie,
}));

/**
 * Блоки задания №5 — десять методов, утверждённых автором
 * (metody5.ts): блок банка и метод здесь одно и то же. Порядок —
 * порядок методов, задачи 1–58 задачника Е. А. Ширяевой разложены по
 * ним диапазонами номеров.
 *
 * В самом задачнике подзаголовков нет: задачи идут подряд. Деление —
 * автора, по способу решения.
 */
export const BLOKI_5: readonly Blok[] = METODY_5.map((m) => ({
  id: m.id,
  nazvanie: m.nazvanie,
  korotko: m.nazvanie,
}));
