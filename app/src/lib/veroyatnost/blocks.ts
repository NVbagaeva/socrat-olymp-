/**
 * Блоки задачника: по ним фильтрует тренажёр.
 *
 * Названия блоков задания №4 взяты из самого задачника
 * Е. А. Ширяевой: «Блок 1. ФИПИ» делится там на два подраздела,
 * и чипы тренажёра повторяют эти два названия слово в слово.
 *
 * Блок — это ещё и порядок: прототипы в тренажёре и в списке идут
 * в том же порядке, что и здесь.
 */

export interface Blok {
  /** Идентификатор: он же значение фильтра. */
  id: string;
  /** Название на кнопке фильтра. */
  nazvanie: string;
  /** Короткая форма для узкой ленты чипов. */
  korotko: string;
}

