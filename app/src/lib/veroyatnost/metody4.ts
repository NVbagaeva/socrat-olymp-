import type { Metod } from './tipologiya';

/** Метод списка А или раздел списка Б: карточка плюс пометки для подсказок. */
export interface Metod4 extends Metod {
  /** Ключевая идея — заметка автора для будущих подсказок. На экран не выводится. */
  ideya?: string;
  flagi?: {
    /**
     * Внутри метода задачи, где нужную группу сначала находят
     * вычитанием («остальные — жёлтого цвета», «оставшихся перевели в
     * запасную аудиторию»).
     */
    vychitanie?: readonly [number, number][];
    /** Исходов бесконечно много: формула m/n напрямую не работает, считаем долю. */
    dolya?: true;
    /** Исходы не равновозможные: считаем делением по частоте наблюдений. */
    chastota?: true;
  };
}

