/**
 * Состав методов задания №5: десять методов, утверждённых автором.
 *
 * Метод здесь — одновременно и блок банка (поле `blok` прототипа), и
 * навык тренажёра, и карточка вкладки «Ключевые методы решения». Один
 * список на всё: порядок — порядок автора, номера — номера карточек.
 *
 * Тексты названий, подписей и формул перенесены дословно из задания
 * автора. Правило именования: название описывает то, что ученик
 * видит в условии, а не то, что делает решающий. Обозначения общие с
 * разделом №4: P(A) = m/n, m — благоприятные, n — общее число исходов.
 * Формула есть только у тех методов, где автор её дал; записана TeX
 * и набирается KaTeX на сборке.
 *
 * Формулы Бернулли в списке нет намеренно: в задачнике нет ни одной
 * задачи вида C_n^k · p^k · q^(n−k). Задачи 55–58 («сколько патронов
 * нужно стрелку») решаются через противоположное событие и подбор n.
 */

/** Диапазон номеров задачника: от и до включительно. */
export type Diapazon = readonly [number, number];

/** Подтип по сюжету — диапазон номеров задачника, название и заметка для подсказки. */
export interface Podtip5 {
  zadachi: Diapazon;
  nazvanie: string;
  /** Ключевая идея подтипа — заметка автора для будущих подсказок. */
  ideya?: string;
}

export interface Metod5 {
  /** Идентификатор: он же `blok` прототипа и навык тренажёра. */
  id: string;
  /** Номер карточки, 1–10. */
  nomer: number;
  /** Название метода — как на карточке и на кнопке тренажёра. */
  nazvanie: string;
  /** Фраза о сути метода — под названием. */
  opisanie: string;
  /** Формула метода одной строкой, в TeX. Есть не у всех. */
  formula?: string;
  /**
   * Диапазоны номеров задачника, отнесённых к методу. Обычно один;
   * у умножения независимых событий два — 29–36 и 45–48.
   */
  zadachnik: readonly Diapazon[];
  /** Подтипы по сюжету, если автор их выделил. */
  podtipy?: readonly Podtip5[];
  /**
   * Ключевая идея решения — заметка автора для будущих подсказок.
   * На экран пока не выводится.
   */
  ideya: string;
  /** Пометки автора: что обязательно в подсказке и в проверке ответа. */
  flagi?: {
    /** Чертёж числовой прямой обязателен в подсказке. */
    chertezh?: true;
    /** Дерево вероятностей обязательно в подсказке. */
    derevo?: true;
    /** Ответ — натуральное число, а не десятичная дробь. */
    otvetNaturalnoe?: true;
  };
}

