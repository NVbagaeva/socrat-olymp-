export function metod5PoId(id: string): Metod5 {
  const est = METODY_5.find((m) => m.id === id);
  if (est === undefined) {
    throw new Error(`Неизвестный метод задания №5: ${id}`);
  }
  return est;
}

/** Метод, к которому автор отнёс задачу задачника с этим номером. */
export function metod5Zadachi(nomer: number): Metod5 | undefined {
  return METODY_5.find((m) => nomer >= m.zadachnik[0] && nomer <= m.zadachnik[1]);
}
