const OPISANIYA: readonly OpisanieNabora[] = [DZ9_NOVOE, DZ9];

function sobratNabor(o: OpisanieNabora): Nabor5 {
  return {
    id: o.id,
    nazvanie: o.nazvanie,
    opisanie: o.opisanie,
    svyazi: Object.fromEntries(
      o.zadachi.flatMap((z, i) => (z.opiraetsyaNa === undefined ? [] : [[i + 1, z.opiraetsyaNa]])),
    ),
    zadachi: o.zadachi.map((z, i) => {
      const sh = najtiShablon(z.shablon);
      const syuzhet = sh?.syuzhety.find((s) => s.id === z.syuzhet);
      if (sh === undefined || syuzhet === undefined) {
        throw new Error(`${o.id} №${i + 1}: нет шаблона или сюжета`);
      }
      const zad = sobrat(
        sh,
        z.p,
        syuzhet,
        rng(`${o.id}:${i + 1}`),
        `${o.id}-${i + 1}`,
        z.uslovie,
        z.uslovie === undefined ? undefined : 0,
      );
      if (zad === null) {
        throw new Error(`${o.id} №${i + 1}: числа не проходят правила ответа`);
      }
      return zad;
    }),
  };
}

let kesh: Nabor5[] | null = null;

/** Все готовые наборы: собираются один раз. */
export function nabory5(): Nabor5[] {
  kesh ??= OPISANIYA.map(sobratNabor);
  return kesh;
}

export function najtiNabor(id: string): Nabor5 | undefined {
  return nabory5().find((n) => n.id === id);
}
