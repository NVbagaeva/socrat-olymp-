interface P12 {
  /** Граней у кости: 6 — обычная, 4 — тетраэдр. */
  m: 4 | 6;
  /** Сумма очков. */
  S: number;
  /** Вопрос: «был сделан ровно k бросков». */
  k: number;
}

/** Все упорядоченные разбиения S на слагаемые 1…m. */
function razbieniya(S: number, m: number): number[][] {
  if (S === 0) return [[]];
  const out: number[][] = [];
  for (let x = 1; x <= Math.min(m, S); x += 1) {
    for (const rest of razbieniya(S - x, m)) out.push([x, ...rest]);
  }
  return out;
}

function kost(p: P12) {
  const vse = razbieniya(p.S, p.m);
  const po = new Map<number, number>();
  vse.forEach((r) => po.set(r.length, (po.get(r.length) ?? 0) + 1));
  const ver = (k: number) => d(po.get(k) ?? 0).times(step(d(1, p.m), k));
  const summaVsego = summa([...po.keys()].map(ver));
  return { vse, po, ver, summaVsego };
}

