/* ══════════════════════════════════════════════════════════
   3. Схема Бернулли: во сколько раз одна вероятность больше другой
   ══════════════════════════════════════════════════════════ */

interface P3 {
  n: number;
  /** Вероятности успеха в десятых: 7 → 0,7. */
  pa: number;
  ka: number;
  pb: number;
  kb: number;
}

function bernulli(n: number, k: number, p: Drob): Drob {
  return d(cnk(n, k))
    .times(step(p, k))
    .times(step(p.ne(), n - k));
}

function bernulliShag(imya: string, n: number, k: number, p: Drob): Shag5 {
  const q = p.ne();
  const x = bernulli(n, k, p);
  return {
    text: `${imya}: $p = ${t(p)}$, $q = ${t(q)}$.`,
    tex: `P_{${n}}(${k}) = C_{${n}}^{${k}} \\cdot ${t(p)}^{${k}} \\cdot ${t(q)}^{${n - k}} = ${cnk(n, k)} \\cdot ${t(step(p, k))} \\cdot ${t(step(q, n - k))} = ${t(x)}`,
  };
}

