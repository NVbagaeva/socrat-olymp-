/* ── Запись чисел ─────────────────────────────────────────── */

/** «0,7» — в тексте условия. */
const v = (x: Drob) => dec(x);
/** «0{,}7» — в формуле. */
const t = (x: Drob) => texChislo(x);
/** «15%» — проценты в тексте. */
const pc = (n: number) => `${n}%`;
/** Ответ части в формуле: «0,87» → «0{,}87». */
const to = (s: string) => s.replace(',', '{,}');
/** «≈» или «=»: ответ записан точно или округлён. */
const priblizh = (x: Drob, s: string) => (znakov(x) !== null && dec(x) === s ? '=' : '\\approx');

/** «= 216/343 ≈ 0,63» или «= 0,512»: точное значение и записанный ответ. */
function itog(x: Drob, s: string): string {
  const tochno = znakov(x) !== null && dec(x) === s;
  return tochno ? `= ${to(s)}` : `= ${texChislo(x)} \\approx ${to(s)}`;
}

/** Случайный процент из сетки: от lo до hi с шагом stepN. */
function procent(r: Rng, lo: number, hi: number, stepN: number): number {
  return lo + stepN * r.int(0, Math.floor((hi - lo) / stepN));
}

