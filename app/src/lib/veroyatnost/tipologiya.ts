/**
 * Общее для типологий методов заданий №4 и №5: карточка метода на
 * вкладке «Ключевые методы решения» и привязка к номерам задачника.
 *
 * У каждого задания свой список методов (metody4.ts, metody5.ts) —
 * это разные карты разных банков, и один конфиг на двоих их бы только
 * спутал. Здесь лежит лишь то, что у карточек общее: название,
 * подпись, формула и диапазоны задачника, по которым считается
 * счётчик «задач в банке».
 */

/** Диапазон номеров задачника: от и до включительно. */
export type Diapazon = readonly [number, number];

/** Подтип по сюжету — диапазон номеров задачника, название и заметка для подсказки. */
export interface Podtip {
  zadachi: Diapazon;
  nazvanie: string;
  /** Ключевая идея подтипа — заметка автора для будущих подсказок. */
  ideya?: string;
}

/** Карточка метода: то, что видно на вкладке и в модалке. */
export interface Metod {
  /** Идентификатор: он же блок банка и навык тренажёра. */
  id: string;
  /** Номер карточки. */
  nomer: number;
  /** Название метода — как на карточке и на кнопке тренажёра. */
  nazvanie: string;
  /** Фраза о сути метода — под названием. */
  opisanie: string;
  /** Формула метода одной строкой, в TeX. Есть не у всех. */
  formula?: string;
  /**
   * Диапазоны номеров задачника, отнесённых к методу. Обычно один;
   * бывает несколько, когда задачи метода в задачнике не подряд.
   */
  zadachnik: readonly Diapazon[];
  /** Подтипы по сюжету, если автор их выделил. */
  podtipy?: readonly Podtip[];
}

/** Сколько задач задачника отнесено к методу: длина всех его диапазонов. */
export function zadachVBanke(metod: Pick<Metod, 'zadachnik'>): number {
  return metod.zadachnik.reduce((sum, [ot, do_]) => sum + (do_ - ot + 1), 0);
}

/** Попадает ли номер задачника в диапазоны метода. */
export function vDiapazonah(metod: Pick<Metod, 'zadachnik'>, nomer: number): boolean {
  return metod.zadachnik.some(([ot, do_]) => nomer >= ot && nomer <= do_);
}
