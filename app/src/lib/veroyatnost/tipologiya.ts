/**
 * Общее для типологий методов заданий №4 и №5: карточка метода на
 * вкладке «Ключевые методы решения» и привязка к номерам сборника.
 *
 * У каждого задания свой список методов (metody4.ts, metody5.ts) —
 * это разные карты разных банков, и один конфиг на двоих их бы только
 * спутал. Здесь лежит лишь то, что у карточек общее: название,
 * подпись, формула и служебные диапазоны номеров сборника. По ним
 * автотест проверяет раскладку банка; на экран номера не выводятся,
 * а счётчик «задач в банке» считается по самому банку сайта.
 */

/** Диапазон номеров сборника: от и до включительно. */
export type Diapazon = readonly [number, number];

/** Подтип по сюжету — диапазон номеров сборника, название и заметка для подсказки. */
export interface Podtip {
  zadachi: Diapazon;
  nazvanie: string;
  /** Ключевая идея подтипа — заметка автора для будущих подсказок. */
  ideya?: string;
}

/** Карточка метода: то, что видно на вкладке и в модалке. */
export interface Metod {
  /** Идентификатор: он же блок банка и навык тренажёра. */
  id: string;
  /** Номер карточки. */
  nomer: number;
  /** Название метода — как на карточке и на кнопке тренажёра. */
  nazvanie: string;
  /** Фраза о сути метода — под названием. */
  opisanie: string;
  /** Формула метода одной строкой, в TeX. Есть не у всех. */
  formula?: string;
  /**
   * Служебные диапазоны номеров сборника, отнесённых к методу. Обычно
   * один; бывает несколько, когда задачи метода в сборнике не подряд.
   */
  sourceRanges: readonly Diapazon[];
  /** Подтипы по сюжету, если автор их выделил. */
  podtipy?: readonly Podtip[];
}

/** Попадает ли номер сборника в диапазоны метода. */
export function vDiapazonah(metod: Pick<Metod, 'sourceRanges'>, nomer: number): boolean {
  return metod.sourceRanges.some(([ot, do_]) => nomer >= ot && nomer <= do_);
}
