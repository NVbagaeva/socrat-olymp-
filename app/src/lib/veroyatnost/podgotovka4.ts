/**
 * Опорные задачи задания №4.
 *
 * Это авторский конспект урока 13–14 сентября, задачи 1–18, разложенные
 * по трём его же заголовкам. Условия перенесены дословно — это
 * проверяется при загрузке bank4/konspekt.ts, где каждая задача стала
 * параметрическим прототипом: вариант 1 — задача конспекта, ещё десять
 * вариантов с другими числами собрал генератор.
 *
 * Здесь задача конспекта получается из варианта 1 своего прототипа:
 * условие, ответ, второй счёт ответа, шаги и рисунок — всё оттуда.
 *
 * Шесть задач конспекта встречаются и в банке прототипов №4. Это не
 * дублирование, а задумка: сначала ученик решает конкретную задачу
 * автора в подготовке, потом получает тот же метод на новых числах в
 * тренажёре.
 *
 * ── Метод каждой задачи ──────────────────────────────────────────
 *
 * У задачи конспекта есть метод из типологии автора (metody4.ts) —
 * тот же, по которому фильтрует тренажёр. Заголовок блока конспекта
 * и метод — разные вещи: блок это порядок урока, метод это способ
 * решения, и внутри одного блока методы бывают разные.
 *
 * Шесть задач-двойников берут метод у своего прототипа задачника.
 * Остальные распределены по правилу автора: признаки проверяются
 * сверху вниз, первый совпавший и даёт метод.
 *
 *  1. бросают игральную кость → Кубики;
 *  2. бросают монету → Монеты;
 *  3. рассадка за столом, жребий, разбиение на группы, соседство
 *     → Круглый стол и жребий;
 *  4. спрашивают, что событие НЕ произойдёт, или решается через
 *     «единица минус» → Противоположные события;
 *  5. исходов бесконечно много: точка на отрезке, дуге, в круге,
 *     на площади; считается доля → Геометрическое определение;
 *  6. вероятность оценивают по наблюдениям и частотам
 *     → Статистическое определение;
 *  7. всё остальное: конечное число равновозможных исходов
 *     → Классическая вероятность.
 *
 * Очередь и порядок (кто выступает после кого, кто летит первым
 * рейсом) признаком 3 не считаются: это классическая вероятность.
 * Так же разложены и задачи задачника — 27–30 и 1–4 в классической.
 */

import { KONSPEKT_4 } from './bank4/konspekt';
import { OPORNYE_4 } from './metody4';
import { type PrepBlok, type PrepZadacha, type Prototype } from './types';

/** Задача конспекта из варианта 1 её прототипа. */
function izPrototipa(P: Prototype, nomer: number): PrepZadacha {
  const pervyy = P.varianty[0];
  if (pervyy === undefined) {
    throw new Error(`У прототипа ${P.id} нет вариантов`);
  }
  const p = pervyy.params;
  const znakov = P.okruglenie(p);
  const metodika = P.metodika;
  return {
    id: P.id,
    nomer,
    uslovie: P.uslovie(p),
    otvet: P.otvet(p),
    proverka: P.perebor(p),
    ...(znakov === null ? {} : { okruglenie: znakov }),
    shagi: P.shagi(p),
    ...(metodika === undefined
      ? {}
      : {
          metodika: {
            metod: metodika.metod,
            methodHints: metodika.methodHints,
            fraza: () => metodika.fraza(p),
            vizual: () => metodika.vizual(p),
          },
        }),
    prototip: P,
  };
}

/**
 * Метод каждой задачи конспекта. Ключ — идентификатор задачи, чтобы
 * список читался рядом с номерами, а не прятался в трёх местах.
 */
const METOD_ZADACHI: Record<string, string> = {
  'k4-01': 'klassicheskaya', // пирожки: выбрать с вареньем
  'k4-02': 'protivopolozhnye', // фильмы: «не будет драмой»
  'k4-03': 'klassicheskaya', // «Мафия»: 2 карты из 10
  'k4-04': 'klassicheskaya', // кот в 10 подъездах
  'k4-05': 'klassicheskaya', // порядок выступлений: очередь не жребий
  'k4-06': 'klassicheskaya', // сад: количества как 8 : 1 : 3
  'k4-07': 'kruglyy-stol', // двойник p4-14: разбивка на игровые пары
  'k4-08': 'klassicheskaya', // двойник p4-01: первый рейс вертолёта
  'k4-09': 'klassicheskaya', // двойник p4-07: чей доклад по счёту
  'k4-10': 'kubiki', // кость дважды: значения совпали
  'k4-11': 'kruglyy-stol', // жребий: трое олигархов из двенадцати
  'k4-12': 'kruglyy-stol', // двойник p4-15: братья в одном автобусе
  'k4-13': 'kruglyy-stol', // двойник p4-15: друзья в одной группе
  'k4-14': 'kruglyy-stol', // круг: двое оказались рядом
  'k4-15': 'kruglyy-stol', // круглый стол на 201 стул
  'k4-16': 'geometricheskoe', // двойник p4-05: где встала стрелка
  'k4-17': 'geometricheskoe', // озеро и домик уточки: доля площади
  'k4-18': 'geometricheskoe', // колечко в саду: доля площади
};

function po(id: string, nomer: number): PrepZadacha {
  const P = KONSPEKT_4.find((k) => k.id === id);
  if (P === undefined) {
    throw new Error(`В конспекте нет прототипа ${id}`);
  }
  const blok = METOD_ZADACHI[id];
  if (blok === undefined) {
    throw new Error(`У задачи конспекта ${id} не назван метод`);
  }
  if (!OPORNYE_4.some((m) => m.id === blok)) {
    throw new Error(`У задачи конспекта ${id} метод «${blok}» не назван в типологии`);
  }
  return { ...izPrototipa(P, nomer), blok };
}

