/** Название в списке задач и вопрос — последняя фраза условия. */
type Tekst = [string, string];

/* ── История: группы и событие ───────────────────────────────────── */

interface Istoriya {
  id: string;
  nazvanie: string;
  uslovie: (p: Params) => string;
  grupy: readonly string[];
  sobytie: readonly [string, string];
  /** Доли групп по порядку; последняя — остаток до единицы. */
  doli: (p: Params) => number[];
  /** Вероятность события в каждой группе. */
  qs: (p: Params) => number[];
  /** Параметры истории — генератор как у исходной задачи. */
  generator: (r: Rng) => Params;
  /** Числа истории допустимы (доли и вероятности внутри (0; 1)). */
  dopustimo: (p: Params) => boolean;
}

function izDvuh(o: Dvuh): Istoriya {
  return {
    id: o.id,
    nazvanie: o.nazvanie,
    uslovie: o.uslovie,
    grupy: o.grupy,
    sobytie: o.sobytie,
    doli: (p) => [num(p, 'a'), tochnee(1 - num(p, 'a'))],
    qs: (p) => [num(p, 'q1'), num(p, 'q2')],
    generator: (r) => ({ a: sluchayno(r, o.a), q1: sluchayno(r, o.q1), q2: sluchayno(r, o.q2) }),
    dopustimo: (p) => {
      const a = num(p, 'a');
      /* Доля и её дополнение равны — кнопки «какая доля» сливаются. */
      return a > 0 && a < 1 && !sovpadaet(a, [tochnee(1 - a)]);
    },
  };
}

function izTri(o: Trigruppy): Istoriya {
  return {
    id: o.id,
    nazvanie: o.nazvanie,
    uslovie: o.uslovie,
    grupy: o.grupy,
    sobytie: o.sobytie,
    doli: (p) => [num(p, 'a'), num(p, 'b'), tochnee(1 - num(p, 'a') - num(p, 'b'))],
    qs: (p) => [num(p, 'q1'), num(p, 'q2'), num(p, 'q3')],
    generator: (r) => ({
      a: sluchayno(r, o.a),
      b: sluchayno(r, o.b),
      q1: sluchayno(r, o.q1),
      q2: sluchayno(r, o.q2),
      q3: sluchayno(r, o.q3),
    }),
    dopustimo: (p) => {
      const a = num(p, 'a');
      const b = num(p, 'b');
      return a > 0 && b > 0 && tochnee(1 - a - b) > 0;
    },
  };
}

/** Последняя фраза условия — вопрос — заменяется новым. */
function sNovymVoprosom(uslovie: string, novyy: string): string {
  const i = uslovie.lastIndexOf('Найдите вероятность');
  if (i < 0) {
    throw new Error(`В условии нет вопроса «Найдите вероятность…»: ${uslovie.slice(0, 60)}`);
  }
  return uslovie.slice(0, i) + novyy;
}

/** Путь по дереву: группа и ветка внутри неё — событие или противоположная. */
interface Put {
  g: number;
  vetka: 's' | 'n';
}

function veroyatnostVetki(qs: readonly number[], put: Put): number {
  const q = qs[put.g] as number;
  return put.vetka === 's' ? q : tochnee(1 - q);
}

/* ── Прототип нового вопроса ─────────────────────────────────────── */

function novyyVopros(ist: Istoriya, vid: 'ne' | 'put', nomer: number, tekst: Tekst): Prototype {
  const [s1, s2] = ist.sobytie;
  const n = ist.grupy.length;
  const posledn = n - 1;
  const puti: Put[] =
    vid === 'ne'
      ? ist.grupy.map((_, g) => ({ g, vetka: 'n' as const }))
      : n === 2
        ? [{ g: 1, vetka: 'n' }]
        : [{ g: 2, vetka: 's' }];
  const gr = (g: number): string => ist.grupy[g] as string;
  const metkaVetki = (put: Put): string => (put.vetka === 's' ? s1 : s2);
  const id = `p5-${nomer}`;
  const osnova = ist.nazvanie.split(':')[0] as string;

  const slagaemye = (p: Params): number[] => {
    const doli = ist.doli(p);
    const qs = ist.qs(p);
    return puti.map((put) => tochnee((doli[put.g] as number) * veroyatnostVetki(qs, put)));
  };
  const otvet = (p: Params): number => tochnee(slagaemye(p).reduce((s, v) => s + v, 0));
  /* Числа, которые ученик видит в подсказке: доли, вероятности и их дополнения. */
  const vidimye = (p: Params): number[] => [
    ...ist.doli(p),
    ...ist.qs(p),
    ...ist.qs(p).map((q) => tochnee(1 - q)),
    ...ist.doli(p).map((d) => tochnee(1 - d)),
  ];
  const proizv = (p: Params, put: Put): string =>
    `${tex(ist.doli(p)[put.g] as number)} \\cdot ${tex(veroyatnostVetki(ist.qs(p), put))}`;

  return prototip({
    id,
    blok: 'polnaya',
    nazvanie: `Рисуем дерево — ${osnova}: ${tekst[0]}`,
    tip: vid === 'ne' ? 'Полная вероятность: противоположные ветки' : 'Один путь по дереву',
    sourceRange: [0, 0],
    format: 'десятичная',
    okruglenie: tochno,
    uslovie: (p) => sNovymVoprosom(ist.uslovie(p), tekst[1]),
    dopustimo: (p) => {
      const qs = ist.qs(p);
      const o = otvet(p);
      return (
        ist.dopustimo(p) &&
        qs.every((q) => q > 0 && q < 1) &&
        konechnaya(o) &&
        !sovpadaet(o, vidimye(p))
      );
    },
    otvet,
    /* Второй путь: 10 000 объектов, штуками по группам. */
    perebor: (p) => {
      const doli = ist.doli(p);
      const qs = ist.qs(p);
      const shtukGrupp: number[] = [];
      let ostalos = BAZA;
      doli.forEach((d, g) => {
        const k = g === posledn ? ostalos : shtuk(d, BAZA);
        shtukGrupp.push(k);
        ostalos -= k;
      });
      const vsego = puti.reduce(
        (s, put) => s + Math.round((shtukGrupp[put.g] as number) * veroyatnostVetki(qs, put)),
        0,
      );
      return tochnee(vsego / BAZA);
    },
    shagi: (p) => {
      const sl = slagaemye(p);
      const o = otvet(p);
      if (puti.length === 1) {
        const put = puti[0] as Put;
        return [
          {
            etap: 'Путь по дереву',
            text: `Нужен один путь — «${gr(put.g)}, ${metkaVetki(put)}»: и группа, и ветка внутри неё.${
              put.vetka === 'n'
                ? ` Вероятность ветки «${s2}» — единица минус вероятность «${s1}».`
                : ''
            }`,
          },
          {
            etap: 'Ответ',
            text: 'Вдоль пути вероятности перемножаются:',
            formula: `P = ${proizv(p, put)} = ${tex(o)}`,
            value: o,
          },
        ] satisfies Step[];
      }
      return [
        {
          etap: 'Противоположное событие',
          text: `В каждой группе ветка «${s2}» — противоположная к «${s1}»: её вероятность — единица минус вероятность «${s1}».`,
        },
        ...puti.map((put, i): Step => ({
          etap: 'Путь по дереву',
          text: `Путь «${gr(put.g)}, ${s2}»:`,
          formula: `${proizv(p, put)} = ${tex(sl[i] as number)}`,
          value: sl[i] as number,
        })),
        {
          etap: 'Ответ',
          text: 'Пути несовместны, складываем:',
          formula: `P = ${sl.map(tex).join(' + ')} = ${tex(o)}`,
          value: o,
        },
      ];
    },
    podskazka: (p) => {
      const doli = ist.doli(p);
      const qs = ist.qs(p);
      const d = (g: number): number => doli[g] as number;
      const q = (g: number): number => qs[g] as number;
      const zapis = zapisShag('десятичная', null);
      if (vid === 'ne') {
        const verno = puti.map((put) => proizv(p, put)).join(' + ');
        const naoborot = puti.map((put) => `${tex(d(put.g))} \\cdot ${tex(q(put.g))}`).join(' + ');
        return [
          vopros(
            `Какая доля всех случаев приходится на «${gr(posledn)}»?`,
            `$${tex(d(posledn))}$`,
            [
              `$${tex(d(0))}$`,
              `$${tex(q(posledn))}$`,
              `$${tex(tochnee(1 - d(posledn)))}$`,
              `$${tex(tochnee(1 - q(posledn)))}$`,
            ],
            'Доли всех групп в сумме дают единицу.',
          ),
          vopros(
            `Какая вероятность у ветки «${s2}» после «${gr(0)}»?`,
            `$${tex(tochnee(1 - q(0)))}$`,
            [
              `$${tex(q(0))}$`,
              `$${tex(d(0))}$`,
              `$${tex(tochnee(1 - d(0)))}$`,
              `$${tex(q(posledn))}$`,
            ],
            'Ветки из одной точки в сумме дают единицу.',
          ),
          vopros(
            'Какие пути ведут к нужному исходу?',
            `Все пути, которые кончаются веткой «${s2}»`,
            [`Все пути, которые кончаются веткой «${s1}»`, `Только путь «${gr(0)}, ${s2}»`],
            'В каждой группе исход свой путь, и все они подходят.',
          ),
          vopros('Какое выражение даёт ответ?', `$${verno}$`, [
            `$${naoborot}$`,
            `$${proizv(p, puti[0] as Put)}$`,
          ]),
          zapis,
        ];
      }
      const put = puti[0] as Put;
      const vetka = veroyatnostVetki(qs, put);
      const drugayaVetka = put.vetka === 'n' ? q(put.g) : tochnee(1 - q(put.g));
      return [
        vopros(
          `Какая доля всех случаев приходится на «${gr(put.g)}»?`,
          `$${tex(d(put.g))}$`,
          [
            `$${tex(d(0))}$`,
            `$${tex(q(put.g))}$`,
            `$${tex(tochnee(1 - d(put.g)))}$`,
            `$${tex(tochnee(1 - q(put.g)))}$`,
          ],
          'Доли всех групп в сумме дают единицу.',
        ),
        vopros(
          'Сколько путей по дереву подходит?',
          `Один: «${gr(put.g)}, ${metkaVetki(put)}»`,
          [`Все пути с веткой «${metkaVetki(put)}»`, 'Все пути дерева'],
          'Нужна и группа, и исход внутри неё — это один путь.',
        ),
        vopros(
          `Какая вероятность у ветки «${metkaVetki(put)}» после «${gr(put.g)}»?`,
          `$${tex(vetka)}$`,
          [
            `$${tex(drugayaVetka)}$`,
            `$${tex(d(put.g))}$`,
            `$${tex(tochnee(1 - d(put.g)))}$`,
            `$${tex(q(0))}$`,
          ],
          put.vetka === 'n' ? 'Ветки из одной точки в сумме дают единицу.' : undefined,
        ),
        vopros('Какое выражение даёт ответ?', `$${proizv(p, put)}$`, [
          `$${tex(d(put.g))} + ${tex(vetka)}$`,
          `$${tex(d(put.g))} \\cdot ${tex(drugayaVetka)}$`,
        ]),
        zapis,
      ];
    },
    varianty: [],
    generator: ist.generator,
    metodika: {
      metod: 'probability-tree',
      methodHints:
        vid === 'ne'
          ? [
              'спрашивают о противоположном исходе — в каждой группе своя противоположная ветка',
              'несколько путей по дереву: умножаем вдоль каждого и складываем',
            ]
          : [
              'нужна и группа, и исход внутри неё — это один путь по дереву',
              'вдоль пути вероятности перемножаются',
            ],
      fraza: () =>
        vid === 'ne'
          ? 'дерево вероятностей — подходят все пути с противоположной веткой: умножаем вдоль каждого и складываем.'
          : 'дерево вероятностей — подходит один путь: доля группы умножается на вероятность ветки внутри неё.',
      vizual: (p) => {
        const doli = ist.doli(p);
        const qs = ist.qs(p);
        const branches: Vetv[] = [];
        ist.grupy.forEach((g, i) => {
          branches.push({ id: `g${i + 1}`, parent: null, label: g, p: doli[i] as number });
        });
        ist.grupy.forEach((_, i) => {
          const qi = qs[i] as number;
          branches.push({ id: `g${i + 1}s`, parent: `g${i + 1}`, label: s1, p: qi });
          branches.push({ id: `g${i + 1}n`, parent: `g${i + 1}`, label: s2, p: tochnee(1 - qi) });
        });
        return derevo(
          ['группа', 'результат'],
          branches,
          puti.map((put) => `g${put.g + 1}${put.vetka}`),
        );
      },
    },
  });
}

