/**
 * Задание №5: другие вопросы к историям полной вероятности.
 *
 * У каждой из 27 историй «Рисуем дерево» (derevo-novye.ts: 20 с двумя
 * группами и 7 с тремя) прежде был один вопрос — вероятность события.
 * Здесь к той же истории ещё два вопроса, каждый — свой прототип:
 *  - противоположное событие: «собран без ошибки», «конфета годная» —
 *    подходят все пути с противоположной веткой, их складывают;
 *  - один путь: у двух групп — вторая группа и противоположная ветка,
 *    у трёх — третья группа и событие; вдоль пути перемножают.
 * Условие то же, меняется последняя фраза — вопрос. Номера —
 * voprosy-nomera.ts; в банке новые прототипы стоят в конце, номера
 * прежних задач и коды вариантов не сдвигаются.
 *
 * Второй путь счёта — штуками из 10 000 объектов, как у исходных задач.
 */

