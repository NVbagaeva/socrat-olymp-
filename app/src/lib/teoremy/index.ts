export const TEOREMY: Readonly<Record<string, Teorema>> = Object.fromEntries(
  SPISOK.map((t) => [t.id, t]),
);

export function teorema(id: string): Teorema {
  const t = TEOREMY[id];
  if (t === undefined) throw new Error(`нет теоремы ${id}`);
  return t;
}

/** Чертёж теоремы SVG. */
export function chertezhTeoremy(id: string, shirina = 240): string {
  return renderPlan(teorema(id).scena(), {
    rezhim: { rezhim: 'uchitel' },
    shirina,
    vysota: Math.round(shirina * 0.75),
    alt: teorema(id).nazvanie,
  });
}

/** Ссылки {{t:id|текст}} в строке: id по порядку появления. */
export const SSYLKA = /\{\{t:([a-z0-9-]+)\|([^}]*)\}\}/g;

export function ssylkiV(text: string): string[] {
  return [...text.matchAll(SSYLKA)].map((m) => m[1]!);
}
