/**
 * Порядок обхода задач внутри навыка.
 *
 * Вынесено из экрана отдельно, потому что это чистая логика без
 * разметки: её видно целиком и можно прогнать на примерах, не
 * поднимая браузер.
 */

/** Как закончилась работа над задачей. null — ещё не бралась. */
export type TaskStatus = 'right' | 'wrong' | 'skipped' | null;

/**
 * Ближайшая нерешённая задача после текущей, с переходом через конец
 * набора.
 *
 * Порядок решения внутри навыка свободный, поэтому «следующая» —
 * это не «следующая по номеру», а ближайшая из тех, что ещё не
 * сделаны: пропущенную в начале не придётся искать кружками руками.
 * Решены все — null, идти внутри навыка некуда.
 */
export function nextUnsolved(status: readonly TaskStatus[], from: number): number | null {
  const total = status.length;
  for (let step = 1; step <= total; step += 1) {
    const i = (from + step) % total;
    if (status[i] !== 'right') {
      return i;
    }
  }
  return null;
}
