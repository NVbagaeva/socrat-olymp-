import localFont from 'next/font/local';

/**
 * Inter 4 Variable (оси wght и opsz) — шрифт «Стеклянной сцены»: главная
 * и демо /styleguide/steklo. На крупном кегле браузер сам берёт начертание
 * Display (font-optical-sizing: auto). next/font предзагружает файл только
 * на маршрутах, которые этот модуль импортируют.
 *
 * Один файл на латиницу, кириллицу, цифры и знаки (76 КБ). Раньше их
 * было два — кириллица и латиница по 29 и 71 КБ, — и тире жило в
 * латинском: когда тот догружался, заголовок героя перестраивался на
 * строку короче, и лид с кристаллом прыгали на 41px (CLS). Один файл
 * меньше двух, и запасной шрифт с подогнанными метриками у него свой —
 * до загрузки строка стоит почти так же.
 *
 * display: optional, а не swap. Корневой layout предзагружает на каждой
 * странице ещё 300 КБ шрифтов, и на медленной сети этот файл приходит
 * последним — через 3,5 с после начала. При swap запасной шрифт успевал
 * написать заголовок на строку длиннее, и подмена двигала всё под ним
 * (CLS 0,026). С optional страница либо сразу рисуется Inter (обычный
 * случай и любой повторный визит), либо до конца визита остаётся
 * запасным шрифтом — без прыжка; к следующей странице файл уже в кеше.
 *
 * Собран pyftsubset из InterVariable.ttf релиза Inter 4.1
 * (github.com/rsms/inter): Basic Latin и Latin-1, кириллица, общая
 * пунктуация, «№», ₽, ≤ ≥ ≠ ≈, стрелки; возможности ccmp, pnum, tnum,
 * kern, mark, mkmk — как у подмножеств fontsource; без хинтинга.
 * Лицензия — в fonts/LICENSE.
 */
export const interSteklo = localFont({
  src: '../fonts/inter-opsz.woff2',
  weight: '100 900',
  variable: '--font-steklo',
  display: 'optional',
  fallback: ['system-ui', '-apple-system', 'sans-serif'],
});
