/**
 * Раздел «Варианты повышенной сложности»: 36 вариантов, у каждого 6
 * версий (k.1 — основная, k.2…k.6 — параллельные с другими числами).
 *
 * Версия — 13 записей «шаблон + замороженные параметры». Шаблоны живут
 * в модулях разделов (чертёж, решатель, разбор — движки разделов), здесь
 * только числа. Задача, ответ и решения собираются в браузере
 * (`shablony.ts`): ответов открытым текстом в данных нет.
 */

import type { EgeNo } from '@/lib/variant/types';

/** Задача версии: шаблон и его параметры. */
export interface Zapis {
  /** Идентификатор шаблона: «z07.koren». */
  s: string;
  p: Record<string, unknown>;
}

/** Вариант: шесть версий по 13 задач (по порядку заданий 1–13). */
export interface VariantPV {
  k: number;
  versii: Zapis[][];
  /** Часть 2: шесть версий по 7 задач (14–20); шаблоны — chast2/. */
  chast2?: Zapis[][];
}

/** Шаблон: какой раздел, какой прототип и откуда взят. */
export interface ShablonInfo {
  ege: EgeNo;
  /** Прототип словами — для отчёта и режима разработчика. */
  prototip: string;
  /** Генератор раздела переиспользован или в разделе добавлен новый шаблон. */
  otkuda: 'razdel' | 'novyy';
}

export const VERSIY = 6;
export const VARIANTOV = 36;
