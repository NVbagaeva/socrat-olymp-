/**
 * №20 (варианты 5–6): в куче n камней, двое по очереди берут от 1 до k камней;
 * кто не может сделать ход, проигрывает. Второй выигрывает ⇔ n кратно k + 1.
 * а) Выигрывает ли первый при n₁? б) Наименьшее n > M, при котором выигрывает
 * второй. в) Сколько n от 1 до N, при которых выигрывает второй.
 */

import type { Chast2Zadacha, Shablon2 } from './types';

export interface PW20 {
  k: number;
  n1: number;
  M: number;
  N: number;
}

export function chislaW20(p: PW20) {
  const m = p.k + 1;
  const daA = p.n1 % m !== 0;
  const b = (Math.floor(p.M / m) + 1) * m;
  const v = Math.floor(p.N / m);
  return { m, daA, b, v };
}

