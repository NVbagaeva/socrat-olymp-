/**
 * №17 (варианты 15–16): участок у стены.
 *
 * Прямоугольный участок площадью S примыкает к стене, сетка — по трём
 * сторонам: L(x) = 2x + S/x (x — сторона, перпендикулярная стене).
 * L′ = 2 − S/x² ⇒ x = √(S/2). S = 2k²: x = k, сторона вдоль стены 2k,
 * L_min = 4k.
 */

import type { Chast2Zadacha, Shablon2 } from './types';

export interface PI17 {
  k: number;
  vopros: 'L' | 'x' | 'y';
}

function sobrat(p: PI17): Chast2Zadacha {
  const S = 2 * p.k * p.k;
  const otv = p.vopros === 'L' ? 4 * p.k : p.vopros === 'x' ? p.k : 2 * p.k;
  const vopr =
    p.vopros === 'L'
      ? 'Какой наименьшей длины сетка для этого понадобится? Ответ дайте в метрах.'
      : p.vopros === 'x'
        ? 'Какой длины должна быть каждая сторона участка, перпендикулярная стене, чтобы сетки ушло меньше всего? Ответ дайте в метрах.'
        : 'Какой длины должна быть сторона участка вдоль стены, чтобы сетки ушло меньше всего? Ответ дайте в метрах.';
  return {
    no: 17,
    shablon: 'i17.uchastok',
    uslovie: `Прямоугольный участок площадью $${S}$ м² одной стороной примыкает к стене сарая; три другие стороны нужно огородить сеткой. ${vopr}`,
    risunok: null,
    punkty: [{ bukva: null, podpis: 'Ответ, м', pole: { vid: 'chislo', verno: String(otv) } }],
    otvet: `$${otv}$`,
    reshenie: [
      {
        title: 'Функция',
        lines: [
          `Пусть $x$ м — каждая из сторон, перпендикулярных стене; тогда сторона вдоль стены равна $\\dfrac{${S}}{x}$ м, длина сетки $L(x)=2x+\\dfrac{${S}}{x}$, $x>0$.`,
        ],
      },
      {
        title: 'Производная',
        lines: [
          `$L'(x)=2-\\dfrac{${S}}{x^2}$; $L'(x)=0$ при $x^2=${S / 2}$, $x=${p.k}$. При $x<${p.k}$ производная отрицательна, при $x>${p.k}$ — положительна: $x=${p.k}$ — точка минимума.`,
        ],
      },
      {
        title: 'Ответ',
        lines: [
          `Стороны: $${p.k}$ м и $${2 * p.k}$ м, сетки $L(${p.k})=${4 * p.k}$ м. Ответ: $${otv}$.`,
        ],
      },
    ],
    razbor: [
      { slovo: 'Длина сетки', formula: `L(x)=2x+\\frac{${S}}{x}` },
      { slovo: 'Производная', formula: `L'(x)=2-\\frac{${S}}{x^2}` },
      { slovo: 'Точка минимума', formula: `x=${p.k}` },
      { slovo: 'Ответ', formula: String(otv) },
    ],
    kontrol: { otvet: otv, S },
  };
}

export const I17_UCHASTOK: Shablon2<PI17> = {
  no: 17,
  prototip: 'Оптимизация: участок заданной площади у стены, наименьшая длина ограждения',
  sobrat,
};
