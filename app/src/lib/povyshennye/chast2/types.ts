/**
 * Часть 2 (задания 14–20) в вариантах повышенной сложности.
 *
 * Задача — условие, пункты с полями ответа (у пункта «докажите» поля
 * нет), эталонное решение и уточнения критериев. Формулы — в $…$, их
 * набирает KaTeX при показе. Верные ответы лежат здесь же: в режиме без
 * входа (самопроверка) их проверяет браузер, как часть 1; в работе,
 * выданной учителем, ключ хранится в базе и сверяется на сервере.
 */

import type { Part2No } from '@/content/variantOnline/bally';
import type { Pole } from '@/lib/chast2/sravnenie';

export interface Punkt {
  /** «а», «б», «в» или null — у задачи без пунктов. */
  bukva: string | null;
  /** Поле ответа; null — пункт без ответа (доказательство). */
  pole: Pole | null;
  /** Подпись к полю: «Корни на отрезке», «Множество значений a». */
  podpis?: string;
}

export interface Chast2Zadacha {
  no: Part2No;
  /** Условие с формулами в $…$; абзацы — через \n. */
  uslovie: string;
  punkty: Punkt[];
  /** Верный ответ для показа (как в бланке): «а) …; б) …». */
  otvet: string;
  /** Эталонное решение: шаги с подписью и строками $…$. */
  reshenie: { title: string; lines: string[] }[];
  /** Уточнения критериев (место {u} в kriterii.ts). */
  utochnenie?: Record<string, string>;
}
